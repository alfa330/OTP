"""Ручка знаний для партнёрского ИИ (Syntony): парк + вопрос → фрагменты вики.

Постановка владельца 29.10.2026. У партнёра свой ИИ отвечает водителям, но база
знаний у него слабее нашей. Партнёр присылает таксопарк и вопрос, на который его
ИИ ответить не смог, а мы отдаём фрагменты статей, по которым он составит ответ
сам. Готового ответа не отдаём — только материал.

Что здесь решено и почему:

* **Права — ровно как у оператора техподдержки.** Партнёрский ИИ для нас «тот
  же оператор»: ключ действует от имени должности в отделе (оператор СЗоВ), и
  периметр считают те же функции, что и помощнику вики (wiki/perimeter.py), без
  мастер-ключа и без черновиков. Поменяют права операторов — поменяется и то,
  что получает партнёр; второго списка статей нигде нет.

* **Ключ, а не учётка.** Ключ партнёра (пакет partner_keys) с областью доступа
  «Ручка знаний»: выпускает и отзывает супер-админ во вкладке «Ключи» раздела
  «Сессии»; каждый вызов — строка журнала partner_key_calls (парк, вопрос, что
  отдали, сколько заняло). Учётка сотрудника для этого не заводится: она
  попадала бы в графики, табло и списки людей.

* **Один таксопарк на вызов.** Акции, офисы и телефоны у парков разные, а в
  вики они лежат общими статьями построчно («Парк: Jana», «Все парки, кроме…»).
  Поэтому фрагменты, где назван только чужой парк, отбрасываются, а общие и
  «все парки, кроме…» отдаются как есть — владелец: «если уверенность низкая,
  отдавать чуть больше, ИИ сама догадается» (knowledge_api/parks.py).

* **«Данных нет» — тоже ответ.** Когда фрагментов не нашлось, вопрос уходит в
  «Вопросы операторов» супервайзерам СЗоВ (как отказ помощника), а партнёру
  возвращается status no_data: статью допишут — в следующий раз найдётся.

Состав пакета (ключи, их журнал и админка — в partner_keys/):
    parks.py         парк в тексте: запрошенный, чужой или «все парки»
    perimeter.py     контекст доступа «оператор отдела» без учётки
    search.py        сам поиск: периметр, выборка, справочники, фильтр по парку
    routes.py        внешний вход /api/knowledge/* по заголовку X-Api-Key
"""
