"""Раздел «Обращения» — тикетная система поверх Telegram-групп.

Что решает (ТЗ задачи #133). Оператор больше не ходит руками в рабочие
Telegram-группы (iTaxi, Sapar, «Вопросы-ответы с регионами», согласование
термокоробов) и не сторожит там ответ. Он заводит обращение в iCORE, бот
относит его в нужную группу, ответы сотрудников возвращаются в ту же карточку,
а о выполнении оператор узнаёт мгновенно.

Почему это оформлено как основа CRM, а не как «ещё одна отправка в чат».
В бэклоге лежат задачи #29 (CRM учёта обращений), #28 (фиксация обращения из
корпоративного чата) и #30 (база знаний с фиксацией обращений). Все три
опираются на одни и те же сущности, поэтому они заложены здесь сразу:

    очередь + тематика   каталог маршрутизации (у #29 это «категория/тематика»)
    обращение            номер, статус, приоритет, автор, клиент, срок
    нить                 переписка целиком, в обе стороны, с вложениями
    история              кто создал, кто менял, когда — для отчётности
    источник (source)    'manual' сейчас; 'chat' и 'call' — точки роста #28/#30

Состав пакета:
    schema.py     DDL таблиц crm_*, идемпотентный
    access.py     чистая логика прав (не импортирует ни базу, ни Flask)
    queries.py    SQL-слой поверх готового курсора
    telegram.py   формат сообщения и кнопок (чистые функции, без сети)
    transport.py  вызовы Bot API
    service.py    сценарии, где база встречается с Telegram
    routes.py     Blueprint /api/crm
    bot.py        обработчики ответов и кнопок в группах
"""

