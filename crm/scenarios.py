CITY = 'city'               # город Казахстана из справочника городов

# Почему TAXI_PARK и CITY — отдельные типы, а не CHOICE со списком в options.
#
# CHOICE носит варианты с собой, и это правильно для вариантов-регламента («на
# каком этапе ошибка»): их пять, они меняются вместе с ТЗ. Справочник парков —
# не регламент, а данные: он живёт в таблице и меняется без нас. Список городов
# тоже данные, только на стороне интерфейса. Вписав их в options, мы бы держали
# копию справочника в файле правил и получили бы третье место, где он расходится
# с настоящим, — вместо этого тип говорит ЧЕМ спрашивать, а варианты интерфейс
# берёт у справочника.
#
# Отсюда же и проверка: членство в списке здесь не проверяется. Модуль чистый —
# ни базы, ни сети, — а значит проверить парк ему нечем; список городов пришлось
# бы дублировать на Python. Значение вне списка не открывает никакой двери: это
# описательный текст для специалиста в группе, ровно как было у свободного поля
# до этой правки. Выбор ограничивает интерфейс, а строгость проверок осталась
# такой же, как была.

# Требование к вложению у тематики.
ATTACH_NONE = 'none'
ATTACH_IMAGE = 'image'          # только скриншот
ATTACH_IMAGE_OR_VIDEO = 'media'  # скриншот или видео/запись экрана

