"""Сценарии обращений: тематики, вопросы, обязательные проверки и правила отправки.

Это сердце задачи #160. Смысл ТЗ в одной фразе: оператор НЕ пишет свободный
текст, а проходит готовый сценарий, и обращение уходит в группу только если
все обязательные проверки выполнены. Всё остальное здесь — следствие.

Почему сценарии объявлены данными, а не кодом с if'ами. Их шесть, у каждого до
шестнадцати вопросов и до шести правил блокировки, и правила ссылаются друг на
друга («документы не отображаются» переводит из тематики №2 в №1). В виде
структуры это читается рядом с ТЗ строка в строку, проверяется тестами целиком
и не требует лезть в поток управления, чтобы поправить формулировку.

Почему в Python, а не в таблице с редактором. Ровно как каталог заявок в IT
(IT_TICKET_CATALOG): правила тут не «настройка», а согласованный регламент —
менять их должен тот, кто меняет ТЗ, через ревью, а не мышкой в проде. Таблицу
под переопределение можно добавить позже, схема к этому готова.

Модуль чистый: ни базы, ни Flask, ни сети. Поэтому весь регламент проверяется
юнит-тестами без окружения (tests/test_crm_scenarios.py).
"""

import re

# ─────────────────────────────────────────────────────────────────────────────
# Типы шагов
#
# Тип решает три вещи сразу: чем спрашивать на экране, как проверить ответ и как
# он выглядит в готовом тексте для группы.
# ─────────────────────────────────────────────────────────────────────────────

IIN = 'iin'                 # ИИН водителя: ровно 12 цифр
PERIOD = 'period'           # отчётный период: месяц и год
TEXT = 'text'               # свободная строка (парк, текст ошибки)
LONGTEXT = 'longtext'       # многострочное описание
CHOICE = 'choice'           # один вариант из списка
YESNO = 'yesno'             # да / нет
YESNO_DATE = 'yesno_date'   # да / нет, при «да» — дата

# Третий ответ у «да/нет»: allow_unknown=True добавляет «Неизвестно».
#
# Он не украшение и не «на всякий случай». Часть вопросов оператор физически не
# может проверить сам и опирается на слова водителя: заставлять его выбрать «да»
# или «нет» там, где ответа нет, — значит получать выдуманные данные, и в группу
# уйдёт не «мы не знаем», а уверенное «нет». Поэтому вариант объявляется у
# конкретного вопроса, а не включён у всех: где ответ обязан быть точным,
# уклониться по-прежнему нельзя.
UNKNOWN = 'unknown'
DATETIME = 'datetime'       # дата и время
ATTACHMENT = 'attachment'   # вложение (скриншот / видео)
TAXI_PARK = 'taxi_park'     # таксопарк из справочника парков
CITY = 'city'               # город Казахстана из справочника городов

# Почему TAXI_PARK и CITY — отдельные типы, а не CHOICE со списком в options.
#
# CHOICE носит варианты с собой, и это правильно для вариантов-регламента («на
# каком этапе ошибка»): их пять, они меняются вместе с ТЗ. Справочник парков —
# не регламент, а данные: он живёт в таблице и меняется без нас. Список городов
# тоже данные, только на стороне интерфейса. Вписав их в options, мы бы держали
# копию справочника в файле правил и получили бы третье место, где он расходится
# с настоящим, — вместо этого тип говорит ЧЕМ спрашивать, а варианты интерфейс
# берёт у справочника.
#
# Отсюда же и проверка: членство в списке здесь не проверяется. Модуль чистый —
# ни базы, ни сети, — а значит проверить парк ему нечем; список городов пришлось
# бы дублировать на Python. Значение вне списка не открывает никакой двери: это
# описательный текст для специалиста в группе, ровно как было у свободного поля
# до этой правки. Выбор ограничивает интерфейс, а строгость проверок осталась
# такой же, как была.

# Требование к вложению у тематики.
ATTACH_NONE = 'none'
ATTACH_IMAGE = 'image'          # только скриншот
ATTACH_IMAGE_OR_VIDEO = 'media'  # скриншот или видео/запись экрана

# Чем кончается прохождение сценария.
READY = 'ready'        # можно отправлять в группу
BLOCKED = 'blocked'    # обязательная проверка не выполнена — вернуть оператора к шагу
CLOSE = 'close'        # вопрос решился по ходу: закрыть без сообщения в группу
SWITCH = 'switch'      # это другая тематика — перевести туда
INCOMPLETE = 'incomplete'  # не хватает ответов или вложения

# Метка на обращении (не блокирует отправку, но видна и в группе, и в карточке).
FLAG_MASS_OUTAGE = 'mass_outage'
FLAG_LABELS = {FLAG_MASS_OUTAGE: 'Возможный массовый сбой'}

# [0-9], а не \d: питоновский \d принимает и, например, восточноарабские цифры,
# а такой «ИИН» сохранился бы в обращении и не нашёлся бы потом никаким поиском.
_IIN_RE = re.compile(r'^[0-9]{12}$')
_PERIOD_RE = re.compile(r'^\d{4}-(0[1-9]|1[0-2])$')  # YYYY-MM


def step(key, label, kind, **extra):
    item = {'key': key, 'label': label, 'kind': kind}
    item.update(extra)
    return item


def rule(when, outcome, message, **extra):
    """Правило «когда бот не отправляет запрос».

    when — (ключ шага, значение). Совпало → сработало.
    """
    item = {'when': when, 'outcome': outcome, 'message': message}
    item.update(extra)
    return item


# ─────────────────────────────────────────────────────────────────────────────
# Общие обязательные данные (раздел 2 ТЗ)
#
# ИИН и отчётный период повторяются почти во всех тематиках Sapar, поэтому
# объявлены один раз: разъехавшиеся формулировки одного и того же вопроса —
# первый признак, что регламент начал жить в двух местах.
# ─────────────────────────────────────────────────────────────────────────────

STEP_IIN = step('iin', 'ИИН водителя', IIN,
                hint='Ровно 12 цифр')
STEP_PERIOD = step('period', 'Отчётный период', PERIOD,
                   hint='Месяц и год. Проверьте период сами и приложите скриншот, '
                        'где видно, что комиссия парка снималась именно в нём')
# Было одно свободное поле «Парк или регион», и оно делало двойную работу:
# операторы писали в него то «iTaxi», то «iTaxi, Алматы», то «ай» и «ноль»
# (это реальные значения с прода). Разделили на два вопроса и оба перевели на
# справочники — просьба СЗоВ. Стоят рядом одной строкой: это одно «где», а не
# два разных вопроса, и вместе они занимают столько же места, сколько занимало
# прежнее поле.
STEP_PARK = step('park', 'Таксопарк', TAXI_PARK, half=True)
STEP_CITY = step('city', 'Город', CITY, half=True)

# Устройство и браузер спрашивают две технические тематики. Примеры к ним —
# просьба СЗоВ: без образца операторы пишут «телефон» и «браузер», и в группе
# по такому ответу воспроизвести ошибку нечем. Один пример стоит подсказкой в
# самом поле (виден, пока поле пустое, и исчезает при вводе), полный список —
# под «i», чтобы не занимать место постоянно.
STEP_DEVICE = step('device', 'Устройство и операционная система', TEXT,
                   placeholder='Например: iPhone 15, iOS 18 или ПК, Windows 11',
                   hint='iPhone 15, iOS 18 · Samsung Galaxy S24, Android 15 · ПК, Windows 11')
STEP_BROWSER = step('browser', 'Название браузера', TEXT,
                    placeholder='Например: Google Chrome, Safari, Яндекс Браузер',
                    hint='Google Chrome · Safari · Яндекс Браузер')


