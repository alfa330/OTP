_MONTHS = ('январь', 'февраль', 'март', 'апрель', 'май', 'июнь', 'июль',
           'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь')


def _sapar_conditions(snapshot):
    documents = snapshot.get('documents') or []
    return {
        'month_not_ready': snapshot.get('month_ready') is False,
        'no_documents': not documents,
        'all_signed': bool(documents) and all(d.get('signed') for d in documents),
        'has_documents': bool(documents),
    }


def sapar_period_text(snapshot):
    month, year = snapshot.get('month'), snapshot.get('year')
    try:
        return '%s %s' % (_MONTHS[int(month) - 1], int(year))
    except (TypeError, ValueError, IndexError):
        return 'выбранный период'


def sapar_open_period_hint(snapshot):
    """Подсказка про период, который подписывают сейчас. Пусто — если нечего сказать.

    Главная путаница этой предпроверки: «отчётный период» — это месяц, ЗА
    который документы, а водитель называет месяц, В КОТОРОМ он их ждёт.
    Документы за июль приходят в августе, и «за август документов нет» звучит
    как поломка, пока не сказано, что сейчас подписывают июль.
    """
    period = (snapshot or {}).get('open_period')
    if not period:
        return ''
    text = ' Сейчас подписываются документы за %s' % sapar_period_text(period)
    documents = period.get('documents') or []
    if documents:
        statuses = ITEM_SEP.join(dict.fromkeys(
            d.get('status_label') or 'статус неизвестен' for d in documents))
        return text + (' — у водителя они есть (%s). Уточните, за какой отчётный '
                       'период он ждёт документы.' % statuses)
    return text + ' — у водителя их там тоже нет.'


def sapar_statuses_text(snapshot):
    """Статусы документов одной строкой, без повторов и в порядке появления."""
    seen, out = set(), []
    for document in snapshot.get('documents') or []:
        label = document.get('status_label') or 'статус неизвестен'
        if label not in seen:
            seen.add(label)
            out.append(label)
    return ITEM_SEP.join(out) if out else 'документов нет'


def sapar_verdict(scenario_key, snapshot):
    """Что предпроверка Sapar говорит про обращение.

    Возвращает {'outcome': …, 'message': …, 'switch_to': …}. PASS означает
    «Sapar ничего не решил, продолжаем интервью» — и это же ответ, когда Sapar
    недоступен: считать молчание сервиса за «документов нет» нельзя, по такому
    выводу обращение закрыли бы зря.
    """
    rules = SAPAR_PRECHECK.get(str(scenario_key or ''))
    if not rules or not (snapshot or {}).get('available'):
        return {'outcome': PASS, 'message': None, 'switch_to': None}

    conditions = _sapar_conditions(snapshot)
    for name, rule_item in rules:
        if not conditions.get(name):
            continue
        outcome, template = rule_item[0], rule_item[1]
        if not template:
            return {'outcome': outcome, 'message': None, 'switch_to': None}
        message = template.format(period=sapar_period_text(snapshot),
                                  statuses=sapar_statuses_text(snapshot),
                                  open_hint=sapar_open_period_hint(snapshot))
        return {'outcome': outcome, 'message': message,
                'switch_to': rule_item[2] if len(rule_item) > 2 else None}
    return {'outcome': PASS, 'message': None, 'switch_to': None}


def sapar_needed(scenario_key):
    """Есть ли у тематики что спрашивать у Sapar. Нужно интерфейсу и роутам."""
    return str(scenario_key or '') in SAPAR_PRECHECK


def sapar_entry_verdict(queue_code, snapshot):
    """Что проверка по ИИН решила ДО выбора категории (инструкция #230, §2–§3).

    Три исхода вместо прежних пяти, потому что решение здесь одно: открывать
    категории или вести оператора по «документов нет».

      close        — документов за месяц нет ни у кого: месяц ещё не закрыт,
                     обращение не нужно вовсе;
      documents    — «Есть документы за отчётный период», открываем категории;
      no_documents — «Нет документов. Документы не поступили», ведём в §3;
      unknown      — Sapar не ответил. Решать нечем, поэтому показываем ВСЕ
                     категории, включая «Документы не поступили»: считать
                     молчание сервиса за «документов нет» нельзя.
    """
    entry = entry_for_queue(queue_code)
    if not entry:
        return {'outcome': ENTRY_UNKNOWN, 'message': None, 'scenario': None}
    if not (snapshot or {}).get('available'):
        return {'outcome': ENTRY_UNKNOWN, 'message': None, 'scenario': None}

    conditions = _sapar_conditions(snapshot)
    if conditions['month_not_ready']:
        return {
            'outcome': CLOSE,
            'message': _MONTH_NOT_READY[1].format(
                period=sapar_period_text(snapshot),
                statuses=sapar_statuses_text(snapshot),
                open_hint=sapar_open_period_hint(snapshot)),
            'scenario': None,
        }
    if conditions['no_documents']:
        return {
            'outcome': ENTRY_NO_DOCUMENTS,
            # Подсказка про открытый период здесь особенно нужна: «за август
            # документов нет» звучит поломкой, пока не сказано, что сейчас
            # подписывают июль.
            'message': (ENTRY_NO_DOCUMENTS_TEXT + '.'
                        + sapar_open_period_hint(snapshot)).strip(),
            'scenario': entry['no_documents'],
        }
    return {
        'outcome': ENTRY_DOCUMENTS,
        'message': '%s (%s)' % (ENTRY_DOCUMENTS_TEXT, sapar_statuses_text(snapshot)),
        'scenario': None,
    }


def entry_category_verdicts(queue_code, snapshot):
    """Что предпроверка говорит про каждую категорию входа.

    Считается один раз вместе с самой проверкой и уезжает в интерфейс целиком.
    Иначе выбор категории стоил бы ещё одного запроса в Sapar за тем же самым
    снимком — а правила у категорий свои: «документы уже подписаны» закрывает
    ошибку подписания, а на «проверить статус» просто отвечает.
    """
    entry = entry_for_queue(queue_code)
    if not entry:
        return {}
    return {key: sapar_verdict(key, snapshot) for key in entry['categories']}


