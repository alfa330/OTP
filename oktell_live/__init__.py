"""Данные Oktell с VM шлюза: то, что читает из базы коннектор `cdr_bridge/oktell_connector.py`.

Зачем
-----
Портал читал базу Oktell через мост — HTTP-прокси `/query`, выставленный наружу из
корпоративной сети, который исполнял любой присланный SQL. Мост чужой и хрупкий: 10.11.2026 он
лёг в 16:32, и табло, отбивка и выгрузки остались без данных. VM шлюза — наша, стоит в той же
сети, что база Oktell, и уже носит порталу «Касания», живые звонки АТС и автоинформатор. Теперь
она носит и Oktell: коннектор читает базу сам, учёткой только на чтение.

Две дороги
----------
  * Снимок «Табло СЗоВ · Линия» коннектор снимает сам, раз в несколько секунд, и присылает
    готовые строки (`store.py`). Табло берёт их, пока они свежие
    (`bot_schedule2._szov_wallboard_fetch_snapshot`).
  * Остальные запросы портала к базе Oktell — отбивка линии, разбор перерывов, выгрузки статусов
    и звонков, биллинг, выборка звонков на оценку — исполняются по требованию (`jobs.py`):
    портал кладёт задание в очередь, исполнитель коннектора забирает его длинным опросом и
    приносит строки (`bot_schedule2._oktell_query`).

Мост Oktell остаётся запасным путём: когда коннектор молчит или за запрос не взялся.

Защита та же, что у остальных жителей шлюза: соединение всегда открывает VM (входящих портов
нет), каждый запрос подписан Ed25519 (`cdr/agent_auth.py`, ключи `CDR_AGENT_KEYS`), а текст
запроса к базе коннектор строит сам — из каталога `cdr/oktell_datasets.py` в своём образе. От
портала ему приходят имя набора и параметры (даты, числа, идентификаторы, цифры номеров), но не
текст SQL.

Состав пакета
-------------
    store.py   последний снимок табло — в памяти процесса; свежесть, параметры, рубильник
    jobs.py    очередь запросов по требованию — в памяти процесса; отказы и рубильник
    routes.py  Blueprint /api/oktell_live: ручки коннектора (снимок и задания)
"""

