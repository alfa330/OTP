"""Раздел «Коды 2FA» — коды Google Authenticator маркетингу с подтверждением главы (задача #373).

Постановка владельца 27.10.2026: «раздел для выдачи кодов и настройки доступов, каким
сотрудникам можно отправлять… когда человек запрашивает код, уведомление приходит главе
маркетинга, и он просто подтверждает, и код отправляется, так же время, после которого код
будет недействителен». ТЗ постановщика (бот на отдельном сервере) владелец заменил разделом
портала; из ТЗ взято только то, без чего поток не работает: «Отклонить», запрос сгорает через
10 минут, при остатке меньше 10 секунд — следующий код, «Код не подошёл» 3 минуты после
подтверждения, журнал. «Доступ на час», причины, резервного подтверждающего, лимит запросов,
выгрузку и недельную сводку владелец не выбрал — их нет намеренно.

Как это работает. Google Authenticator кодов не получает: он считает их сам из секретного
ключа и времени (RFC 6238). Ключ аккаунта лежит здесь зашифрованным, и сервер считает те же
6 цифр. Поток:

    сотрудник   «Запросить код» в разделе             → запрос ждёт подтверждения
    глава       кнопка в Telegram или в разделе       → первое нажатие решает
    сотрудник   код и время действия в Telegram       → цифры стираются через 60 с

Кто что делает:

    глава маркетинга   подтверждает и отклоняет запросы, ведёт аккаунты и доступы, журнал
    супер-админ        ведёт аккаунты и доступы, журнал — подтверждать не может
    сотрудник с доступом  запрашивает коды своих аккаунтов

Состав пакета (разделение то же, что у thermoboxes/ и discipline/):
    totp.py      расчёт кода — ни базы, ни сети
    otpauth.py   разбор QR: otpauth:// и экспорт Google Authenticator
    crypto.py    шифрование ключей (AES-256-GCM, ключ из окружения)
    access.py    чистая логика прав
    rules.py     сроки, подписи, тексты сообщений — ни базы, ни сети
    schema.py    DDL, идемпотентный
    queries.py   SQL поверх готового курсора
    service.py   процесс: запрос, решение, повторный код, сроки
    telegram.py  вызовы Bot API (отправить, править, стереть)
    timer.py     будильник сроков — без фонового опроса
    routes.py    Blueprint /api/twofa
"""

