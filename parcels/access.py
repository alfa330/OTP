"""Права раздела «Посылки». Чистая логика: ни базы, ни Flask.

Модуль намеренно не импортирует ни database, ни flask — так его можно
импортировать в тестах напрямую (импорт database открывает пул к боевой базе,
та же причина, что у crm/access.py и wiki/__init__.py).

Роли из ТЗ #240 ложатся на портал так:

    фронт-офисы (front_office)   заводят карточки, ведут статус, правят
    глава фронт-офисов           то же, плюс удаление записи (01.09.2026)
    СЗоВ (szov)                  читают и ищут — «операторам нет необходимости
                                 давать возможность редактировать записи»
    глобальный админ             то же, что фронт-офис, плюс удаление
    тренер                       в раздел не пускается вовсе

Почему периметр — ОТДЕЛ, а не роль. Посылку принимает тот, кто сидит в офисе, а
ищет её тот, кому позвонил водитель; ни то, ни другое не зависит от того,
оператор человек или супервайзер. Роль внутри отдела здесь значения не имеет —
ровно как в «Обращениях».

Граница «глава отдела ≠ глобальный админ» — действующая семантика портала:
назначение главой ЗАМЕНЯЕТ базовую роль и режет периметр своим отделом.
"""

# Роли, которые вообще существуют в портале.
_KNOWN_ROLES = ('super_admin', 'admin', 'sv', 'supervisor', 'trainer', 'operator', 'trainee')

# ─── Кто пускается в раздел ───────────────────────────────────────────────────
#
# Два отдела с разными правами на одни и те же записи. Списка id нет и не будет:
# отдел — это и есть периметр.
WRITE_DEPARTMENT_CODE = 'front_office'   # заводят и ведут посылки
READ_DEPARTMENT_CODE = 'szov'            # ищут и читают

SECTION_DEPARTMENT_CODES = (WRITE_DEPARTMENT_CODE, READ_DEPARTMENT_CODE)

# Тренер видит «всё» в других разделах, но телефоны живых водителей не его дело
# (то же решение, что закрыло ему «Обращения»).
_SECTION_EXCLUDED_ROLES = ('trainer',)

_ADMIN_ROLES = ('super_admin', 'admin')


def normalize_role(role):
    value = str(role or '').strip().lower()
    return value if value in _KNOWN_ROLES else 'operator'


def _codes(values):
    return {str(code).strip().lower() for code in (values or []) if code}


def _own_code(ctx):
    return str(ctx.get('department_code') or '').strip().lower()


def is_department_head(ctx):
    return bool(ctx.get('headed_department_ids'))


def is_global_admin(ctx):
    """Глобальный админ — тот, кто не привязан к одному отделу.

    super_admin — всегда. admin — только пока он не назначен главой отдела:
    назначение главой заменяет базовую роль, иначе глава фронт-офисов правил бы
    всё подряд по всему порталу, а глава СЗоВ получил бы запись в реестр.
    """
    role = normalize_role(ctx.get('role'))
    if role == 'super_admin':
        return True
    return role == 'admin' and not is_department_head(ctx)


def _belongs_to(ctx, code):
    """Человек в этом отделе — своим членством или как его глава."""
    if code in _codes(ctx.get('headed_department_codes')):
        return True
    return _own_code(ctx) == code


def can_open_section(ctx):
    """Пускать ли пользователя в раздел вообще.

    Проверяется на КАЖДОМ роуте, а не только в меню: спрятанный пункт — это не
    доступ, раздел открывается и прямым адресом ?view=parcels.
    """
    if is_global_admin(ctx):
        return True
    if normalize_role(ctx.get('role')) in _SECTION_EXCLUDED_ROLES:
        return False
    return any(_belongs_to(ctx, code) for code in SECTION_DEPARTMENT_CODES)


def can_edit(ctx):
    """Заводить карточки, править их и менять статус.

    Только фронт-офисы и глобальный админ. СЗоВ сюда не попадает НИ В КАКОЙ
    роли — прямая формулировка ТЗ: «операторам нет необходимости давать
    возможность редактировать записи». Супервайзер СЗоВ тоже не попадает: он не
    видел посылку своими глазами, а карточка — свидетельство о вещи, которая
    лежит в конкретном офисе.

    Внутри фронт-офисов границы по городам нет: реестр общий («после сохранения
    запись появляется в общем реестре»), а подменять коллегу из соседнего города
    приходится каждый отпуск.
    """
    if is_global_admin(ctx):
        return True
    if normalize_role(ctx.get('role')) in _SECTION_EXCLUDED_ROLES:
        return False
    return _belongs_to(ctx, WRITE_DEPARTMENT_CODE)


def can_delete(ctx):
    """Удалить карточку целиком — глава фронт-офисов и глобальный админ.

    Ошибочно заведённую посылку менеджер региона не удаляет, а исправляет:
    удаление уносит с собой историю, а по ней потом отвечают на вопрос «куда
    делась коробка». То же правило, что у обращений.

    Глава отдела добавлен по просьбе владельца 01.09.2026 («это может делать
    только рук отдела и Админ»). До неё удалять не мог и он: назначение главой
    ЗАМЕНЯЕТ базовую роль (is_global_admin), поэтому единственный глава
    фронт-офисов — сам с ролью admin — проваливался мимо обоих условий.

    Глава СЗоВ сюда НЕ входит, и это не оплошность: его отдел не правит реестр
    ни в какой роли (can_edit), а право стереть запись вместе с историей у того,
    кому нельзя исправить в ней опечатку, — не «строже», а бессмысленно.
    Периметр тот же, что у записи: отдел, который эти карточки и ведёт.
    """
    if is_global_admin(ctx):
        return True
    return is_department_head(ctx) and WRITE_DEPARTMENT_CODE in _codes(
        ctx.get('headed_department_codes'))


def requires_sensitive_qr(ctx):
    """Нужно ли подтвердить сессию QR-кодом, прежде чем раздел откроется.

    Оператору — да, обоим отделам (прямое требование постановки: «раздел
    открывается только после сканирования QR как в разделах Вики и Обращения»).
    В карточке ФИО и телефон живого водителя, его машина и парк — это те же
    персональные данные, ради которых закрыты «Обращения».

    Ключ тот же, что у «Обращений», «Вики» и «Моих оценок» (bot_schedule2:
    sensitive-access): QR генерирует сам сотрудник, подтверждает админ или
    супервайзер, доступ живёт до конца ЭТОЙ сессии. Своего второго ключа раздел
    не заводит намеренно — два разных QR на один экран человек не различит.

    Кого гейт не касается: главы отдела и глобального админа — им подтверждать
    доступ не у кого, а также супервайзера (он и подтверждает).

    Незнакомая роль подпадает под гейт: normalize_role сводит её к 'operator', и
    это правильная сторона ошибки — закрыто, а не открыто.
    """
    if is_global_admin(ctx) or is_department_head(ctx):
        return False
    return normalize_role(ctx.get('role')) == 'operator'


def default_city(ctx):
    """Город, который подставляется в форму сам.

    «У менеджера, у которого указан город, город выбран автоматом» — просьба
    владельца. Город берётся из карточки сотрудника (`users.city`, поле есть
    только у фронт-офисов) и НЕ является ограничением: менеджер вправе завести
    посылку в любом городе, просто свой не приходится выбирать каждый раз.

    У читающего (СЗоВ) города нет и подставлять нечего — вернём None, форму он
    всё равно не открывает.
    """
    if not can_edit(ctx):
        return None
    city = str(ctx.get('city') or '').strip()
    return city or None


def capabilities(ctx):
    """Сводка для фронта: раздел рисует кнопки по ней, а не по роли.

    Одно место правды: правило меняется здесь, а не в трёх местах интерфейса.
    """
    return {
        'can_open': can_open_section(ctx),
        'can_edit': can_edit(ctx),
        'can_delete': can_delete(ctx),
        'requires_qr': requires_sensitive_qr(ctx),
        'is_global_admin': is_global_admin(ctx),
        'is_department_head': is_department_head(ctx),
        'default_city': default_city(ctx),
    }
