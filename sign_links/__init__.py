"""Раздел «Ссылка на подписание».

Оператор СЗоВ или менеджер фронт-офиса вводит ИИН водителя, сервер ходит в
гостевой генератор Sapar и отдаёт ссылку на подписание документов через
eGov Mobile. Каждый запрос — строка журнала для админов.

Зачем это внутри портала, а не закладкой на страницу вендора. Страница
генератора публичная: любой, кто знает адрес, вводит любой ИИН и получает
ссылку — без следа, кто и зачем. У нас ИИН вводится в свой раздел за QR-гейтом,
адрес генератора наружу не уходит вовсе (оператор до него не добирается), а
журнал отвечает на вопрос «кто и когда запрашивал ссылку по этому ИИН».

Состав пакета — тот же, что у «Посылок» и «Чатов водителей»:

    access.py      кто что может (чистая логика, без базы и Flask)
    iin.py         проверка ИИН: 12 цифр, дата рождения, контрольная сумма
    sapar_link.py  сеть: форма генератора и разбор её ответа
    schema.py      DDL журнала
    queries.py     SQL
    routes.py      Flask Blueprint /api/sign_links
"""
