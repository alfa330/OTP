# -*- coding: utf-8 -*-
"""Права раздела «Лиды OLX». Чистая логика: ни базы, ни Flask.

Модуль намеренно не импортирует ни database, ни flask — так его можно
импортировать в тестах напрямую (импорт database открывает пул к боевой базе;
та же причина у parcels/access.py, crm/access.py и wiki/__init__.py).

Кому раздел нужен
-----------------
Работу, которую забирает робот, сегодня делает маркетолог: он обходит девять
кабинетов OLX и заводит сделки руками. Он же первым заметит, что робот
замолчал, — значит журнал и состояние кабинетов нужны прежде всего ему.
Разбирают заведённые сделки менеджеры отдела продаж, и их руководителю нужна
та же сводка, чтобы видеть поток заявок.

    глобальный админ              всё, включая подключение кабинетов
    глава «Маркетинга» и «ОП»     журнал, сводка, состояние кабинетов
    сотрудник «Маркетинга»        то же, но БЕЗ ответа кандидату
    остальные                     раздела не видят

Периметр — ОТДЕЛ, а не роль: набор `('op', 'marketing')` уже используется в
портале для наблюдателей «Оценок ИИ» (`AI_QA_HEAD_DEPARTMENT_CODES` в
bot_schedule2.py и в src/App.jsx), и заводить второй, свой, список отделов под
ту же аудиторию значило бы гарантированно разойтись с первым.

Подключение кабинета (согласие владельца в браузере, выдача токенов) отдано
ТОЛЬКО глобальному админу: это выдача доступа к переписке девяти корпоративных
кабинетов, и решение о ней не отдельского уровня.
"""

_ADMIN_ROLES = ('super_admin', 'admin')

# Отделы, чьи главы видят раздел. Тот же состав, что у наблюдателей «Оценок ИИ»,
# минус СЗоВ: лиды с OLX к службе заботы о водителях отношения не имеют.
SECTION_HEAD_DEPARTMENT_CODES = ('op', 'marketing')

# Отдел, рядовые сотрудники которого видят раздел наравне с главой. Ровно тот
# маркетолог, о котором написана шапка модуля: работу, которую забрал робот, он
# делал руками и первым заметит, что робот замолчал.
#
# Отдельная константа, а не строка в SECTION_HEAD_DEPARTMENT_CODES: тот набор
# отвечает на вопрос «чьи ГЛАВЫ видят раздел» и сверяется с фронтом дословно
# (OLX_LEADS_HEAD_DEPARTMENT_CODES в src/App.jsx). Дописав туда 'marketing'
# второй раз, мы бы заодно открыли раздел рядовым отдела продаж.
SECTION_MEMBER_DEPARTMENT_CODE = 'marketing'

# Должность рядового сотрудника «Маркетинга». Проверяем её ВМЕСТЕ с отделом:
# одного отдела мало — под ним же числятся люди, заведённые до появления
# должности обычными операторами, и раздел им не выдавали.
SECTION_MEMBER_ROLE = 'marketing_manager'


def _codes(values):
    return {str(code).strip().lower() for code in (values or []) if code}


def is_global_admin(ctx):
    """Админ портала — но НЕ глава отдела.

    Назначение главой отдела ЗАМЕНЯЕТ базовую роль и режет периметр своим
    отделом — действующая семантика портала, та же проверка в соседних разделах.
    """
    if not ctx:
        return False
    if ctx.get('headed_department_ids'):
        return False
    return str(ctx.get('role') or '').strip().lower() in _ADMIN_ROLES


def heads_section_department(ctx):
    """Глава отдела, которому раздел положен."""
    if not ctx or not ctx.get('headed_department_ids'):
        return False
    return bool(_codes(ctx.get('headed_department_codes'))
                & set(SECTION_HEAD_DEPARTMENT_CODES))


def works_in_section_department(ctx):
    """Рядовой сотрудник «Маркетинга» — тот, кому раздел и нужен по существу."""
    if not ctx or ctx.get('headed_department_ids'):
        return False
    if str(ctx.get('role') or '').strip().lower() != SECTION_MEMBER_ROLE:
        return False
    return (str(ctx.get('department_code') or '').strip().lower()
            == SECTION_MEMBER_DEPARTMENT_CODE)


def can_view(ctx):
    """Пускать ли в раздел вообще."""
    return bool(is_global_admin(ctx)
                or heads_section_department(ctx)
                or works_in_section_department(ctx))


def can_manage_cabinets(ctx):
    """Подключать кабинеты и выдавать токены. Только глобальный админ."""
    return bool(is_global_admin(ctx))


def can_reply(ctx):
    """Писать кандидату в чат OLX из раздела.

    Отдельной функцией это вынесено намеренно. Отвечать кандидату — это
    действие НАРУЖУ, от лица компании и в переписке с живым человеком, тогда как
    остальное в разделе только чтение.

    Здесь периметр и разошёлся с can_view (04.09.2026): рядовой сотрудник
    «Маркетинга» раздел теперь видит, но пишет ли он кандидату от лица компании
    — решение не того же уровня, что «показать журнал». Владелец просил открыть
    раздел, а не выдать право переписки, поэтому право осталось у тех, у кого
    было: глобальный админ и главы «Маркетинга» и «ОП».
    """
    return bool(is_global_admin(ctx) or heads_section_department(ctx))


def capabilities(ctx):
    """Что клиенту рисовать. Одна форма ответа на все роли — фронт не гадает."""
    return {
        'can_view': can_view(ctx),
        'can_reply': can_reply(ctx),
        'can_manage_cabinets': can_manage_cabinets(ctx),
    }
