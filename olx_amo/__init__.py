"""Робот переноса откликов из чатов OLX в amoCRM.

Задача #223 (Сейтақын Төлеген). До этого модуля маркетолог руками обходил девять
кабинетов OLX, открывал раздел «Чат», копировал телефон из текста отклика,
приводил его к единому виду, заводил сделку в amoCRM, ставил тег кабинета и
ответственного. Девять кабинетов — это часы работы, и главное, это задержка:
отклик, оставленный ночью или в час пик, доезжал до CRM через несколько часов, а
кандидат за это время успевал откликнуться конкурентам.

Что делает робот:

    чаты 9 кабинетов OLX  →  сделка в воронке «Отдел продаж», этап «Новая заявка»
                             название = телефон в формате 77XXXXXXXXX
                             тег кабинета, ответственный «Администратор»
                             контакт с тем же номером в поле «Раб. тел.»

    обращение без номера  →  заготовленный ответ с телефоном ЭТОГО кабинета

Состав пакета (разделение то же, что у parcels/ и crm/):

    cabinets.py   справочник девяти кабинетов: теги, телефоны, тексты ответов
    phones.py     приведение номера к 77XXXXXXXXX и поиск номера в тексте
    schema.py     DDL журнала и учёток, идемпотентный
    olx_client.py клиент OLX Partner API: токены, треды, сообщения
    amo_writer.py запись в amoCRM: сделка + контакт + тег + ответственный
    service.py    сам цикл: опросить кабинеты, разобрать новое, отправить
    queries.py    SQL поверх готового курсора
    routes.py     Blueprint /api/olx_amo — журнал, сводка, состояние кабинетов
    access.py     чистая логика прав, без базы и без Flask

Почему журнал — отдельная таблица, а не строчка в логе. ТЗ требует по каждому
обращению хранить кабинет, идентификатор чата, время отклика, время создания
сделки, номер ДО и ПОСЛЕ нормализации, тег, результат и текст ошибки, и уметь
выгрузить это за произвольный период. Такое из текстового лога не достать, а
из него же считается ежедневная сводка и контроль SLA.

Почему учётки кабинетов лежат в базе, а не только в окружении. OLX выдаёт
токен на кабинет, и токен этот живёт час, а обновляется по refresh_token,
который приходит один раз и меняется при каждом обновлении. Держать такое в
переменных окружения нельзя: их правит человек и перезапуск, а токен меняется
сам каждый час. В окружении остаётся только то, что выдал OLX и что человек
вводит однажды — логин, пароль, ключ приложения.
"""

