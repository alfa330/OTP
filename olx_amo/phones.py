# -*- coding: utf-8 -*-
"""Приведение номера к формату 77XXXXXXXXX и поиск номера в тексте обращения.

Правила — раздел 3 ТЗ задачи #223, дословно:

    как написал кандидат      как заносится      что делаем
    +7 775 702 51 44          77757025144        убрать «+», пробелы, скобки, дефисы
    +77757025144              77757025144        убрать «+»
    87757025144               77757025144        первую «8» заменить на «7»
    8 (775) 702-51-44         77757025144        убрать форматирование, «8» → «7»
    77757025144               77757025144        уже правильно
    7757025144 (10 цифр)      77757025144        добавить «7» в начало

Итог обязан лечь в маску `77` + девять цифр. Не лёг — обращение НЕ теряем:
ТЗ прямо требует всё равно завести лид и пометить его как требующий ручной
проверки. Поэтому `scan()` возвращает не только распознанные номера, но и
отвергнутых кандидатов — по ним видно разницу между «номера в обращении нет»
(тогда кандидату уходит заготовленный ответ) и «номер есть, но кривой» (тогда
заводится лид с пометкой).

Почему разбор текста, а не поле API. В OLX номер приезжает внутри текста
сообщения, свободной строкой: отдельного поля с телефоном кандидата в чате нет.
"""

import re

# Разделители, которые встречаются в живых номерах: пробельные (в том числе
# неразрывный и типографские), скобки, точка и дефис во всех начертаниях —
# обычный и юникодные. Юникодный дефис не экзотика: именно такой приехал в
# присланной таблице доступов, и в сообщениях кандидатов он тоже попадается.
# «Плюса» здесь нет намеренно — он допускается только в самом начале номера,
# это отдельный `\+?` в шаблоне ниже.
_SEPARATORS = r"\s ()\-‐‑‒–—. - "

# Кандидат в номер: цифра, дальше цифры и разделители, дальше цифра. Границы —
# чтобы не откусить половину длинного числа. «+» разрешён только в начале.
_CANDIDATE_RE = re.compile(
    r"(?<![0-9])\+?[0-9][0-9%s]{6,24}[0-9](?![0-9])" % _SEPARATORS)

# Сколько цифр должно быть в куске текста, чтобы считать его ПОПЫТКОЙ написать
# телефон. Ниже порога — это дата, сумма, номер машины или год, и молчать о нём
# правильно. Верхняя граница отсекает склеенные подряд числа.
_MIN_DIGITS = 9
_MAX_DIGITS = 15

_VALID_RE = re.compile(r"^77[0-9]{9}$")


def digits_only(value):
    """Только цифры. `None` и не-строки превращаются в пустую строку."""
    if not value:
        return ""
    return re.sub(r"[^0-9]", "", str(value))


def normalize(value):
    """Номер в формате 77XXXXXXXXX или None, если он под маску не подходит.

    Ничего не «чинит» сверх правил ТЗ: длина не та или код чужой — это отказ,
    а не повод угадывать. Решение, что делать с отказом, принимает вызывающий.
    """
    raw = digits_only(value)
    if not raw:
        return None

    if len(raw) == 11 and raw[0] == "8":
        raw = "7" + raw[1:]
    elif len(raw) == 10 and raw[0] == "7":
        # Кандидат опустил код страны: 775 702 51 44 → 7 775 702 51 44.
        raw = "7" + raw

    return raw if _VALID_RE.match(raw) else None


def is_normalized(value):
    """Уже в целевом формате? Проверка для стражей и для тестов."""
    return bool(value) and bool(_VALID_RE.match(str(value)))


class Scan(object):
    """Что нашлось в тексте обращения.

    `phones`   — распознанные номера в порядке появления, без повторов;
    `raw`      — как они были НАПИСАНЫ, теми же местами списка;
    `rejected` — куски, похожие на телефон, но не подошедшие под маску;
    `own_lines`— наши собственные номера линий, встреченные в тексте.

    Исходное написание хранится не для красоты: раздел 7 ТЗ требует держать в
    журнале номер И ДО, И ПОСЛЕ нормализации. Без `raw` спорный случай «почему
    номер распознался вот так» разобрать нечем — в журнале лежали бы две
    одинаковые колонки.
    """

    __slots__ = ('phones', 'raw', 'rejected', 'own_lines')

    def __init__(self, phones, raw, rejected, own_lines):
        self.phones = phones
        self.raw = raw
        self.rejected = rejected
        self.own_lines = own_lines

    @property
    def first(self):
        return self.phones[0] if self.phones else None

    @property
    def first_raw(self):
        """Как кандидат написал тот номер, который мы взяли."""
        return self.raw[0] if self.raw else None

    @property
    def has_phone(self):
        return bool(self.phones)

    @property
    def needs_manual_review(self):
        """Номер писали, но он не читается — лид завести, но пометить."""
        return not self.phones and bool(self.rejected)

    def __repr__(self):
        return '<Scan phones=%r raw=%r rejected=%r own=%r>' % (
            self.phones, self.raw, self.rejected, self.own_lines)


def scan(text, own_lines=()):
    """Разобрать текст обращения.

    `own_lines` — телефоны наших же линий (см. `cabinets.LINE_PHONES`). Их надо
    выкинуть: робот сам пишет кандидату «позвоните по номеру 8XXXXXXXXXX», и
    кандидат нередко отвечает цитатой. Сделка с номером собственной линии — это
    мусор в воронке, и по нему потом никто не дозвонится до кандидата.
    """
    own = set(own_lines or ())
    phones, raw_forms, rejected, seen_own = [], [], [], []
    seen = set()

    for match in _CANDIDATE_RE.finditer(text or ""):
        chunk = match.group(0)
        raw = digits_only(chunk)
        if not (_MIN_DIGITS <= len(raw) <= _MAX_DIGITS):
            continue

        number = normalize(raw)
        if number is None:
            if chunk not in rejected:
                rejected.append(chunk)
            continue
        if number in own:
            if number not in seen_own:
                seen_own.append(number)
            continue
        if number not in seen:
            seen.add(number)
            phones.append(number)
            # Сохраняем кусок ТЕКСТА, а не приведённые цифры: в журнал должно
            # лечь то, что человек написал, вместе с его пробелами и скобками.
            raw_forms.append(chunk.strip())

    return Scan(phones, raw_forms, rejected, seen_own)
