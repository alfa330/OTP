"""Права раздела «Чаты водителей». Чистая логика: ни базы, ни Flask.

Модуль намеренно не импортирует ни database, ни flask — так его можно
импортировать в тестах напрямую (импорт database открывает пул к боевой базе;
та же причина, что у parcels/access.py и crm/access.py).

Постановка #271 задаёт периметр тремя фразами: «этот раздел будет доступен в
отделе СЗоВ», «чат-менеджерам он виден не будет», «о доступе для операторов
сделать QR-доступ». Ниже — как они ложатся на портал.

    оператор СЗоВ, стажёр СЗоВ   ищут чат, открывают, жмут «Передан» — после QR
    супервайзер СЗоВ             то же плюс журнал; QR ему не задают (он его и
                                 подтверждает)
    глава СЗоВ                   то же, что супервайзер
    чат-менеджер СЗоВ            НЕ пускается вовсе
    тренер                       НЕ пускается вовсе
    глобальный админ             всё, включая журнал
    остальные отделы             не пускаются

Почему чат-менеджер исключён, хотя он тоже сотрудник СЗоВ. Раздел существует,
чтобы оператор линии достал переписку и ПЕРЕДАЛ её чат-менеджеру. Чат-менеджер
эту же переписку видит у себя в Chat2Desk — в своём рабочем окне, целиком и без
нашего посредника. Дать ему ещё и наш поиск по любому номеру значило бы открыть
ему чаты коллег, чего в его рабочем инструменте нет: там он видит свои диалоги.
Это прямое требование постановщика, а не наша осторожность.

Почему тренер исключён. То же решение, что закрыло ему «Обращения» и
«Посылки»: телефоны и переписка живых водителей — не его дело.
"""

# Роли, которые вообще существуют в портале.
_KNOWN_ROLES = ('super_admin', 'admin', 'sv', 'supervisor', 'trainer', 'operator', 'trainee')

# Периметр раздела — один отдел. Списка id нет и не будет: отдел и есть периметр.
SECTION_DEPARTMENT_CODE = 'szov'

# Тренер видит «всё» в других разделах, но переписка живых водителей не его дело.
_SECTION_EXCLUDED_ROLES = ('trainer',)

# Модель расчёта направления «Чат менеджер». Именно по ней, а не по id
# направления: направления версионируются (id 69 — лишь текущая версия), и
# переименование направления обнуляет привязку операторов, а модель переживает
# и то, и другое.
CHAT_MANAGER_DIRECTION_MODEL = 'chat_manager'

# Кому гейт задаёт QR-подтверждение. Стажёр включён СОЗНАТЕЛЬНО, в отличие от
# «Посылок» и вики, где он проходит молча (известный незакрытый дефект, см.
# parcels/access.py:requires_sensitive_qr). Здесь на кону не карточка с
# телефоном, а переписка целиком, и «стажёр читает чаты водителей из дома без
# подтверждения» — не та сторона ошибки, на которой стоит оказаться.
_QR_GATED_ROLES = ('operator', 'trainee')

_ADMIN_ROLES = ('super_admin', 'admin')

# ─── Стадия выката ────────────────────────────────────────────────────────────
#
# Пока True — раздел видит ТОЛЬКО супер-админ (решение владельца 03.09.2026,
# на время обкатки). Периметр ниже при этом описан целиком и покрыт тестами:
# открыть раздел отделу СЗоВ — это снять флаг здесь и такой же во фронте
# (`DRIVER_CHATS_ROLLOUT_SUPER_ADMIN_ONLY` в src/App.jsx), а не восстанавливать
# по памяти, кому раздел предназначался.
#
# Флаг, а не удаление правил: раздел уже стоит на проде, и «временно закрыть»
# не должно означать «потерять периметр».
ROLLOUT_SUPER_ADMIN_ONLY = True


def normalize_role(role):
    value = str(role or '').strip().lower()
    return value if value in _KNOWN_ROLES else 'operator'


def _codes(values):
    return {str(code).strip().lower() for code in (values or []) if code}


def _own_code(ctx):
    return str(ctx.get('department_code') or '').strip().lower()


def is_department_head(ctx):
    return bool(ctx.get('headed_department_ids'))


def is_global_admin(ctx):
    """Глобальный админ — тот, кто не привязан к одному отделу.

    super_admin — всегда. admin — только пока он не назначен главой отдела:
    назначение главой ЗАМЕНЯЕТ базовую роль (действующая семантика портала),
    иначе глава Бухгалтерии читал бы переписку водителей.
    """
    role = normalize_role(ctx.get('role'))
    if role == 'super_admin':
        return True
    return role == 'admin' and not is_department_head(ctx)


def is_supervisor(ctx):
    return normalize_role(ctx.get('role')) in ('sv', 'supervisor')


def belongs_to_section_department(ctx):
    """Человек в СЗоВ — своим членством или как его глава."""
    if SECTION_DEPARTMENT_CODE in _codes(ctx.get('headed_department_codes')):
        return True
    return _own_code(ctx) == SECTION_DEPARTMENT_CODE


def is_chat_manager(ctx):
    """Чат-менеджер — по модели расчёта его направления, а не по имени.

    Проверяем ещё и отдел: модель `chat_manager` живёт в СЗоВ, и если такая же
    модель когда-нибудь появится в другом отделе, это будут другие люди с другой
    работой.
    """
    model = str(ctx.get('direction_model') or '').strip().lower()
    if model != CHAT_MANAGER_DIRECTION_MODEL:
        return False
    return _own_code(ctx) == SECTION_DEPARTMENT_CODE


def section_perimeter_allows(ctx):
    """Полное правило периметра — БЕЗ учёта стадии выката.

    Проверяется на КАЖДОМ роуте, а не только в меню: спрятанный пункт — это не
    доступ, раздел открывается и прямым адресом ?view=driver_chats.

    Порядок условий значим. Глобальный админ проходит первым: у него нет отдела,
    и все отдельные проверки ниже он бы провалил. Исключения (тренер,
    чат-менеджер) считаются ДО членства в отделе, иначе чат-менеджер СЗоВ
    прошёл бы по строке «мой отдел — СЗоВ».
    """
    if is_global_admin(ctx):
        return True
    if normalize_role(ctx.get('role')) in _SECTION_EXCLUDED_ROLES:
        return False
    if is_chat_manager(ctx):
        return False
    return belongs_to_section_department(ctx)


def can_open_section(ctx):
    """Пускать ли пользователя в раздел СЕЙЧАС.

    Это периметр плюс стадия выката. Пока `ROLLOUT_SUPER_ADMIN_ONLY` включён,
    раздел видит только супер-админ — решение владельца 03.09.2026 на время
    обкатки. Правило периметра при этом живое и проверенное тестами: открыть
    раздел отделу — это снять один флаг здесь и такой же во фронте, а не
    вспоминать через месяц, кому он вообще предназначался.
    """
    if ROLLOUT_SUPER_ADMIN_ONLY:
        return normalize_role(ctx.get('role')) == 'super_admin'
    return section_perimeter_allows(ctx)


def can_view_journal(ctx):
    """Журнал «кто открывал чаты и кто нажимал «Передан»».

    Постановщик назвал троих: Ару Омарова (СВ СЗоВ), супервайзеры СЗоВ и
    суперадмины. Именного списка id здесь нет намеренно — Ару Омарова и есть
    супервайзер СЗоВ, поэтому правило «СВ этого отдела» покрывает её целиком и
    переживёт как её замену, так и появление второго руководителя. Хардкод id
    ломается ровно в тот день, когда человек меняется, и ломается молча.

    Глава СЗоВ входит: журнал о работе его отдела. Глава другого отдела — нет,
    его в can_open_section уже не пустили.

    Оператор не видит журнал НИКОГДА, даже свой: журнал ведётся ради контроля
    за ним, и «посмотреть, что про меня записано» — это другой продукт.
    """
    if is_global_admin(ctx):
        return True
    if not can_open_section(ctx):
        return False
    if is_department_head(ctx):
        return SECTION_DEPARTMENT_CODE in _codes(ctx.get('headed_department_codes'))
    return is_supervisor(ctx)


def requires_sensitive_qr(ctx):
    """Нужно ли подтвердить сессию QR-кодом, прежде чем раздел откроется.

    Ключ тот же, что у «Вики», «Обращений», «Посылок» и «Моих оценок»
    (bot_schedule2: sensitive-access): QR генерирует сам сотрудник, подтверждает
    админ или супервайзер, доступ живёт до конца ЭТОЙ сессии. Своего второго
    ключа раздел не заводит намеренно — два разных QR на один экран человек не
    различит.

    ЧЕСТНАЯ ГРАНИЦА ЭТОГО МЕХАНИЗМА (сказано постановщику отдельно): QR
    подтверждает человека, а не место. Он не проверяет ни сеть, ни устройство,
    ни город. Требование «из дома нельзя» им НЕ выполняется и выполнено быть не
    может — ни IP офисов в портале нет, ни запретить снимок экрана нельзя.
    Поэтому рядом с гейтом стоит журнал: он отвечает на вопрос «кто открыл и
    что передал», на который QR не отвечает.

    Кого гейт не касается: глобального админа, главы отдела и супервайзера — им
    подтверждать доступ не у кого, а супервайзер его и выдаёт.

    Незнакомая роль подпадает под гейт: normalize_role сводит её к 'operator', и
    это правильная сторона ошибки — закрыто, а не открыто.
    """
    if is_global_admin(ctx) or is_department_head(ctx) or is_supervisor(ctx):
        return False
    return normalize_role(ctx.get('role')) in _QR_GATED_ROLES


def capabilities(ctx):
    """Сводка для фронта: раздел рисует кнопки по ней, а не по роли.

    Одно место правды: правило меняется здесь, а не в трёх местах интерфейса.
    """
    return {
        'can_open': can_open_section(ctx),
        'can_view_journal': can_view_journal(ctx),
        'requires_qr': requires_sensitive_qr(ctx),
        'is_global_admin': is_global_admin(ctx),
        'is_department_head': is_department_head(ctx),
    }
