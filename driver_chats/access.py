"""Права раздела «Чаты водителей». Чистая логика: ни базы, ни Flask.

Модуль намеренно не импортирует ни database, ни flask — так его можно
импортировать в тестах напрямую (импорт database открывает пул к боевой базе;
та же причина, что у parcels/access.py и crm/access.py).

Постановка #271 задаёт периметр тремя фразами: «этот раздел будет доступен в
отделе СЗоВ», «чат-менеджерам он виден не будет», «о доступе для операторов
сделать QR-доступ». Ниже — как они ложатся на портал.

    оператор СЗоВ, стажёр СЗоВ   ищут чат, открывают, жмут «Передан» — после QR
    супервайзер СЗоВ             то же плюс журнал; QR ему не задают (он его и
                                 подтверждает). ВКЛЮЧАЯ СВ чат-менеджеров
    глава СЗоВ (Ару Омарова)     то же, что супервайзер
    чат-менеджер СЗоВ            НЕ пускается (исключение — только рядовые)
    тренер                       НЕ пускается вовсе
    админ портала                НЕ пускается (сужено 08.09.2026)
    супер-админ                  всё, включая журнал
    остальные отделы             не пускаются

Почему чат-менеджер исключён, хотя он тоже сотрудник СЗоВ. Раздел существует,
чтобы оператор линии достал переписку и ПЕРЕДАЛ её чат-менеджеру. Чат-менеджер
эту же переписку видит у себя в Chat2Desk — в своём рабочем окне, целиком и без
нашего посредника. Дать ему ещё и наш поиск по любому номеру значило бы открыть
ему чаты коллег, чего в его рабочем инструменте нет: там он видит свои диалоги.
Это прямое требование постановщика, а не наша осторожность.

Но СУПЕРВАЙЗЕР чат-менеджеров проходит (решение владельца 08.09.2026): «доступ
супервайзерам» он сформулировал по роли, а исключение по направлению касается
рядовых — тех, у кого раздел открыл бы чужие диалоги вместо своих. Супервайзер и
так разбирает работу отдела по чатам коллег, и журнал ведётся в том числе для
него.

Почему тренер исключён. То же решение, что закрыло ему «Обращения» и
«Посылки»: телефоны и переписка живых водителей — не его дело.

Почему админ портала НЕ проходит, хотя в соседних разделах проходит. Владелец
08.09.2026 сузил круг до «линия/основа, супервайзеры, Ару, суперадмины»: роль
`admin` без своего отдела в остальном портале означает «видит всё», а здесь на
кону переписка живых водителей, и пятеро таких админов, числящихся в СЗоВ,
получали бы вместе с разделом ещё и журнал о работе чужого отдела. Глава СЗоВ
при этом проходит своей строкой — назначение главой заменяет базовую роль.
"""

# Роли, которые вообще существуют в портале.
_KNOWN_ROLES = ('super_admin', 'admin', 'sv', 'supervisor', 'trainer', 'operator', 'trainee')

# Периметр раздела — один отдел. Списка id нет и не будет: отдел и есть периметр.
SECTION_DEPARTMENT_CODE = 'szov'

# Тренер видит «всё» в других разделах, но переписка живых водителей не его дело.
_SECTION_EXCLUDED_ROLES = ('trainer',)

# Модель расчёта направления «Чат менеджер». Именно по ней, а не по id
# направления: направления версионируются (id 69 — лишь текущая версия), и
# переименование направления обнуляет привязку операторов, а модель переживает
# и то, и другое.
CHAT_MANAGER_DIRECTION_MODEL = 'chat_manager'

# Кому гейт задаёт QR-подтверждение. Стажёр включён СОЗНАТЕЛЬНО, в отличие от
# «Посылок» и вики, где он проходит молча (известный незакрытый дефект, см.
# parcels/access.py:requires_sensitive_qr). Здесь на кону не карточка с
# телефоном, а переписка целиком, и «стажёр читает чаты водителей из дома без
# подтверждения» — не та сторона ошибки, на которой стоит оказаться.
#
# Имя ПУБЛИЧНОЕ, потому что список читает монолит: три ручки /api/sensitive-access/*
# и кнопка «Открыть доступ» в «Сессиях» умеют выдавать подтверждение только тем
# ролям, у которых его хоть кто-то спрашивает. Пока список был приватным, они о
# стажёре не знали, и он оказывался в тупике: раздел требует QR, а сгенерировать
# его портал отказывается («этой роли подтверждение не требуется»).
QR_GATED_ROLES = ('operator', 'trainee')


# ─── Стадия выката ────────────────────────────────────────────────────────────
#
# Обкатка закончена: 08.09.2026 владелец открыл раздел отделу — «доступ для
# линии/основы СЗоВ, супервайзерам и руководителя Ару Омаровой, и так же будет
# виден суперадминам». Ровно это и есть периметр ниже:
#
#   линия/основа  = СЗоВ минус чат-менеджеры (на проде живых направлений в
#                   отделе два: «Основа» с моделью `operator` — 50 человек, и
#                   «Чат менеджер» с моделью `chat_manager` — 18);
#   супервайзеры  = роль sv/supervisor в СЗоВ;
#   Ару Омарова   = глава отдела СЗоВ (departments.head_user_id), проходит
#                   строкой про главу, а не по своему id.
#
# Флаг оставлен, а не удалён: закрыть раздел обратно на день разбора — это одна
# строка здесь и такая же во фронте, а не удаление правил периметра. Двойник —
# `DRIVER_CHATS_ROLLOUT_SUPER_ADMIN_ONLY` в src/App.jsx: там он прячет пункт
# меню, здесь закрывает сами ручки, и разъехаться им не даёт тест.
ROLLOUT_SUPER_ADMIN_ONLY = False


def normalize_role(role):
    value = str(role or '').strip().lower()
    return value if value in _KNOWN_ROLES else 'operator'


def _codes(values):
    return {str(code).strip().lower() for code in (values or []) if code}


def _own_code(ctx):
    return str(ctx.get('department_code') or '').strip().lower()


def is_department_head(ctx):
    return bool(ctx.get('headed_department_ids'))


def is_super_admin(ctx):
    """Единственная роль, которая проходит сюда мимо отдела.

    В остальных разделах портала рядом с super_admin стоит и «глобальный админ»
    (роль `admin`, не назначенная главой отдела). Здесь его нет намеренно:
    08.09.2026 владелец сузил круг до «линия/основа СЗоВ, супервайзеры, Ару,
    суперадмины». Пятеро админов портала числятся в СЗоВ, и прежнее правило
    отдавало им вместе с разделом ещё и журнал.
    """
    return normalize_role(ctx.get('role')) == 'super_admin'


def is_portal_admin_outside_department(ctx):
    """Роль `admin`, не назначенная главой отдела, — админ портала.

    Назначение главой ЗАМЕНЯЕТ базовую роль (действующая семантика портала),
    поэтому глава СЗоВ сюда не попадает и проходит своей строкой.
    """
    return normalize_role(ctx.get('role')) == 'admin' and not is_department_head(ctx)


def is_supervisor(ctx):
    return normalize_role(ctx.get('role')) in ('sv', 'supervisor')


def belongs_to_section_department(ctx):
    """Человек в СЗоВ — своим членством или как его глава."""
    if SECTION_DEPARTMENT_CODE in _codes(ctx.get('headed_department_codes')):
        return True
    return _own_code(ctx) == SECTION_DEPARTMENT_CODE


def is_chat_manager(ctx):
    """Чат-менеджер — по модели расчёта его направления, а не по имени.

    Проверяем ещё и отдел: модель `chat_manager` живёт в СЗоВ, и если такая же
    модель когда-нибудь появится в другом отделе, это будут другие люди с другой
    работой.
    """
    model = str(ctx.get('direction_model') or '').strip().lower()
    if model != CHAT_MANAGER_DIRECTION_MODEL:
        return False
    return _own_code(ctx) == SECTION_DEPARTMENT_CODE


def section_perimeter_allows(ctx):
    """Полное правило периметра — БЕЗ учёта стадии выката.

    Проверяется на КАЖДОМ роуте, а не только в меню: спрятанный пункт — это не
    доступ, раздел открывается и прямым адресом ?view=driver_chats.

    Порядок условий значим. Супер-админ проходит первым: у него нет отдела, и
    все отдельные проверки ниже он бы провалил. Исключения (тренер, админ
    портала, рядовой чат-менеджер) считаются ДО членства в отделе, иначе
    чат-менеджер СЗоВ прошёл бы по строке «мой отдел — СЗоВ».
    """
    if is_super_admin(ctx):
        return True
    if normalize_role(ctx.get('role')) in _SECTION_EXCLUDED_ROLES:
        return False
    if is_portal_admin_outside_department(ctx):
        return False
    # Исключение по направлению — про РЯДОВЫХ чат-менеджеров. Их супервайзер
    # проходит: владелец 08.09.2026 назвал доступ по роли («супервайзерам»), а
    # смысл исключения — не открывать человеку чужие диалоги вместо своих
    # рабочих. У супервайзера работа как раз в чужих: он их разбирает.
    if is_chat_manager(ctx) and not is_supervisor(ctx):
        return False
    return belongs_to_section_department(ctx)


def can_open_section(ctx):
    """Пускать ли пользователя в раздел СЕЙЧАС.

    Это периметр плюс стадия выката. Флаг `ROLLOUT_SUPER_ADMIN_ONLY` снят
    08.09.2026 — раздел открыт отделу, и «сейчас» совпадает с периметром. Пока
    флаг стоял, раздел видел только супер-админ; вернуть это состояние на день
    разбора — снова одна строка здесь и такая же во фронте.
    """
    if ROLLOUT_SUPER_ADMIN_ONLY:
        return normalize_role(ctx.get('role')) == 'super_admin'
    return section_perimeter_allows(ctx)


def is_search_limited(ctx):
    """Считать ли этому человеку суточный лимит поисков.

    Лимит защищает не деньги, а месячную квоту Chat2Desk, общую с ночным синком
    метрик отдела: исчерпав её, встают табло СЗоВ, зарплатные метрики
    чат-менеджеров и учёт часов. Поэтому он стоит на КАЖДОМ, кто работает в
    разделе, — от оператора до главы отдела.

    Супер-админ вне лимита (решение владельца 08.09.2026). Он не ведёт линию, а
    разбирает жалобы и проверяет сам раздел: упереться в потолок посреди разбора
    ему негде и незачем. Обратная сторона — потолка у него нет вовсе, поэтому
    его поиски видны в журнале наравне со всеми.
    """
    return not is_super_admin(ctx)


def can_view_journal(ctx):
    """Журнал «кто открывал чаты и кто нажимал «Передан»».

    Постановщик назвал троих: Ару Омарова, супервайзеры СЗоВ и суперадмины —
    и ровно это здесь и стоит, без «глобального админа» соседних разделов
    (см. is_super_admin: сужено владельцем 08.09.2026).
    Именного списка id здесь нет намеренно, и это не осторожность, а
    единственный способ не сломаться молча: у Ару в базе ДВЕ учётки —
    id 205 («Омарова Ару», роль sv, статус fired, ни одной сессии) и рабочая
    id 1 («Omarova Aru», роль admin), которая и записана главой СЗоВ
    (`departments.head_user_id = 1`). Хардкод любого из этих id выдал бы доступ
    не тому человеку. Правило же «глава этого отдела ИЛИ его супервайзер»
    покрывает её как есть и переживает и замену человека, и вторую учётку.

    Глава СЗоВ входит: журнал о работе его отдела. Глава другого отдела — нет,
    его в can_open_section уже не пустили.

    Оператор не видит журнал НИКОГДА, даже свой: журнал ведётся ради контроля
    за ним, и «посмотреть, что про меня записано» — это другой продукт.
    """
    if is_super_admin(ctx):
        return True
    if not can_open_section(ctx):
        return False
    if is_department_head(ctx):
        return SECTION_DEPARTMENT_CODE in _codes(ctx.get('headed_department_codes'))
    return is_supervisor(ctx)


def requires_sensitive_qr(ctx):
    """Нужно ли подтвердить сессию QR-кодом, прежде чем раздел откроется.

    Ключ тот же, что у «Вики», «Обращений», «Посылок» и «Моих оценок»
    (bot_schedule2: sensitive-access): QR генерирует сам сотрудник, подтверждает
    админ или супервайзер, доступ живёт до конца ЭТОЙ сессии. Своего второго
    ключа раздел не заводит намеренно — два разных QR на один экран человек не
    различит.

    ЧЕСТНАЯ ГРАНИЦА ЭТОГО МЕХАНИЗМА (сказано постановщику отдельно): QR
    подтверждает человека, а не место. Он не проверяет ни сеть, ни устройство,
    ни город. Требование «из дома нельзя» им НЕ выполняется и выполнено быть не
    может — ни IP офисов в портале нет, ни запретить снимок экрана нельзя.
    Поэтому рядом с гейтом стоит журнал: он отвечает на вопрос «кто открыл и
    что передал», на который QR не отвечает.

    Кого гейт не касается: глобального админа, главы отдела и супервайзера — им
    подтверждать доступ не у кого, а супервайзер его и выдаёт.

    Незнакомая роль подпадает под гейт: normalize_role сводит её к 'operator', и
    это правильная сторона ошибки — закрыто, а не открыто.
    """
    if is_super_admin(ctx) or is_department_head(ctx) or is_supervisor(ctx):
        return False
    return normalize_role(ctx.get('role')) in QR_GATED_ROLES


def capabilities(ctx):
    """Сводка для фронта: раздел рисует кнопки по ней, а не по роли.

    Одно место правды: правило меняется здесь, а не в трёх местах интерфейса.
    """
    return {
        'can_open': can_open_section(ctx),
        'can_view_journal': can_view_journal(ctx),
        'requires_qr': requires_sensitive_qr(ctx),
        'is_search_limited': is_search_limited(ctx),
        'is_super_admin': is_super_admin(ctx),
        'is_department_head': is_department_head(ctx),
    }
