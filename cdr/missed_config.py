"""Настройки робота «пропущенные входящие → amoCRM» (задача #291). Секретов здесь нет.

Отдельным модулем, а не в missed_service: раздел «Касания» спрашивает только «включён
ли робот», и ради этого тянуть клиента amoCRM (requests, логин) в каждую ручку незачем.

Включение — ТОЛЬКО переменной окружения `CDR_MISSED_AMO_ENABLED=1` на Render. Файл
`.env.codex.local` здесь намеренно не читается: локальный прогон или тест не должен
заводить сделки в боевой amoCRM из-за строки в файле разработчика.

Идентификаторы — боевого аккаунта igroupkz, сняты чтением API 28.09.2026:
  * воронка «Отдел продаж» 5524684, этап «Новая заявка» 48846277. Этапа «Новый лид»,
    который назван в ТЗ, в воронке нет; «Новая заявка» — первый рабочий этап, туда же
    кладёт сделки робот OLX (решение владельца 28.09.2026). Одноимённый этап есть и в
    «Тестовой воронке» (87053946), поэтому этап задаётся парой чисел;
  * ответственный «Администратор» 8303491 — тот же, что у робота OLX: сделку на
    перезвон распределяют дальше в самой amoCRM;
  * тега «Пропущенный входящий» в аккаунте на 28.09.2026 нет — amoCRM создаёт его при
    первой сделке, дальше он находится по имени (missed_amo.MissedCallWriter.tag_ref).
"""

import os

ENABLED_ENV = 'CDR_MISSED_AMO_ENABLED'

PIPELINE_ID = int(os.getenv('CDR_MISSED_AMO_PIPELINE_ID') or 5524684)        # «Отдел продаж»
STATUS_ID = int(os.getenv('CDR_MISSED_AMO_STATUS_ID') or 48846277)           # «Новая заявка»
RESPONSIBLE_USER_ID = int(os.getenv('CDR_MISSED_AMO_RESPONSIBLE_ID') or 8303491)
TAG_NAME = (os.getenv('CDR_MISSED_AMO_TAG') or 'Пропущенный входящий').strip()

# Закрытые этапы amoCRM — одинаковые во всех воронках.
CLOSED_STATUS_IDS = (142, 143)


def enabled():
    """Включён ли робот. Выключен по умолчанию: выкладка кода не должна сама начинать
    заводить сделки, которые операторы тут же начнут обзванивать."""
    return str(os.environ.get(ENABLED_ENV) or '').strip().lower() in ('1', 'true', 'yes', 'on')
