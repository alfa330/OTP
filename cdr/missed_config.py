"""Настройки робота «пропущенные входящие → CRM» (задачи #291 и SALES-4). Секретов здесь нет.

Отдельным модулем, а не в missed_service: раздел «Касания» спрашивает только «включён
ли робот и куда он передаёт», и ради этого тянуть клиентов CRM (requests, логин) в каждую
ручку незачем.

Куда передаёт робот
-------------------
С 28.09.2026 — в amoCRM сделкой (#291). SALES-4 (19.11.2026, «переадресация лидов
„пропущенный входящий“ из Амо в синтони»): лиды отдела продаж переехали в CRM Syntony, и
пропущенные идут туда же — заявкой через форму Syntony (cdr/missed_syntony.py).

Включение — ТОЛЬКО переменными окружения прода:
  * `CDR_MISSED_SYNTONY_ENABLED=1` — передавать в Syntony; нужен и ключ формы
    `SYNTONY_LEADS_FORM_KEY`. Это переадресация: при ней amoCRM робот не трогает, даже если
    включён и прежний флаг;
  * `CDR_MISSED_AMO_ENABLED=1` — передавать в amoCRM, как было до SALES-4.
С переезда прода 25.11.2026 окружение лежит в GitLab itaxi3/infra/k8s-yc, файл
prod/apps/portal/env.yaml (main меняет девопс, правка — merge request), до того — в Render.
Его перенесли выгрузкой с Render от 23.11, и включение Syntony от 24.11 в неё не попало: до
MR !7 прод снова передавал в amoCRM. Сверять окружение после таких переносов.
Файл `.env.codex.local` здесь намеренно не читается: локальный прогон или тест не должен
заводить сделки в боевой CRM из-за строки в файле разработчика.

Идентификаторы amoCRM — боевого аккаунта igroupkz, сняты чтением API 28.09.2026:
  * воронка «Отдел продаж» 5524684, этап «Новая заявка» 48846277. Этапа «Новый лид»,
    который назван в ТЗ, в воронке нет; «Новая заявка» — первый рабочий этап, туда же
    кладёт сделки робот OLX (решение владельца 28.09.2026). Одноимённый этап есть и в
    «Тестовой воронке» (87053946), поэтому этап задаётся парой чисел;
  * ответственный «Администратор» 8303491 — тот же, что у робота OLX: сделку на
    перезвон распределяют дальше в самой amoCRM;
  * тега «Пропущенный входящий» в аккаунте на 28.09.2026 нет — amoCRM создаёт его при
    первой сделке, дальше он находится по имени (missed_amo.MissedCallWriter.tag_ref).
У Syntony воронку, ответственного и теги задаёт форма в самой Syntony, а не запрос.
"""

import os

ENABLED_ENV = 'CDR_MISSED_AMO_ENABLED'
SYNTONY_ENABLED_ENV = 'CDR_MISSED_SYNTONY_ENABLED'

AMO = 'amo'
SYNTONY = 'syntony'

PIPELINE_ID = int(os.getenv('CDR_MISSED_AMO_PIPELINE_ID') or 5524684)        # «Отдел продаж»
STATUS_ID = int(os.getenv('CDR_MISSED_AMO_STATUS_ID') or 48846277)           # «Новая заявка»
RESPONSIBLE_USER_ID = int(os.getenv('CDR_MISSED_AMO_RESPONSIBLE_ID') or 8303491)
TAG_NAME = (os.getenv('CDR_MISSED_AMO_TAG') or 'Пропущенный входящий').strip()

# Закрытые этапы amoCRM — одинаковые во всех воронках.
CLOSED_STATUS_IDS = (142, 143)

# Метки, которыми робот подписывает свои заявки в Syntony. По ним отбивка «Лиды по
# источникам» узнаёт заявку на перезвон и не считает её лидом (db/amo_leads.py) — как не
# считала сделки amoCRM с тегом «Пропущенный входящий»: тег формы выбирают в Syntony, и
# тег вида call_<парк>_… попал бы в строку «Звонки». Значения выбраны так, чтобы ни одно
# правило источников (amocrm/leads.count_by_source) на них не срабатывало и без исключения.
SYNTONY_UTM = {'utm_source': 'icore', 'utm_medium': 'missed_call'}


def _flag(name):
    return str(os.environ.get(name) or '').strip().lower() in ('1', 'true', 'yes', 'on')


def target():
    """Куда робот передаёт пропущенные: SYNTONY, AMO или None — выключен.

    Выключен по умолчанию: выкладка кода не должна сама начинать заводить сделки, которые
    операторы тут же начнут обзванивать. Syntony главнее: SALES-4 — переадресация, и при
    обоих флагах сделка в amoCRM не заводится."""
    if _flag(SYNTONY_ENABLED_ENV):
        return SYNTONY
    if _flag(ENABLED_ENV):
        return AMO
    return None


def enabled():
    """Включён ли робот — в какую бы CRM он ни передавал."""
    return target() is not None


def crm_label(crm):
    """Название CRM для людей: в журнал цикла и в тексты раздела."""
    return 'Syntony' if crm == SYNTONY else 'amoCRM'
