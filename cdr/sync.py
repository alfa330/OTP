# -*- coding: utf-8 -*-
"""Какие сутки нужно забрать со станции. Чистая логика очереди.

Портал к станции не ходит: за данными ходит мост внутри корпоративной сети
(`cdr_bridge/`), а здесь решается только «каких суток не хватает» и «какое
задание протухло». Ни сети, ни базы в этом модуле нет — поэтому правила очереди
проверяются тестом без единого соединения.
"""

from datetime import datetime, timedelta

# Задание, взятое мостом и не закрытое за этот срок, считается брошенным: VM
# перезагрузили, службу перезапустили, сеть моргнула. Сутки читаются секунды,
# так что пятнадцать минут — это с большим запасом, а не «вдруг ещё считает».
STALE_MINUTES = 15

# Предел периода за один заход. Сутки — это ~23 тысячи строк CDR на станции;
# 92 дня мост разбирает примерно за четверть часа. Дальше человек уже не ждёт у
# экрана, а станция всё это время занята нами.
MAX_PERIOD_DAYS = 92

# Часовой хвост следующих суток, который мост дочитывает, чтобы собрать звонок,
# начатый до полуночи. Константа живёт здесь, а не только в мосте: её же
# показывает раздел, объясняя, почему сутки закрываются не ровно в 00:00.
TAIL_HOURS = 1

# Сколько раз пробуем одни сутки, прежде чем перестать. Без потолка получается
# вечный круг: раздел опрашивается раз в три секунды, каждый опрос возвращает
# упавшие сутки в очередь, мост снова идёт на станцию и снова падает — и так
# пока открыта вкладка. Пять попыток переживают моргнувшую сеть, но не переживут
# сутки, которых на станции нет.
#
# Потолок снимается вручную кнопкой «обновить» (sync?force=1): человек, который
# видит ошибку и всё равно жмёт, знает, что делает.
MAX_ATTEMPTS = 5


def parse_day(value, field='дата'):
    """'ГГГГ-ММ-ДД' → date. ValueError с человеческим текстом, не ISO-жаргоном."""
    text = str(value or '').strip()[:10]
    try:
        return datetime.strptime(text, '%Y-%m-%d').date()
    except ValueError:
        raise ValueError('Не разобрал %s: «%s». Ожидается ГГГГ-ММ-ДД' % (field, value))


def days_in_period(day_from, day_to):
    count = (day_to - day_from).days + 1
    return [day_from + timedelta(days=i) for i in range(count)]


def days_needing_sync(states, day_from, day_to, today, now=None):
    """Какие сутки периода надо поставить в очередь мосту. Чистая функция.

    Ставятся заново:
      * сутки, которых в очереди нет вовсе;
      * `error` — мост не смог, человек вправе попросить ещё раз;
      * `done`, но `complete = false` — сутки читались, когда ещё не кончились,
        и станция дописала в них звонки после этого;
      * протухшие `running` — мост взял задание и пропал.

    НЕ ставятся:
      * сутки в будущем — станции нечего о них рассказать, а запись «ошибка» на
        завтрашней дате выглядела бы поломкой раздела;
      * свежие `running` — мост уже занят ими прямо сейчас;
      * закрытые `done` — они не меняются.
    """
    now = now or datetime.utcnow()
    by_day = {row['day']: row for row in (states or [])}
    need = []
    for day in days_in_period(day_from, day_to):
        if day > today:
            continue
        state = by_day.get(day.isoformat())
        if not state:
            need.append(day)
            continue
        status = state.get('status')
        if status == 'done':
            if not state.get('complete'):
                need.append(day)
            continue
        if attempts_exhausted(state):
            # Столько раз не смогли, что пора перестать. Потолок распространяется
            # и на залипшее `running`: мост, который стабильно берёт сутки и не
            # закрывает их (например портал отвергает его тело запроса), иначе
            # читал бы станцию по кругу вечно и молча — статус `error` в этом
            # сценарии не выставляется никем.
            continue
        if status == 'running':
            if is_stale(state.get('claimed_at'), now):
                need.append(day)
            continue
        need.append(day)
    return need


def attempts_exhausted(state):
    return int((state or {}).get('attempts') or 0) >= MAX_ATTEMPTS


def is_settled(state, day, today):
    """Сутки, по которым больше НЕЧЕГО ЖДАТЬ прямо сейчас.

    Это не то же самое, что «сутки закрыты навсегда», и разница здесь —
    единственное, что отделяет работающий раздел от вечного спиннера.

    **Сегодняшние сутки готовы, как только мост их привёз.** `complete` у них
    FALSE по построению (станция дописывает в них звонки до полуночи), и если
    ждать `complete`, ожидание не кончится никогда: период по умолчанию — «7
    дней», то есть включает сегодня, значит полоса прогресса крутилась бы вечно
    на 86%, кнопка «обновить» оставалась бы заблокированной, а вкладки
    «Операторы» и «По дням» не загружались бы вообще. Данные при этом лежат в
    базе и показываются.

    Перечитывание незакрытых суток от этого не страдает: за него отвечает
    `days_needing_sync`, и оно продолжает возвращать сегодня при каждом заходе.

    Второй исход — «мы сдались»: сутки, которых на станции нет, столько раз не
    дались, что ждать их бессмысленно. Список отказов человеку уже показан
    отдельной плашкой, а вечный спиннер не сказал бы ему ничего.
    """
    if not state:
        return False
    if state.get('status') == 'done':
        return bool(state.get('complete')) or day >= today
    return attempts_exhausted(state)


def days_awaiting(states, day_from, day_to, today):
    """Каких суток периода ещё НЕТ в готовом виде. Чистая функция.

    Не то же самое, что `days_needing_sync`, и разница стоила отдельного разбора:
    сутки, которые мост прямо сейчас читает (`running`, отметка свежая),
    переспрашивать не надо — но и готовыми они не являются. Если считать
    ожидание по «что переспросить», полоса прогресса покажет 100% в тот момент,
    когда мост ещё на середине, а фронт перестанет опрашивать и не увидит
    приехавших данных.

    Сутки в будущем не ожидаются: их не будет никогда.
    """
    by_day = {row['day']: row for row in (states or [])}
    awaiting = []
    for day in days_in_period(day_from, day_to):
        if day > today:
            continue
        if not is_settled(by_day.get(day.isoformat()), day, today):
            awaiting.append(day)
    return awaiting


def is_stale(claimed_at, now=None):
    """Брошено ли задание. Нет отметки — считаем брошенным: строка `running` без
    времени взятия могла пережить перезапуск ещё до того, как отметку поставили."""
    now = now or datetime.utcnow()
    if not claimed_at:
        return True
    moment = _naive_utc(claimed_at)
    if moment is None:
        return True
    return (now - moment) > timedelta(minutes=STALE_MINUTES)


def _naive_utc(value):
    """Отметка времени из базы → наивный UTC.

    Postgres отдаёт TIMESTAMPTZ с зоной, а сравниваем мы с utcnow(): вычитание
    осведомлённого времени из наивного бросает TypeError, и очередь встала бы
    целиком. Строку тоже принимаем — из JSON состояния она приходит текстом.
    """
    if isinstance(value, str):
        try:
            value = datetime.fromisoformat(value)
        except ValueError:
            return None
    if not isinstance(value, datetime):
        return None
    if value.tzinfo is None:
        return value
    return (value - value.utcoffset()).replace(tzinfo=None)


def window_for(day):
    """Границы чтения суток на станции: сами сутки плюс часовой хвост.

    Хвост нужен, чтобы собрать плечи звонка, начатого в 23:59 — без него такой
    звонок распался бы на два обрубка с неверной длительностью. Мост присылает
    только касания, начавшиеся в эти сутки, поэтому хвост не удваивает данные.
    """
    start = datetime.combine(day, datetime.min.time())
    end = start + timedelta(days=1, hours=TAIL_HOURS)
    return start.strftime('%Y-%m-%dT%H:%M:%S'), end.strftime('%Y-%m-%dT%H:%M:%S')
