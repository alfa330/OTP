# -*- coding: utf-8 -*-
"""Таксопарк линии: чей номер набрал клиент или с какого номера позвонили ему.

Номер у касания есть всегда (`line_number`, см. cdr/touches.py), но номеров у парка
десятки: у Jana их 41, у «Центра регистрации» 66. Человеку в разделе нужен парк, а
номер — чтобы проверить. Поэтому парк выводится, а не хранится.

Откуда парк
-----------
Станция сама знает, чей номер: входящий на него уходит в очередь парка (DID →
автоинформатор → очередь 3034 «Jana»). Эту связь раздел не спрашивает у станции, а
видит в своих же касаниях: у входящего есть и набранный номер, и очередь, куда звонок
пришёл. Исходящему парк достаётся по номеру — очередь, в которую чаще всего уходят
входящие на этот же номер. Сверено на сутках 23.09.2026: все 13 номеров, с которых
звонили, в те же сутки принимали и входящие.

Почему не очередь самого касания у исходящего: заявка автообзвона идёт через очередь
кампании (`Local/3016@ext-to-queue`), а номер клиенту показывается другой — префикс
`7778*` уходит через транк «Центра регистрации». На вопрос «с какого парка позвонили»
отвечает номер, а не очередь кампании.

Названия — по очереди, а не по номеру: номеров сотни и они меняются, очередей у отдела
продаж два десятка. Подписи те же, что у «Биллинга Oktell» (_OKTELL_BILLING_LINE_LABELS
в монолите), — это названия, которыми парки называет сам бизнес. Очередь без подписи
показывается честно номером очереди: так новый парк виден сразу, а не пропадает.

Модуль чистый: ни сети, ни базы.
"""

from cdr import touches as touches_mod

# Очередь станции → таксопарк. Названия очередей на станции техничные и местами
# устарели («Перезвон фокус группы» у очереди, куда ведут 66 номеров «Центра
# регистрации»), поэтому подписи свои; источник — план набора станции на 23.09.2026.
PARK_BY_QUEUE = {
    '3000': 'Честный',
    '3001': 'iTaxi',
    '3002': 'OLX',
    '3003': 'Бизнес Партнер',
    '3004': 'РСС Маркетинг',
    '3006': 'Департамент',
    '3007': 'Amanat',
    '3008': 'Qazaq',
    '3010': 'Центр регистрации',
    '3015': 'Global',
    '3030': 'Eki Dongelek',
    '3033': 'Стабильный',
    '3034': 'Jana такси',
    '3035': 'Тенге Такси',
    '3036': 'Аренда авто',
    '3037': 'Центр регистрации',
    '3038': 'Салам Такси',
    '3040': 'Такси 24',
    '3041': 'Ноль такси',
    '3042': 'Достойный',
    '3077': 'Wolt',
    '4001': 'Автообзвон',
}

QUEUE_PREFIX = 'очередь '


def first_queue(queue):
    """«3000,3001» → «3000». Две очереди у звонка — перевод; парк — по первой."""
    return str(queue or '').split(',', 1)[0].strip()


def park_of_queue(queue):
    """Подпись парка по очереди; незнакомая очередь — её номером, пустая — пусто."""
    queue = first_queue(queue)
    if not queue:
        return ''
    return PARK_BY_QUEUE.get(queue) or QUEUE_PREFIX + queue


def queues_of_park(park):
    """Обратно: какие очереди называются этим парком. Нужен фильтру — у парка их
    бывает две («Центр регистрации» — 3010 и 3037)."""
    park = str(park or '').strip()
    if not park:
        return []
    if park.startswith(QUEUE_PREFIX):
        return [park[len(QUEUE_PREFIX):]]
    return sorted(queue for queue, name in PARK_BY_QUEUE.items() if name == park)


def line_queues(rows):
    """[(номер, очередь, сколько входящих)] → {номер: очередь}.

    Берётся очередь, куда уходило больше всего входящих на этот номер: номер могли
    перевести в другой парк, и за окно у него встречаются обе. Ничья — меньшая
    очередь, чтобы ответ не зависел от порядка строк в выдаче базы."""
    counts = {}
    for number, queue, count in rows or []:
        number = str(number or '')
        queue = first_queue(queue)
        if not number or not queue:
            continue
        bucket = counts.setdefault(number, {})
        bucket[queue] = bucket.get(queue, 0) + int(count or 0)
    return {number: min(bucket, key=lambda queue: (-bucket[queue], queue))
            for number, bucket in counts.items()}


def park_queue(touch, known):
    """Очередь, по которой называется парк касания.

    Входящий — своя очередь: куда звонок реально пришёл, то и парк, даже если номер
    с тех пор перевели. Исходящий и входящий без очереди — очередь номера (`known`,
    см. line_queues). Номер незнаком — своя очередь, если она есть.

    То же правило записано в SQL фильтра (queries._FILTER_SQL, условие по парку):
    меняя одно, меняйте и другое, иначе фильтр «Jana» покажет не те строки, что
    подписаны «Jana»."""
    number = str(touch.get('line_number') or '')
    own = first_queue(touch.get('queue'))
    outgoing = touch.get('call_type') == touches_mod.TYPE_OUT
    if number in known and (outgoing or not own):
        return known[number]
    return own


def park(touch, known):
    return park_of_queue(park_queue(touch, known))


def park_filter(park_name, known):
    """Фильтр по парку → (очереди парка, номера парка, все знакомые номера).

    Три списка ровно под условие в SQL: знакомый номер у исходящего или бесочередного
    касания проверяется по «номерам парка», остальное — по своей очереди."""
    queues = queues_of_park(park_name)
    wanted = set(queues)
    numbers = sorted(number for number, queue in known.items() if queue in wanted)
    return queues, numbers, sorted(known)
