"""Раздел «Касания» — звонки отдела продаж из CDR АТС FreePBX.

Касание — это один звонок клиенту: когда позвонили, кто, чем кончилось, сколько
говорили и где лежит запись. С июня 2026 такие файлы собирались вручную
скриптами из `outputs/kasaniya_leads_*`, потому что станция была видна только из
локальной сети. Тот же человек, который поднял прокси к Oktell, вывел наружу и
CDR — теперь до станции дотягивается прод, и выгрузка живёт в разделе.

Что важно знать про предметную область (всё проверено на данных, не выведено):

* **Касание — это ОДИН ВЫЗОВ, а не строка CDR.** У входящего в очередь строк
  бывает до двух десятков — каждая попытка дозвониться до агента. Склейка идёт
  по `linkedid`: 23 тысячи строк суток превращаются в 3,4 тысячи касаний.

* **Эта АТС — только отдел продаж.** Из 98 внутренних номеров, встретившихся в
  CDR, 55 совпали с ОП-номерами из базы, а три «СЗоВ-номера» станция держит за
  сотрудниками ОП. СЗоВ и Тез КЦ сидят на Oktell. Значит, любой звонок отсюда —
  касание ОП, и отдельного фильтра по отделу не нужно.

* **Внутренний номер оператора живёт в имени файла записи**, а не в src/dst: у
  автодозвона его в этих полях нет вовсе.

Состав пакета (разделение то же, что у parcels/ и fleet_edm/):
    config.py     адрес и логин прокси станции; секретов в коде нет
    client.py     HTTP-клиент CDR: страницы по 5000, справочник агентов
    touches.py    чистая склейка строк CDR в касания — ни сети, ни базы
    directory.py  чистая сборка справочника «номер → сотрудник» с периодами
    schema.py     DDL таблиц cdr_*, идемпотентный
    queries.py    SQL поверх готового курсора
    sync.py       выкачка суток и очередь работ
    report.py     книга xlsx в потоковом режиме
    access.py     чистая логика прав
    routes.py     Blueprint /api/cdr

Логика склейки и справочника перенесена один в один из офлайн-сборки и сверена
с уже собранным файлом «Лиды 24.08 + касания ОП»: все 1288 касаний эталона
воспроизвелись, расхождений по полям нет (tests/test_cdr_touches.py).
"""

