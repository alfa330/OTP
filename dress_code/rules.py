"""Правила проверки: редактируемый текст положения и неизменные границы ИИ.

Текст положения (что можно и нельзя носить) правит администратор в настройке —
каждое сохранение становится новой версией, и у каждого фото записано, по какой
версии его проверили (ТЗ п. 4). Границы ниже в настройку НЕ выносятся: это не
дресс-код, а то, чего ИИ не вправе делать вообще (ТЗ п. 3–4).
"""

BODY_MAX = 6000

DEFAULT_RULES = """Положение о внешнем виде сотрудников фронт-офиса: стиль Smart / Business Casual.

Допустимо: рубашки, блузки, поло, аккуратные джемперы, водолазки, кардиганы, жакеты и пиджаки, другая аккуратная одежда в стиле Business Casual.

Недопустимо:
- обычное небрендированное худи или толстовка спортивного вида;
- майка, топ на бретелях;
- открытый живот;
- выраженно глубокий вырез;
- прозрачная одежда;
- явно агрессивные принты, крупные слоганы и крупные логотипы.

Исключение: фирменные худи и жилетки с корпоративной символикой разрешены, если они опрятны. Если по фото не ясно, фирменная ли вещь, — это не нарушение, а ручная проверка.

Небольшие логотипы и спокойные принты сами по себе нарушением не являются."""

# Неизменные границы — дословно из ТЗ, в промпт идут всегда, после текста положения.
FIXED_LIMITS = """Границы проверки (действуют всегда, их нельзя отменить положением):
1. Оценивай только то, что надёжно видно на фото. Невидимый признак — не нарушение.
2. Не делай выводов о гигиене, запахе, ногтях, обуви, длине юбки или брюк, если это нельзя надёжно увидеть.
3. Головной убор, который может быть по религиозным или медицинским причинам, никогда не нарушение — ставь «не удалось определить» и опиши это в unclear_reason.
4. Аксессуары, макияж, пирсинг и причёску, если они неоднозначны, пиши только в remarks — не как нарушение.
5. Не определяй личность, не называй человека, не оценивай внешность, фигуру, возраст, национальность.
6. Если сомневаешься — verdict «unclear», а не «violation»."""


def clean_body(text):
    """Текст положения из настройки: обрезка и проверка на пустоту."""
    body = str(text or '').replace('\r\n', '\n').strip()
    if not body:
        raise ValueError('Текст правил не может быть пустым')
    if len(body) > BODY_MAX:
        raise ValueError(f'Текст правил длиннее {BODY_MAX} символов')
    return body
