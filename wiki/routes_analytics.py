# -*- coding: utf-8 -*-
"""Эндпоинт вкладки «Аналитика».

Собирает четыре блока — чтение, содержимое, ознакомления и спрос без ответа —
ОДНИМ ответом, а не четырьмя запросами с фронта: периметр у них общий, и
считать его четырежды значило бы четырежды пройти цепочку «субъекты → разделы
→ статьи» ради одного экрана.

Блоков четыре, потому что вопросов четыре: пользуются ли викой вообще, в каком
состоянии её содержимое, выполнено ли обязательное и чего в вике не хватает.
Разрезы, которые не ведут ни к какому решению, сюда не попадают намеренно —
отчёт, где половина таблиц «просто цифры», перестают открывать целиком.

Блок «Содержимое» закрывает требования 4.6 постановки: статистика по разделам
(сколько статей, когда последний раз правили, кто правит) и отчёт по
необновляемым статьям. Перепись читателей поимённо — оттуда же («какие
сотрудники пользовались Wiki за период»), но живёт она в блоке чтения: это
ответ на вопрос «кто читает», просто не сводный, а поимённый.

ГЕЙТОВ ДВА, И ОНИ ОТВЕЧАЮТ НА РАЗНЫЕ ВОПРОСЫ.

Способность открывает вкладку: её видит тот, кто ВЕДЁТ содержимое, — редактор
(can_create | can_edit | can_publish), тот же набор, что у статистики
тренажёров. Решение владельца: отчёт про базу знаний нужен тому, кто её пишет,
а не только администратору доступов. Отдельно пропускается администратор
доступов без прав правки — вкладка у него уже была, и отнимать её незачем.

Граница отдела решает, кого на вкладке можно показать ПОИМЁННО. Способность
редактора отделов не знает, и без границы супервайзер СЗоВ увидел бы, кто
именно в отделе продаж просрочил ознакомление. Правило повторено из
wiki/routes_trainers.py намеренно: там оно живёт замыканием внутри register() и
импортировать его нельзя, а разъезжаться правилам про одно и то же не дают
тесты.

Признак scoped уходит в ответ: у супервайзера и у директора числа в поимённых
списках РАЗНЫЕ, и без пометки это читается как расхождение данных.
"""

from flask import jsonify, request

from . import access as wiki_access
from . import analytics as wiki_analytics
from . import perimeter as wiki_perimeter
from .routes_structure import _int_or_none

# Потолок строк в подробных разрезах. Ограничение не про базу — про экран:
# таблица на тысячу строк не читается, а за подробностями есть выгрузка.
MAX_ROWS = 100
DEFAULT_ROWS = 10

# Списки-ПЕРЕПИСИ (кто пользовался викой, какие есть разделы) режутся своим
# потолком, а не общим с топами. Топ отвечает на «что самое читаемое», и
# двадцати строк ему хватает; перепись отвечает на «кто/что вообще есть», и
# обрезанная на двадцати она отвечает не на тот вопрос. На экране длинный
# список свёрнут до десяти строк с кнопкой «показать всех».
ROSTER_ROWS = 100

# Сколько дней без правки считать устареванием. Полгода — обычный цикл
# пересмотра корпоративных регламентов; число написано на экране, потому что
# «устаревшая статья» без указания срока — это оценка, а не факт.
STALE_DAYS = 180


def register(bp, wiki_route, db, log_ip):

    def _period():
        """Диапазон дат из строки запроса. Пусто = «за всё время».

        Формат не разбираем: Postgres принимает ISO-дату как есть, а
        самодельный парсер добавил бы второе место, где формат может разойтись
        со всеми остальными периодами раздела.
        """
        def one(name):
            raw = str(request.args.get(name) or '').strip()
            return raw[:10] or None
        return one('since'), one('until')

    def _departments(ctx):
        """Границы, внутри которых человеку можно показывать людей поимённо.

        Правило то же, что у статистики тренажёров (_departments в
        routes_trainers.py) и у выдачи доступа (_grant_departments в
        routes_structure.py).

        None — без границы: у супер-админа и у администратора доступов её нет
        по построению, они и так видят весь портал. У остальных — свои отделы,
        то есть возглавляемые плюс собственный.

        Пока вкладка гейтилась одной способностью can_manage_access, эта
        функция всегда возвращала None и границы фактически не было: способность
        выдаётся только мастер-ключом супер-админа или ролью вики, а обе ветки
        ниже как раз их и пропускают. С гейтом по правам правки граница стала
        рабочей — супервайзер-редактор видит поимённо только свой отдел.
        """
        if wiki_access.normalize_role(ctx['otp_role']) == 'super_admin':
            return None
        if bool(ctx['wiki_roles']) and ctx['capabilities'].get('can_manage_access'):
            return None
        own = set(ctx.get('headed_department_ids') or [])
        if ctx.get('department_id'):
            own.add(ctx['department_id'])
        return sorted(own)

    def _is_editor(ctx):
        """Кто ведёт содержимое. Формула ОДНА на весь раздел.

        Та же, что в статистике тренажёров и во фронте (WikiView: isEditor).
        Разъедься эти три места — и вкладка появлялась бы в меню у того, кому
        сервер отвечает 403.
        """
        caps = ctx['capabilities']
        return bool(caps.get('can_create') or caps.get('can_edit')
                    or caps.get('can_publish'))

    @wiki_route('/analytics')
    def wiki_analytics_report(cursor, ctx):
        """Сводка раздела за период.

        Гейт стоит в ТЕЛЕ обработчика, а не параметром capability= на роуте:
        способностей, любая из которых открывает вкладку, четыре, а параметр
        принимает одну. Гард во фронте прячет вкладку, но не защищает прямой
        запрос, поэтому проверка обязана быть здесь.

        Периметр берётся с МАСТЕР-КЛЮЧОМ, и это не дыра: замыкание «видеть всё»
        внутри allowed_section_ids срабатывает только у супер-админа и у
        администратора доступов (wiki/queries.py). Рядовому редактору тот же
        вызов отдаёт его ЛИЧНЫЙ периметр — отчёт по чужой ветке ему не соберётся.

        Пространство сужает отчёт ДО расчёта, а не после: статья чужой вики
        иначе доезжает до топа, и «что читают в Тез» смешивается с
        «Таксопарками».
        """
        if not (_is_editor(ctx) or ctx['capabilities'].get('can_manage_access')):
            return jsonify({
                "error": "Аналитика доступна тем, кто ведёт статьи вики",
                "code": "WIKI_EDITOR_ONLY",
            }), 403

        since, until = _period()
        space_id = _int_or_none(request.args.get('space_id'))
        limit = min(max(_int_or_none(request.args.get('limit')) or DEFAULT_ROWS, 1),
                    MAX_ROWS)
        depts = _departments(ctx)

        _subjects, sections, visible = wiki_perimeter.read_perimeter(
            cursor, ctx, master_key=True, space_id=space_id)

        return jsonify({
            'period': {'since': since, 'until': until},
            # Числа в поимённых списках у супервайзера и у директора разные.
            # Без этого признака расхождение читается как поломка данных.
            'scoped': depts is not None,
            'reading': wiki_analytics.reading(
                cursor, visible, since=since, until=until, limit=limit,
                depts=depts, roster=ROSTER_ROWS),
            # Разделы приходят из того же периметра, что и статьи: считать их
            # заново значило бы завести вторую реализацию доступа.
            'content': wiki_analytics.content(
                cursor, sections, visible, since=since, until=until,
                limit=limit, roster=ROSTER_ROWS, stale_days=STALE_DAYS),
            'acknowledgements': wiki_analytics.acknowledgements(
                cursor, visible, depts=depts, limit=limit),
            'demand': wiki_analytics.demand(
                cursor, since=since, until=until, space_id=space_id, limit=limit),
            # Оговорки отдаёт СЕРВЕР, а не рисует фронт: они про то, как
            # устроены данные, и меняются вместе с запросами, а не с вёрсткой.
            'notes': _notes(len(visible), depts),
        })

    def _notes(visible_count, depts):
        """Оговорки — СЛОВАРЬ ПО ТЕМАМ, а не список.

        Списком они складывались подвалом «как это посчитано» в самом низу
        экрана: набор верных предложений, до которых не доскроллили, — тогда
        как каждое из них объясняет ровно одно число выше. Ключ позволяет
        фронту поставить оговорку к тому числу, о котором она: определение
        прочтения — к плитке «Прочтений», сужение по отделу — к поимённому
        списку. Текст при этом остаётся здесь, рядом с запросами: он меняется
        вместе с ними, а не с вёрсткой.

        Ключей, которых нет, в ответе нет вовсе — фронту не приходится
        отличать «оговорки не случилось» от пустой строки.
        """
        notes = {
            'read':
                'Прочтение — это человек, статья и минута: обновление '
                'страницы и возврат «назад» пишутся в журнал отдельными '
                'строками, поэтому открытий всегда больше. Счётчик под самой '
                'статьёй показывает открытия за всё время, а не прочтения за '
                'период, — числа на двух экранах и не должны совпадать.',
            # Без «показаны на сейчас» в начале: это же написано чипом рядом
            # с заголовком блока, и повтор съедал бы строку впустую.
            'ack_now':
                'Выбранный период на этот блок не действует: просрочка не '
                'бывает «за прошлый месяц», она есть сейчас или её нет.',
        }
        if depts is not None:
            notes['scoped'] = ('Люди показаны поимённо только по вашим '
                               'отделам — у руководителя выше по лестнице '
                               'числа в этом списке будут другими. Плитки '
                               'выше считают всю вику целиком.')
        if not visible_count:
            notes['empty'] = ('В выбранном пространстве вам не видно ни одной '
                              'статьи, поэтому все числа нулевые.')
        return notes
