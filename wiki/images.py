"""Картинки вики уезжают в бакет одним форматом — WebP.

ЗАЧЕМ. Статью иллюстрируют чем придётся: скриншот из мессенджера, картинка,
вынутая из Word, фотография с телефона на 12 мегапикселей. Читают это потом в
колонке шириной около 760 пикселей, то есть до глаза не доезжает и десятой доли
загруженных байтов. WebP на том же кадре весит в 2-4 раза меньше PNG и заметно
меньше JPEG при неотличимой картинке, а понимают его все браузеры, из которых
портал вообще открывают.

Место у конвертации одно — wiki/storage.py, через который проходит КАЖДЫЙ файл
вики: картинка из редактора, картинка, вынутая из docx при импорте, логотип
парка. Второй экземпляр этой логики разошёлся бы с первым молча.

Что здесь неочевидно и почему сделано именно так.

PILLOW ИМПОРТИРУЕТСЯ ВНУТРИ ФУНКЦИИ, а не наверху файла. Это не стилистика.
Модуль лежит в цепочке wiki.routes -> routes_import -> storage -> сюда, а сам
wiki.routes подключается в bot_schedule2 внутри try/except: любая осечка на
импорте оставила бы портал без ВСЕГО раздела — семьдесят роутов начали бы
отвечать 404, и молча. Отложенный импорт превращает отсутствие Pillow в то, чем
оно и является: картинка не пережалась, статья сохранилась. Так же в пакете
подключены mammoth и pypdf (wiki/importer.py).

СКРИНШОТ И ФОТОГРАФИЯ СЖИМАЮТСЯ ПО-РАЗНОМУ. У скриншота резкие границы букв, и
сжатие с потерями превращает мелкий текст в кашу — по такой инструкции уже не
прочитать, что написано на кнопке. Поэтому «экранные» источники (PNG, BMP,
TIFF) пакуются БЕЗ ПОТЕРЬ, а фотографии (JPEG, HEIC) — с потерями: разницы на
фотографии не видно, а без потерь она весила бы больше исходника.

ФОТОГРАФИЯ, СОХРАНЁННАЯ В PNG, — обычное дело: так отдаёт и «Ножницы», и
половина редакторов. На ней сжатие без потерь даёт файл БОЛЬШЕ исходного,
поэтому у крупного результата сверяется второй вариант, с потерями, и берётся
меньший.

УЖЕ WEBP НЕ ПЕРЕЖИМАЕТСЯ. Второй проход через кодек — потеря качества на ровном
месте, а формат и так нужный. Случай не выдуманный: логотип парка браузер
пережимает в WebP ещё до отправки (src/components/wiki/parkLogo.js), и серверу
осталось бы только испортить уже готовое. Такой файл проходит насквозь — у него
лишь считываются размеры.

SVG НЕ ТРОГАЕМ ВОВСЕ. Это разметка, а не растр: Pillow её не откроет, а перевод
в пиксели убил бы единственное её достоинство — масштабируемость.

ОТКАЗ КОНВЕРТЕРА НЕ ОТМЕНЯЕТ ЗАГРУЗКУ. Всё, что здесь не получилось, возвращает
None, и вызывающий кладёт файл как есть. Не пустить картинку в статью из-за
того, что кодек споткнулся на экзотическом кадре, — хуже, чем сохранить её
исходным форматом.
"""

import io
import logging
import os

# Длинная сторона, до которой ужимаем кадр. Тело статьи — колонка примерно в 760
# пикселей, и даже на экране с двойной плотностью больше 1520 показать физически
# негде: лупы у картинки в статье нет, кликом она не открывается. 2560 оставлено
# с запасом — ровно столько в скриншоте окна 1280 на «retina», а такие кадры в
# инструкциях резать нельзя: по ним читают подписи в интерфейсе.
MAX_SIDE = 2560

# Что не переводим ни при каких условиях.
SKIP_TYPES = {
    'image/svg+xml', 'image/x-icon', 'image/vnd.microsoft.icon',
    'image/avif',   # тоже современный формат, второй проход только испортит
}

# Источники «с экрана»: резкие границы букв, сжимать с потерями нельзя. WebP
# здесь тоже не случайно: насквозь проходит только тот, что уже в габаритах, а
# всё, что крупнее, пережимается — и делать это с потерями значило бы мылить
# текст на скриншоте, ради которого весь этот список и заведён.
SCREEN_TYPES = {'image/png', 'image/x-png', 'image/bmp', 'image/tiff', 'image/gif',
                'image/webp'}

# Форматы, у которых несколько кадров означают АНИМАЦИЮ. Проверять один лишь
# n_frames нельзя: у снимка с двухкамерного телефона (MPO внутри JPEG) и у
# многостраничного скана TIFF кадров тоже больше одного, и такой файл уехал бы
# в бакет мигающей анимацией — вчетверо тяжелее и вместо картинки.
ANIMATED_TYPES = {'image/gif', 'image/png', 'image/x-png', 'image/apng', 'image/webp'}

# Режимы, которые в WebP не переводим. Дело не в поддержке: у 16-битной серой
# картинки Pillow при переводе в RGB не масштабирует диапазон 0..65535, а
# ОБРЕЗАЕТ его — всё выше 255 становится белым. Ошибки при этом нет, и в бакет
# лёг бы почти сплошной белый прямоугольник. Такой файл честнее оставить как есть.
UNSUPPORTED_MODES = {'I', 'I;16', 'I;16B', 'I;16L', 'I;16N', 'F'}

# Порог, за которым у «экранного» кадра имеет смысл проверить вариант с
# потерями. У мелкого скриншота сжатие без потерь выигрывает всегда, и второй
# проход кодека был бы потраченным временем впустую.
_SECOND_OPINION_BYTES = 300 * 1024

# Кадров в анимации, после которых оставляем исходник. Дело не в формате, а во
# времени: каждый кадр кодируется отдельно, а загрузка идёт с ОТКРЫТЫМ
# соединением из пула вики — запись экрана на тысячу кадров держала бы его до
# таймаута.
MAX_FRAMES = 200

# Пикселей, выше которых картинку не разбираем вовсе. Дело не в формате, а в
# ПАМЯТИ: распакованный кадр занимает 4 байта на пиксель независимо от того,
# сколько весил файл, и лежит он в куче не в одном экземпляре — рядом живут
# буфер после ресайза и буфер кодировщика. Портал стоит на Render с общей
# памятью, и уронить его пережатием одной картинки — цена, которой сжатие не
# стоит; такой файл ложится в бакет как есть. 25 миллионов — это 5000x5000,
# втрое больше самого крупного скриншота и вдвое больше фотографии с телефона,
# а у JPEG сверх того работает draft (см. ниже).
MAX_PIXELS = 25 * 1000 * 1000

_LOSSY_QUALITY = 88          # фотография: на глаз неотличимо от исходника


def _pil():
    """(Image, ImageOps, ImageSequence) или None. Импорт отложенный — см. шапку."""
    try:
        from PIL import Image, ImageOps, ImageSequence
    except ImportError:      # pragma: no cover — окружение без Pillow
        return None
    return Image, ImageOps, ImageSequence


def _resample(Image):
    # LANCZOS переехал в Image.Resampling в Pillow 9 и остался доступен по
    # старому имени — берём тот, что есть, чтобы не привязываться к версии.
    return getattr(Image, 'Resampling', Image).LANCZOS


def _fit(Image, img):
    """Ужимает длинную сторону до MAX_SIDE. Кадр меньше отдаётся как есть."""
    side = max(img.size)
    if side <= MAX_SIDE:
        return img
    scale = float(MAX_SIDE) / float(side)
    size = (max(1, int(round(img.width * scale))), max(1, int(round(img.height * scale))))
    return img.resize(size, _resample(Image))


def _encode(img, icc=None, **options):
    """Кадр в байты WebP.

    ICC-профиль переносится, а EXIF — нет, и это разные решения. Снимки
    современных телефонов размечены Display P3; без профиля браузер считает их
    sRGB, и фирменный цвет на скриншоте уезжает в перенасыщение. EXIF же
    выбрасывается намеренно: там GPS-координаты и модель аппарата, а статью
    вики читает весь портал.
    """
    if icc:
        options['icc_profile'] = icc
    out = io.BytesIO()
    img.save(out, format='WEBP', **options)
    return out.getvalue()


def _still(Image, ImageOps, img, kind):
    """Один кадр: (картинка после подгонки, байты WebP)."""
    # У JPEG просим декодер сразу отдать уменьшенный кадр. Это не замена
    # ресайзу ниже, а способ не разворачивать в памяти то, что всё равно будет
    # выброшено: libjpeg умеет распаковывать в 1/2, 1/4, 1/8 размера, и на
    # фотографии в 8000 пикселей это разница между 256 и 64 МБ. Для остальных
    # форматов вызов — пустая операция.
    img.draft('RGB', (MAX_SIDE, MAX_SIDE))
    if img.width * img.height > MAX_PIXELS:
        logging.info('wiki: кадр %dx%d не пережимаем, кладём как есть',
                     img.width, img.height)
        return None

    if img.mode in UNSUPPORTED_MODES:
        return None

    icc = img.info.get('icc_profile')

    # Поворот из EXIF применяем ДО кодирования: WebP такого поля не хранит, и
    # фотография с телефона легла бы в статью боком. in_place — не мелочь: без
    # него Pillow возвращает ПОЛНУЮ КОПИЮ кадра даже когда поворачивать нечего,
    # то есть удваивает пик памяти на ровном месте. Возврат None при этом
    # штатный, его гасит `or img`.
    try:
        img = ImageOps.exif_transpose(img, in_place=True) or img
    except TypeError:      # Pillow до 9.5: аргумента нет, работаем по-старому
        img = ImageOps.exif_transpose(img) or img

    # Прозрачность живёт в ДВУХ разных местах, и второе легко не заметить. У
    # PNG с палитрой (а это типовой значок и типовой логотип) отдельного канала
    # нет вовсе: прозрачный цвет записан номером в info['transparency'], и
    # проверка «есть ли канал A» его не находит. Такая картинка уезжала бы в
    # RGB, и прозрачный фон значка становился бы ЧЁРНЫМ прямоугольником.
    if 'transparency' in img.info and img.mode != 'RGBA':
        img = img.convert('RGBA')
    elif img.mode not in ('RGB', 'RGBA'):
        img = img.convert('RGBA' if 'A' in img.getbands() else 'RGB')
    img = _fit(Image, img)

    if kind not in SCREEN_TYPES:
        return img, _encode(img, icc, quality=_LOSSY_QUALITY, method=6)

    # method=4, а не 6: у сжатия без потерь шестой метод считается втрое дольше
    # ради выигрыша в пару процентов, а держит он при этом соединение загрузки.
    best = _encode(img, icc, lossless=True, method=4)
    if len(best) > _SECOND_OPINION_BYTES:
        lossy = _encode(img, icc, quality=90, method=6)
        if len(lossy) < len(best):
            best = lossy
    return img, best


def _animated(Image, ImageSequence, src):
    """Анимация в анимированный WebP. None — она слишком велика (см. ниже).

    Кадры пишутся БЕЗ ПОТЕРЬ, и это не перестраховка. Анимация приезжает в вики
    гифкой, а в гифке на кадр приходится не больше 256 цветов — то есть плоские
    заливки и резкие границы, ровно то, что сжатие без потерь берёт лучше
    всего. Замер на записи из 12 кадров: исходный GIF 5,0 КБ, WebP с потерями
    9,1 КБ (то есть ХУЖЕ исходника и вдобавок мыльный), WebP без потерь 2,6 КБ.
    """
    frames = getattr(src, 'n_frames', 1)
    # Кадры собираются в СПИСОК, то есть в памяти лежат все сразу: сотня кадров
    # 800x600 — это почти двести мегабайт. Поэтому потолок здесь общий, на всю
    # анимацию, а не на один кадр.
    if frames > MAX_FRAMES or frames * src.width * src.height > MAX_PIXELS:
        return None

    images, durations = [], []
    for frame in ImageSequence.Iterator(src):
        # convert копирует кадр: итератор двигает ОДИН и тот же объект, и без
        # копии в списке оказалось бы N ссылок на последний кадр.
        shot = frame.convert('RGBA')
        # Размер считается по ПЕРВОМУ кадру и навязывается остальным: WebP
        # требует одинаковых габаритов у всей анимации, а подгонка каждого
        # кадра по его собственной длинной стороне дала бы разные размеры и
        # отказ кодировщика уже в конце работы.
        images.append(_fit(Image, shot) if not images
                      else (shot if shot.size == images[0].size
                            else shot.resize(images[0].size, _resample(Image))))
        durations.append(int(frame.info.get('duration') or 80))
    if not images:
        return None

    data = _encode(images[0], src.info.get('icc_profile'),
                   save_all=True, append_images=images[1:],
                   duration=durations,
                   # Ноль — «крутить бесконечно», и подставлять его по
                   # умолчанию нельзя: у GIF без блока NETSCAPE зацикливания
                   # нет вовсе, он проигрывается один раз. Подстановка нуля
                   # превратила бы разовую анимацию в вечно мигающую картинку
                   # посреди инструкции.
                   loop=int(src.info['loop']) if 'loop' in src.info else 1,
                   lossless=True, method=4, minimize_size=True)
    return images[0], data


def to_webp(data, content_type=''):
    """Картинка в WebP: (байты, 'image/webp', ширина, высота).

    None — переводить нечего (не картинка, SVG, битый файл) или нечем (нет
    Pillow). Что делать с этим, решает вызывающий: отказать в загрузке из-за
    конвертера хуже, чем положить файл исходным форматом.
    """
    pil = _pil()
    if not pil or not data:
        return None
    Image, ImageOps, ImageSequence = pil

    kind = str(content_type or '').strip().lower().split(';')[0]
    if not kind.startswith('image/') or kind in SKIP_TYPES:
        return None

    try:
        src = Image.open(io.BytesIO(data))
    except Exception:
        # Формат, который Pillow не знает (HEIC без плагина), или подпись,
        # совравшая про содержимое. Это не поломка, а «конвертировать нечего», —
        # засорять журнал трассировкой тут не за что.
        logging.info('wiki: картинку не открыть, кладём как есть (%s)', kind or '?')
        return None

    try:
        with src:
            width, height = src.size

            # Уже WebP и в габаритах — отдаём ИСХОДНЫЕ байты. Нужны от него
            # здесь только размеры: колонки width/height в wiki_files есть с
            # самого начала и до сих пор заполнялись значением NULL.
            if kind == 'image/webp' and max(width, height) <= MAX_SIDE:
                return data, 'image/webp', width, height

            animated = kind in ANIMATED_TYPES and getattr(src, 'n_frames', 1) > 1
            result = (_animated(Image, ImageSequence, src) if animated
                      else _still(Image, ImageOps, src, kind))
            if not result:
                return None
            image, encoded = result

            # Пережали, а стало ТЯЖЕЛЕЕ — значит не пережимали, а испортили.
            # Случай не гипотетический: картинка, прошедшая через мессенджер,
            # приезжает JPEG'ом невысокого качества, и второй проход через
            # кодек даёт файл до полутора раз больше исходного и вдобавок хуже
            # (потери накладываются на потери). Замер: JPEG q=50 весом 218 КБ
            # превращался в WebP на 308 КБ. Условие про размер обязательно —
            # у ужатого кадра сравнивать не с чем, там выигрыш даёт сам ресайз.
            if (image.width, image.height) == (width, height) and len(encoded) >= len(data):
                logging.info('wiki: WebP вышел не меньше исходника (%d против %d), '
                             'оставляем %s', len(encoded), len(data), kind)
                return data, kind, width, height

            return encoded, 'image/webp', image.width, image.height
    except Exception:
        logging.exception('wiki: картинка не перевелась в WebP (%s, %d байт)',
                          kind or '?', len(data))
        return None


def webp_name(original_name):
    """Имя файла с расширением .webp.

    Расширение меняется вместе с содержимым, а не остаётся исходным: из имени
    складывается путь в бакете (importer.blob_path_for), и файл «схема.png», в
    котором лежит WebP, — ровно та мелочь, на которой через полгода теряют
    полчаса, разбирая, почему «PNG не открывается». У картинок из документа имя
    вообще захардкожено строкой 'image' — им расширение появляется впервые.
    """
    base = os.path.splitext(os.path.basename(str(original_name or '')))[0].strip()
    # Имя из одних точек оставило бы файл «.webp» — скрытым в любом файловом
    # менеджере и безымянным в базе.
    return (base.strip('.') or 'image') + '.webp'
