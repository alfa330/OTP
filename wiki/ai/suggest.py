# -*- coding: utf-8 -*-
"""Подсказки на пустом экране помощника — из статей, доступных ЭТОМУ человеку.

Раньше на пустом экране висели три вопроса, зашитые в код («Как оформить возврат
депозита водителю?» и ещё два). Они были одинаковы для всех и ни на что не
опирались: у половины людей таких статей в периметре нет вовсе, и первое же
нажатие приводило к «в доступных вам статьях этого нет». Подсказка, ведущая в
отказ, хуже отсутствия подсказки — она учит, что помощник не работает.

ОТКУДА БЕРУТСЯ ВОПРОСЫ. Из двух слоёв, и оба — внутри периметра спрашивающего.

  1. Вопросительные подзаголовки статей. Замер на проде 04.09.2026: из 505
     кусков с подзаголовком 45 сформулированы вопросом («Как отвязать карту?»,
     «Почему удерживается комиссия?», «Что входит в страховку»). Это лучший
     возможный источник: вопрос написал автор статьи, ответ на него в статье
     заведомо есть, и придумывать ничего не нужно.
  2. Добор по самым читаемым статьям периметра, если подзаголовков не хватило.
     45 вопросов лежат в 18 статьях из 76, и у человека с узким периметром
     первый слой может не дать ничего.

ПОЧЕМУ НЕ ЧУЖИЕ ВОПРОСЫ. Соблазн подставлять реальные удачные вопросы других
людей проверен по базе и отвергнут: разных удачных вопросов 216, но заданных
ДВУМЯ и более людьми — два. То есть почти каждый вопрос индивидуален, и показать
его другому человеку значит показать, что спрашивал коллега. Порог «спрашивали
двое» оставил бы подсказок ровно две на всю компанию, а без порога это утечка.

ПОЧЕМУ НЕ МОДЕЛЬ. Сгенерировать вопросы по корпусу можно, но это внешний вызов
на открытие панели — при том что помощник и так держит соединение из пула на
время генерации. Слой из подзаголовков стоит один SELECT и даёт формулировки
автора статьи, а не пересказ модели.
"""

import random
import re

# Слова, с которых начинается вопрос. Знак «?» в подзаголовках ставят не всегда,
# поэтому одного его мало: «Что входит в страховку» вопрос без знака.
_QUESTION_START = (
    'как ', 'что ', 'какие ', 'какой ', 'какая ', 'какое ', 'каких ', 'кому ',
    'где ', 'когда ', 'почему ', 'зачем ', 'сколько ', 'кто ', 'чем ', 'куда ',
    'можно ли', 'нужно ли', 'нужен ли', 'нужна ли', 'есть ли', 'в каких ',
)

# Нумерованный пункт — это шаг инструкции, а не вопрос: «7. Если текст уже есть
# в документе». Как подсказка он бессмыслен, потому что вырван из порядка.
_NUMBERED = re.compile(r'^\s*\d+[.)]\s')

# Указательные слова выдают подзаголовок, который без статьи не читается:
# «Сколько это стоит» — стоит что? Такому нужен заголовок статьи впереди.
_DEMONSTRATIVE = re.compile(r'\b(это|этого|этому|этим|этот|эта|эти|такой|такое|'
                            r'него|неё|нее|них|них)\b', re.I)

MIN_LEN = 12
MAX_LEN = 90

# Длиннее этого заголовок статьи в приставку не ставится (см. _from_headings).
TITLE_PREFIX_MAX = 32

# Из скольких самых читаемых кандидатов выбираем. Берём с запасом, чтобы у
# разных людей подсказки отличались, но не настолько, чтобы доставать со дна.
HEADING_POOL = 12

# Подзаголовки идут вместе с читаемостью своей статьи и в её порядке. Это не
# украшение выдачи, а фильтр качества: вопросительных подзаголовков хватает и во
# внутренних инструкциях («Как заполнять вики» — 23 просмотра), где они звучат
# как «Что уже готово» и оператору бесполезны. Сортировка по просмотрам топит их
# сама, без списка запрещённых статей, который пришлось бы вести руками.
_HEADINGS_SQL = """
SELECT c.heading_path, a.title, count(v.id) AS views
  FROM wiki_ai_chunks c
  JOIN wiki_articles a ON a.id = c.article_id
  LEFT JOIN wiki_article_views_log v ON v.article_id = a.id
 WHERE c.article_id = ANY(%(ids)s)
   AND c.heading_path <> ''
 GROUP BY c.heading_path, a.id, a.title
 ORDER BY views DESC, a.id
"""

# Самые читаемые статьи периметра. Читаемость берём как есть из журнала
# просмотров: подсказка обязана вести туда, куда люди и так ходят, иначе она
# показывает случайный угол вики.
_POPULAR_SQL = """
SELECT a.title, count(v.id) AS views
  FROM wiki_articles a
  LEFT JOIN wiki_article_views_log v ON v.article_id = a.id
 WHERE a.id = ANY(%(ids)s)
 GROUP BY a.id, a.title
 ORDER BY views DESC, a.id
 LIMIT 40
"""


# Оформительский мусор в начале подзаголовка: «¶ Как заправляться» приезжало на
# экран вместе со знаком абзаца, скопированным из исходного документа.
_DECOR = re.compile(r'^[\s\u00b6\u2022\u2013\u2014\-–—*#>«»"\'.,:;]+')

def _clean(segment):
    """Последний уровень подзаголовка, пригодный к показу, либо None."""
    segment = (segment or '').split('>')[-1].strip()
    segment = _DECOR.sub('', segment).strip()
    if not segment or 'http' in segment.lower():
        return None
    if _NUMBERED.match(segment):
        return None
    segment = segment.rstrip(':').strip()
    if not (MIN_LEN <= len(segment) <= MAX_LEN):
        return None
    return segment


def _is_question(segment):
    low = segment.lower()
    return segment.endswith('?') or low.startswith(_QUESTION_START)


# Вопросительное слово темы не несёт: в «Что видит читатель» подлежащее только
# «читатель», и без статьи это не вопрос, а обрывок. Поэтому при счёте
# содержательных слов вопросительные не учитываются вовсе.
_INTERROGATIVE = frozenset((
    'что', 'как', 'где', 'кто', 'кому', 'чем', 'куда', 'зачем', 'когда',
    'почему', 'сколько', 'какие', 'какой', 'какая', 'какое', 'каких', 'ли',
))


def _needs_title(segment):
    """Нужен ли заголовок статьи впереди, чтобы подзаголовок читался сам по себе."""
    if _DEMONSTRATIVE.search(segment):
        return True
    # ЗНАК ВОПРОСА — признак законченной мысли. Автор, поставивший его, написал
    # вопрос целиком: «Как отвязать карту?», «Почему удерживается комиссия?».
    # Приставка такому только мешает — она превращает вопрос в строку каталога.
    # Считать слова здесь незачем: их всё равно два, и по счёту эти вопросы
    # неотличимы от обрывка «Что видит читатель», где знака как раз нет.
    if segment.endswith('?'):
        return False
    words = [w.strip('«»"\'.,:;?!()').lower() for w in re.split(r'\s+', segment)]
    meaningful = [w for w in words if len(w) >= 4 and w not in _INTERROGATIVE]
    # Меньше трёх содержательных слов — обрывок, который сам по себе не читается
    # («Сколько стоит», «Что видит читатель»). Такому нужен заголовок статьи, и
    # если заголовок в приставку не годится, кандидат выбывает: лучше меньше
    # подсказок, чем подсказка, по которой непонятно, о чём спрашивают.
    return len(meaningful) < 3


def _from_headings(cursor, article_ids):
    cursor.execute(_HEADINGS_SQL, {'ids': list(article_ids)})
    found = []
    for heading_path, title, _views in cursor.fetchall():
        segment = _clean(heading_path)
        if not segment or not _is_question(segment):
            continue
        if _needs_title(segment):
            # Приставка нужна, но длинный заголовок в неё не годится: «Информация
            # по Грузовой/Доставка/Шаттл: кто такой грузчик» читается как путь в
            # каталоге, а не как вопрос. Такой кандидат просто выбывает.
            if not title or len(title) > TITLE_PREFIX_MAX:
                continue
            text = f'{title}: {segment[0].lower()}{segment[1:]}'
            if len(text) > MAX_LEN:
                continue
        else:
            text = segment
        found.append(text)
    # Порядок из SQL — по читаемости; берём верхушку и перемешиваем уже её.
    return found[:HEADING_POOL]


def _from_popular(cursor, article_ids):
    cursor.execute(_POPULAR_SQL, {'ids': list(article_ids)})
    return [f'Что нужно знать про «{title}»?'
            for title, _views in cursor.fetchall()
            if title and len(title) <= 60]


def build(cursor, article_ids, *, limit=3, seed=0):
    """Подсказки для пустого экрана. Пустой периметр — пустой список.

    seed задаётся снаружи (пользователь + день), чтобы подсказки не были вечно
    одними и теми же и при этом не прыгали на каждом открытии панели: человек,
    у которого вопросы меняются в момент закрытия, перестаёт им доверять.
    """
    if not article_ids:
        return []

    rng = random.Random(seed)
    picked, seen = [], set()

    for pool in (_from_headings(cursor, article_ids), _from_popular(cursor, article_ids)):
        # Перемешиваем КАЖДЫЙ слой отдельно, а не общий список: иначе добор по
        # заголовкам вытеснял бы вопросы автора статьи, которые всегда лучше.
        rng.shuffle(pool)
        for text in pool:
            key = text.lower()
            if key in seen:
                continue
            seen.add(key)
            picked.append(text)
            if len(picked) >= limit:
                return picked
    return picked
