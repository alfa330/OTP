# -*- coding: utf-8 -*-
"""Актуальность фрагмента: архивный он или просроченный.

Разбор инцидента 27.08.2026. На вопрос «актуальные акции» помощник выдал таблицу
«Актуальные акции для водителей», и одной строкой в ней стояла акция «Приведи
друга» со сроком 01.03.2025-30.04.2025 — закончившаяся за шестнадцать месяцев до
вопроса. Источник строки — статья «Архивные акции TEZ» (id 731), и она
опубликована: люди должны её читать. Периметр помощника отсекает статус
'archived' (wiki/perimeter.py), но статья со словом «архивные» В НАЗВАНИИ ему
неотличима от любой другой.

Дальше по тракту признака архивности не было вовсе:

  * названия статьи нет ни в chunk_tsv (wiki/schema.py), ни в тексте эмбеддинга
    (wiki/ai/embed.py) — то есть на ранжирование слово «Архивные» не влияет
    никак, и архивный кусок конкурирует с актуальным на равных;
  * сегодняшней даты в промпте нет (wiki/ai/answer.py), поэтому «30.04.2025» для
    модели не «прошло», а просто число, которое правило 8 велит перенести
    дословно;
  * из шести постпроверок ответа ни одна не смотрит на срок, а три работают на
    стороне протухшего: ungrounded_numbers ЗАВЕРЯЕТ просроченную дату (цифры во
    фрагменте есть), _support_score даёт совпавшему числу вес 5,0 и поднимает
    архивный кусок в источники, pick_excerpt выбирает под ответ ровно строку со
    сроком — как подтверждение, а не как предупреждение.

Модуль закрывает эту дыру одним понятием — «фрагмент несвежий» — и намеренно
НИЧЕГО не выбрасывает. Выбросить нельзя: на вопрос «а была ли акция „Приведи
друга“» ответ обязан найтись, и архив для того и опубликован. Задача другая —
чтобы несвежее нельзя было выдать за действующее: оно доезжает до модели с
пометкой в подписи, а под ответ сервер сам ставит оговорку, не спрашивая модель.

Два признака, и они разной природы.

  1. АРХИВНАЯ СТАТЬЯ — тумблер редактора (wiki_articles.historical) плюс страховка
     по названию статьи и пути заголовков. Страховка нужна потому, что тумблер
     забудут: статью 731 назвали «Архивные акции TEZ» и опубликовали как обычную,
     и ровно так же назовут следующую. Признак — свойство ВСЕЙ статьи, поэтому
     считается по подписи, а не по телу куска.

  2. ИСТЁКШИЙ СРОК — дата окончания в тексте куска, которая уже прошла. Считается
     НА МОМЕНТ ВОПРОСА, а не при индексации, и поэтому не хранится в куске: срок
     истекает сам, без правки статьи, и запомненный в индексе признак протух бы
     ровно тогда, когда он и нужен.

Про точность разбора дат сказано у _END_CUE и _deadlines: ложное срабатывание
здесь дороже пропуска. Пометка «уже не действует» на действующей акции — это
оператор, который не предложит водителю живой бонус, то есть прямая потеря;
а пропущенный архив ловится вторым слоем — пометкой всей статьи.
"""

import datetime
import re

# ─────────────────────────────────────────────────────────────────────────────
# ПРИЗНАК 1: АРХИВНАЯ СТАТЬЯ ПО НАЗВАНИЮ
#
# Проверяется этот список ТОЛЬКО по названию статьи и пути заголовков — строкам
# в несколько слов. По телу куска его гонять нельзя: разведка по боевому корпусу
# показала, что скан тела помечает 32 статьи из 71 при пяти настоящих, то есть
# 27 ложных срабатываний («срок действия банковской карты», «Завершение» как шаг
# инструкции, «Период» как графа расписания). Заголовок — это ЯРЛЫК, который
# редактор повесил сознательно, и он ведёт себя предсказуемо.
#
# Первая редакция списка включала «отмен» и «заверш», и на том же корпусе это
# сразу дало ложное срабатывание: «Инструкция по Отмене/завершению корпоративного
# заказа (Эконом)» (id 13) — действующая инструкция, которую помощник объявил бы
# недействующей. Оба корня выброшены.
#
# Голое существительное «архив» ловится наравне с прилагательным, и это НЕ
# перестраховка: на проде самый крупный архивный пласт подписан именно так —
# 16 из 26 кусков статьи «Все акции» (id 33) имеют heading_path «ВСЕ ПАРКИ
# АРХИВ», и эти куски уже стали источником 62 раз в 44 ответах операторам.
# Прилагательного там нет ни одного, и правило только по «архивн» прошло бы
# мимо главного случая.
_HISTORICAL_TITLE = re.compile(
    r'(?<![а-яё])(?:арх[ие]в|неактуальн|устаревш|устарел|прошедш|бывш)[а-яё]*',
    re.I)

# Исключение к голому «архиву»: перечисление, а не ярлык.
#
# «12. Статус и архив» — раздел методички «Как заполнять вики» (id 216), где
# архив это ТЕМА раздела, а не пометка на содержимом. Отличает их предлог или
# союз прямо перед словом: ярлык вешают в конце именной группы («ВСЕ ПАРКИ
# АРХИВ»), а тему перечисляют через «и», «про», «об».
#
# Правило узкое намеренно — оно снимает ровно один ложный случай боевого корпуса
# и не трогает ни одного верного.
_HISTORICAL_TOPIC = re.compile(
    r'(?:^|[^а-яё])(?:и|или|про|об|о|пере)\s+$', re.I)

# Второе исключение — ДЕЙСТВИЕ вместо места: «Как убрать статью в архив».
# Такого заголовка в корпусе на 28.08.2026 нет, но статья «Как заполнять вики»
# (id 216) — ровно то место, где он появится следующим.
#
# Различает их падеж, и поэтому предлог здесь работает только с ГОЛЫМ
# винительным «архив»: «в архив» — куда убрать (действие), «в архиве» — где
# лежит (ярлык на содержимом). Проверять предлог без падежа было бы дороже, чем
# польза: «Акции в архиве» — законная пометка, и гасить её нельзя.
_HISTORICAL_ACTION = re.compile(
    r'(?:^|[^а-яё])(?:в|во|из|на)\s+$', re.I)


# ─────────────────────────────────────────────────────────────────────────────
# ПРИЗНАК 2: ИСТЁКШИЙ СРОК
#
# Дата берётся ТОЛЬКО с явным указателем конца перед ней. Без указателя дата в
# тексте не значит ничего: «дата запуска: 01.03.2025» и «Реестр акций от
# 24.07.2026» — прошедшие даты в совершенно живых утверждениях, а «С 28 июля
# 2025 года бонусы приостанавливаются» — прошедшая дата у правила, которое как
# раз ДЕЙСТВУЕТ. Поэтому указатель обязателен, и это главный ограничитель
# ложных срабатываний.
#
# Указатель ищется в сорока знаках ПЕРЕД датой и обязан упираться прямо в неё:
# между ним и датой допустимы только пробелы и знаки препинания. Иначе «до» из
# «до 100 заказов по 30.04.2025» цеплялось бы к чему угодно.
#
# «по» и «до» — целыми словами. Без границы «по» ловится в «поездок», «полных»,
# «после», а это половина текста про акции.
_END_CUE = re.compile(
    r'(?:^|[^0-9а-яёa-z])'
    r'(?:по|до|оконч\w*|заверш\w*|включительно|истека\w*|истек\w*|истёк\w*)'
    r'[\s:;,.\-–—«»"“”„\']*$',
    re.I)

# Сорок знаков: «дата окончания: » — шестнадцать, «действует с 01.03.2025 по » —
# двадцать шесть. Больше брать нечего, дальше начинается соседнее предложение.
_CUE_WINDOW = 40

# Год только четырьмя цифрами. Двузначный («30.04.25») не берём намеренно: в
# тексте про акции «25» с тем же успехом номер, процент или количество заказов,
# и разобрать «31.05.25» как дату — угадывание, а не разбор.
#
# Хвост — (?!\d), а НЕ \b. Первая редакция кончалась на \b, и на боевом тексте
# она не нашла ровно ту дату, из-за которой всё затевалось: в статье написано
# «дата окончания: 30.04.2025г», а между «5» и «г» границы слова нет — обе
# стороны буквенные. Русское «г» после года стоит в вике повсеместно.
_NUMERIC_DATE = re.compile(r'\b(\d{1,2})[.\-/](\d{1,2})[.\-/](\d{4})(?!\d)')

_MONTHS = ('январ', 'феврал', 'март', 'апрел', 'ма[йя]', 'июн', 'июл',
           'август', 'сентябр', 'октябр', 'ноябр', 'декабр')
_TEXT_DATE = re.compile(
    r'\b(\d{1,2})\s+(' + '|'.join(_MONTHS) + r')\w*\s+(\d{4})',
    re.I)
# Номер месяца — по ПОРЯДКУ в _MONTHS, а не по второму списку: разойдись список
# с регуляркой, и «апрель» молча стал бы мартом. Здесь тот же кортеж, из которого
# собрана регулярка, поэтому расхождение невозможно по построению.
#
# Из корня убирается класс символов: у мая альтернатива записана как «ма[йя]»,
# и корень слова — «ма». Сортировка по убыванию длины нужна ровно из-за него:
# «марта» начинается и с «март», и с «ма», и выиграть обязан длинный корень.
_MONTH_STEMS = sorted(
    ((re.sub(r'\[.*?\]', '', stem), number)
     for number, stem in enumerate(_MONTHS, start=1)),
    key=lambda item: -len(item[0]))


def today():
    """Сегодня по Алматы — тому же поясу, в котором живёт вся база раздела.

    Не date.today(): сервер стоит в UTC, и с полуночи до пяти утра по Алматы он
    отдавал бы вчерашнее число. На сроке акции это ровно один день ошибки в
    сторону «ещё действует», то есть в сторону инцидента.
    """
    return (datetime.datetime.utcnow()
            + datetime.timedelta(hours=6)).date()


def _as_date(day, month, year):
    try:
        return datetime.date(int(year), int(month), int(day))
    except ValueError:
        return None


def _has_end_cue(text, start):
    return bool(_END_CUE.search(text[max(0, start - _CUE_WINDOW):start]))


def _iter_dates(text):
    """Пары (позиция начала, дата) для обоих написаний, в порядке текста."""
    body = str(text or '')
    for match in _NUMERIC_DATE.finditer(body):
        value = _as_date(match.group(1), match.group(2), match.group(3))
        if value:
            yield match.start(), value
    for match in _TEXT_DATE.finditer(body):
        stem = match.group(2).lower()
        number = next((value for key, value in _MONTH_STEMS
                       if stem.startswith(key)), None)
        value = _as_date(match.group(1), number, match.group(3)) if number else None
        if value:
            yield match.start(), value


def all_dates(text):
    """Все распознанные даты текста, без разбора «конец это или начало».

    Нужна не свежести, а сверке чисел (answer.ungrounded_numbers): одна и та же
    дата в статье и в ответе записывается по-разному, и без приведения к общему
    виду верный ответ отбрасывается как выдуманный. См. там же.
    """
    return [value for _start, value in _iter_dates(text)]


def compact(value):
    """Дата → «ддммгггг». Общий вид для сверки написаний."""
    return value.strftime('%d%m%Y')


def deadlines(text):
    """Все даты окончания, найденные в тексте. Список объектов date.

    Только с указателем конца перед датой — см. шапку у _END_CUE. Дата без
    указателя («дата запуска: 01.03.2025») сюда не попадает вовсе.
    """
    body = str(text or '')
    return [value for start, value in _iter_dates(body)
            if _has_end_cue(body, start)]


def expiry(text, on_date=None):
    """Разбор сроков фрагмента: (истёкшие, живые). Оба — списки дат.

    Считается ПОСТРОЧНО, а не по куску целиком, и это существенно: кусок здесь —
    чаще всего таблица, развёрнутая в строки «поле: значение» (wiki/ai/tables.py),
    и в одной таблице соседствуют закончившаяся акция и действующая. По куску
    целиком побеждал бы позднейший срок, и живая строка прикрывала бы мёртвую —
    ровно тот способ спрятать протухшее, из-за которого всё и затевалось.

    Внутри ОДНОЙ строки, наоборот, побеждает позднейший срок: «до 30.04.2025,
    продлена до 31.12.2026» — это одно утверждение о продлении, а не два
    независимых, и оно живое.
    """
    edge = on_date or today()
    dead, alive = [], []
    for line in str(text or '').splitlines():
        found = deadlines(line)
        if not found:
            continue
        last = max(found)
        (dead if last < edge else alive).append(last)
    return dead, alive


def expired_on(text, on_date=None):
    """Позднейший ИСТЁКШИЙ срок фрагмента или None. Удобная обёртка над expiry."""
    dead, _alive = expiry(text, on_date)
    return max(dead) if dead else None


def historical_label(*parts):
    """Слово-маркер архива в названии статьи или пути заголовков, если оно есть."""
    for part in parts:
        text = str(part or '')
        for match in _HISTORICAL_TITLE.finditer(text):
            before = text[:match.start()]
            if _HISTORICAL_TOPIC.search(before):
                continue                 # перечисление темы, а не ярлык
            if (match.group(0).lower() == 'архив'
                    and _HISTORICAL_ACTION.search(before)):
                continue                 # «убрать в архив» — действие, не ярлык
            return match.group(0)
    return None


def chunk_currency(chunk, on_date=None):
    """Свежесть одного куска: {'stale', 'kind', 'note', 'deadline'}.

    kind:
      * 'historical' — статья помечена архивной (тумблером или названием);
      * 'expired'    — в тексте куска стоит уже прошедший срок;
      * None         — признаков нет.

    Архив ПЕРЕВЕШИВАЕТ срок: если статья архивная, «срок истёк такого-то» ниже
    по силе утверждения, чем «эти сведения вообще не действуют», а показывать
    модели две пометки на одном фрагменте значит спорить с самим собой.

    note — готовая строка для подписи фрагмента и для оговорки под ответом.
    Собирается здесь, а не в двух местах: разойдись формулировки, оператор
    увидел бы в ответе одно, а в источниках другое.
    """
    marker = None
    if chunk.get('historical'):
        marker = 'помечена архивной'
    else:
        word = historical_label(chunk.get('title'), chunk.get('heading_path'))
        if word:
            marker = 'архивная по названию'
    if marker:
        return {'stale': True, 'kind': 'historical', 'deadline': None,
                'note': 'АРХИВ — сведения уже не действуют'}

    # Срок ищем и в ПУТИ ЗАГОЛОВКОВ, а не только в теле. На проде у статьи
    # «Яндекс Заправка» (id 604) верхняя граница стоит именно там: heading_path
    # = «¶ Баллы приоритета > ¶ До 15.05.2025 есть возможность получить +6
    # балла…». Мало того что в теле её нет — путь заголовков идёт в FTS с весом
    # B против D у текста, то есть протухший кусок этой строкой ещё и
    # поднимается в выдаче.
    dead, alive = expiry('%s\n%s' % (chunk.get('heading_path') or '',
                                     chunk.get('text') or ''), on_date)
    if not dead:
        return {'stale': False, 'kind': None, 'deadline': None, 'note': ''}
    deadline = max(dead)
    if alive:
        # Смешанный кусок: часть строк живая. Называть его «срок истёк» целиком
        # было бы неправдой в другую сторону — модель выбросила бы и живые
        # строки, а оператор не предложил бы водителю действующий бонус.
        return {'stale': True, 'kind': 'expired', 'deadline': deadline,
                'note': 'ЧАСТЬ СРОКОВ ИСТЕКЛА, последний %s — сверь даты по строкам'
                        % deadline.strftime('%d.%m.%Y')}
    return {'stale': True, 'kind': 'expired', 'deadline': deadline,
            'note': 'СРОК ИСТЁК %s' % deadline.strftime('%d.%m.%Y')}


def mark_chunks(chunks, on_date=None):
    """Проставить свежесть каждому куску. Возвращает НОВЫЙ список.

    Куски приходят из поиска словарями и дальше живут в подписи промпта, в
    источниках и в журнале — считать свежесть в каждом из этих мест значило бы
    завести три копии правила. Считается один раз, здесь.
    """
    out = []
    for chunk in chunks:
        state = chunk_currency(chunk, on_date)
        out.append({**chunk, 'stale': state['stale'],
                    'stale_kind': state['kind'],
                    'stale_note': state['note']})
    return out


def stale_titles(sources, kind=None):
    """Названия статей-источников, которые несвежие. Для оговорки под ответом.

    kind сужает до одного вида ('historical' | 'expired'): оговорка про архив и
    оговорка про истёкший срок — разные утверждения, и валить их в одну фразу
    значит говорить неправду про половину случаев.
    """
    titles = []
    for source in sources:
        if not source.get('stale'):
            continue
        if kind and source.get('stale_kind') != kind:
            continue
        title = source.get('title') or ''
        if title and title not in titles:
            titles.append(title)
    return titles
