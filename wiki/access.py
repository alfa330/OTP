def _merge_grants(rules):
    """ИЛИ по правам всех разрешающих правил."""
    result = dict(NO_PERMISSIONS)
    for rule in rules:
        for name in PERMISSION_COLUMNS:
            if rule.get(name):
                result[name] = True
    return result


def _collect_denials(rules):
    """Набор прав, которые хотя бы одно deny-правило запрещает."""
    denied = set()
    for rule in rules:
        if rule.get('mode') != 'deny':
            continue
        for name in PERMISSION_COLUMNS:
            # В deny-правиле отмеченное право означает «запретить именно его».
            if rule.get(name):
                denied.add(name)
    return denied


def resolve_article_permissions(*, capabilities, visibility_mode='inherit',
                                strict_mode=False, section_rules=(), article_rules=(),
                                otp_role=None, is_section_owner=False,
                                is_article_owner=False, guest_allows_read=False):
    """Эффективные права на конкретную статью.

    section_rules  — правила разделов, которым принадлежит статья (только grant).
    article_rules  — правила самой статьи, каждое с полем mode ('grant'|'deny').

    Возвращает (permissions, reason), где reason — короткая строка, объясняющая
    решение. Она нужна эндпоинту /api/wiki/access/effective: когда уровней прав
    четыре, администратору необходим ответ на вопрос «почему он это видит».
    """
    role = normalize_role(otp_role)
    is_super_admin = role == 'super_admin'
    is_wiki_admin = bool(capabilities.get('can_manage_access'))

    grants = [r for r in article_rules if r.get('mode') != 'deny']
    denials = _collect_denials(article_rules)

    if visibility_mode == 'restricted':
        permissions = _merge_grants(grants)
        reason = 'правила статьи (режим «только по списку»)'
    else:
        permissions = _merge_grants(list(section_rules) + grants)
        reason = 'правила разделов статьи'
        if grants:
            reason = 'правила разделов + правила статьи'

    # Владелец раздела и автор статьи всегда могут её читать и править:
    # иначе человек способен потерять доступ к тому, что сам ведёт.
    if is_section_owner or is_article_owner:
        permissions['can_read'] = True
        permissions['can_edit'] = True
        reason = 'владелец раздела' if is_section_owner else 'автор статьи'

    if guest_allows_read and not permissions['can_read']:
        permissions['can_read'] = True
        reason = 'гостевой доступ'

    # Запреты сильнее разрешений.
    if denials:
        for name in denials:
            permissions[name] = False
        reason = 'запрещено правилом статьи'

    # Право записи требует и глобальной способности, и разрешения на объекте.
    #
    # Исключение — владелец раздела и автор статьи. Их назначили поимённо, и
    # выше об этом сказано «всегда могут её читать и править», но до 21.08.2026
    # строчкой ниже это гасилось: у оператора и стажёра способности can_edit
    # нет, и назначенный владельцем раздела человек молча терял свой же раздел.
    # Запрет правилом при этом сильнее и здесь — он применён ВЫШЕ, и если
    # can_edit уже сняли, воскрешать нечего.
    owner_may_edit = (is_section_owner or is_article_owner) and permissions['can_edit']
    for name in ('can_create', 'can_edit', 'can_delete', 'can_publish', 'can_approve'):
        if permissions[name] and not capabilities.get(name):
            permissions[name] = False
    if owner_may_edit:
        permissions['can_edit'] = True

    # Обход администратора. strict_mode оставляет эту дверь только super_admin.
    bypassed = False
    if strict_mode:
        if is_super_admin:
            permissions = {name: True for name in PERMISSION_COLUMNS}
            reason = 'обход super_admin (статья в строгом режиме)'
            bypassed = True
    elif is_wiki_admin:
        permissions = dict(permissions)
        permissions['can_read'] = True
        for name in PERMISSION_COLUMNS:
            if capabilities.get(name):
                permissions[name] = True
        if denials:
            reason = 'администратор вики (перекрывает запрет)'
            bypassed = True
        else:
            reason = 'администратор вики'

    permissions['_reason'] = reason
    permissions['_bypassed_restriction'] = bypassed
    return permissions


def permissions_only(permissions):
    """Отбрасывает служебные поля _reason/_bypassed_restriction."""
    return {name: bool(permissions.get(name)) for name in PERMISSION_COLUMNS}


# ─────────────────────────────────────────────────────────────────────────────
# Кто кому может выдавать доступ («зернистость»)
# ─────────────────────────────────────────────────────────────────────────────
#
# Решение владельца 18.08.2026: право раздавать доступ само ограничено
# должностью раздающего.
#
#     Коммерческий директор  → ЛЮБОЙ сотрудник, включая других директоров
#     Руководитель группы    → СВОЙ ОТДЕЛ ЦЕЛИКОМ: другой руководитель, СВ,
#                              тренер, оператор
#     Супервайзер            → оператор
#     Тренер, оператор       → не раздают вовсе, только читают
#
# Таблица, а не арифметика «на ступень ниже»: у супервайзера ступенька
# ПЕРЕПРЫГИВАЕТ тренера. Это не описка — так сформулировал владелец: СВ
# раздаёт операторам, тренера не трогает. Вывести это формулой нельзя, а
# формула, которая «почти совпадает», разошлась бы с решением молча.
#
# РУКОВОДИТЕЛЬ ВЫДАЁТ И СВОЕМУ УРОВНЮ (решение владельца 21.08.2026):
# «руководитель выше СВ и оператора — значит он сам выдаёт им доступы и
# правила, и конкретным людям своего отдела». Прежний потолок 30 запирал в
# матрице строку «Руководитель группы» («не ваш уровень») и вычёркивал из
# списка сотрудников коллег-руководителей — то есть отдел, за который он
# отвечает, он же и не мог настроить целиком.
#
# Возражение «расширяет собственный круг» здесь не работает, потому что
# руководителя держит ВТОРАЯ граница — отдел (_grant_departments в
# routes_structure): правило уровня 40 он пишет на ветку своего отдела, и
# открывает оно раздел руководителям ЭТОГО отдела, а не всей компании. У
# супервайзера такой брони нет — правило без порога адресовано всему отделу
# сразу, поэтому свой уровень ему по-прежнему закрыт.
#
# Отдел берётся из ветки раздела (structure.section_branch_department), а не
# из должности, поэтому СЗоВ и ОП работают одинаково и без отдельной ветки в
# коде: руководитель СЗоВ настраивает разделы под «СЗоВ», руководитель ОП —
# под «ОП», и чужую ветку ни один из них не видит.
#
# ДИРЕКТОР ВЫДАЁТ И СВОЕМУ УРОВНЮ — «может добавить любого сотрудника»
# (дословное требование владельца). Правило «никто не выдаёт своему уровню»
# действует ниже по лестнице, но наверху лишено смысла: над директором никого
# нет, эскалировать некуда, а супер-админ и так видит все разделы
# (queries.from_super_admin). Потолок 40 отрезал от списка пятерых
# супер-админов, и владелец не смог выписать правило на коллегу.
#
# Значение — максимальный уровень, которому носитель роли вправе открыть
# раздел. Роли, которой в таблице нет, выдавать нельзя вообще.
GRANT_CEILING = {
    'super_admin': 50,
    'admin': 40,          # свой отдел целиком, включая других руководителей
    'sv': 10,             # только оператор; тренер (20) пропущен намеренно
    'supervisor': 10,
}

# Правило без порога открывает раздел всем от оператора и выше, поэтому его
# «вес» равен уровню оператора. Отдельная константа, чтобы NULL не превращался
# в ноль где-нибудь по дороге: ноль пропустил бы любую проверку.
UNBOUNDED_RULE_LEVEL = ROLE_LEVELS['operator']


def grant_ceiling(otp_role, *, is_wiki_admin=False):
    """До какого уровня должности человек вправе открывать разделы.

    None — не вправе вовсе. is_wiki_admin (способность can_manage_access,
    выданная РОЛЬЮ ВИКИ, а не должностью) поднимает потолок до максимума:
    администратора вики назначают руками именно для этого.
    """
    if is_wiki_admin:
        return ROLE_LEVELS['super_admin']
    return GRANT_CEILING.get(normalize_role(otp_role))


def rule_grant_level(min_role_level):
    """Уровень, которому правило фактически открывает раздел."""
    return UNBOUNDED_RULE_LEVEL if min_role_level is None else int(min_role_level)


def may_grant_with_ceiling(ceiling, min_role_level, target_role=None):
    """Проходит ли правило под уже посчитанный потолок.

    Потолок приходит готовым, а не выводится из роли второй раз: роут считает
    его один раз на запрос (там же решается вопрос про роль вики), и повторный
    вывод — это второй источник истины, который однажды разойдётся с первым.

    target_role — роль КОНКРЕТНОГО адресата (правило на человека). Без неё
    супервайзер выписал бы правило subject_type='user' на самого себя и выдал
    бы себе полный доступ к любому разделу: порог там NULL, и одна лишь
    проверка порога такое пропускает.
    """
    if ceiling is None:
        return False
    if rule_grant_level(min_role_level) > ceiling:
        return False
    if target_role is not None and role_level_of(target_role) > ceiling:
        return False
    return True


def may_grant_rule(otp_role, min_role_level, *, is_wiki_admin=False,
                   target_role=None):
    """Вправе ли носитель роли выписать такое правило."""
    return may_grant_with_ceiling(
        grant_ceiling(otp_role, is_wiki_admin=is_wiki_admin),
        min_role_level, target_role)


# ─────────────────────────────────────────────────────────────────────────────
# РАЗДЕЛ, СТОЯЩИЙ ВЫШЕ САМОГО РАЗДАЮЩЕГО
# ─────────────────────────────────────────────────────────────────────────────
#
# Решение владельца 25.08.2026, дословно: «у супервайзера есть доступ на то,
# чтобы предоставить доступ для чтения в разделе руководителя — это неправильно,
# он может предоставить только доступ к своему разделу и ниже, но никак не выше;
# та же ситуация с руководителями группы».
#
# До этого дня раздел проверялся ОДНОЙ границей — отделом ветки. Дерево вики
# повторяет оргструктуру («Руководитель группы» → «Супервайзер» → «Оператор»
# внутри ветки отдела), поэтому раздел руководителя лежит в том же отделе, что и
# раздел супервайзера, — граница пропускала, и супервайзер СЗоВ открывал
# руководительский раздел кому хотел внутри своего отдела.
#
# Потолок GRANT_CEILING этой двери не закрывал и закрыть не мог: он отвечает на
# вопрос «КОМУ по чину», а не «ГДЕ». Правило без порога весит как оператор
# (UNBOUNDED_RULE_LEVEL) и проходит даже супервайзерский потолок 10 — то есть
# именно самая широкая выдача и была самой проходимой.
#
# ЧЕМ ИЗМЕРЯЕТСЯ ВЫСОТА РАЗДЕЛА. Порогом должности в его собственных правилах:
# min_role_level — это и есть лестница («ниже какого уровня должности правило не
# действует», wiki/schema.py), другого признака ранга у раздела в модели нет.
# Берём МИНИМУМ по правилам НА ЧТЕНИЕ: раздел «Руководитель группы» открыт одним
# правилом с порогом 40 — значит это раздел уровня 40; «Оператор» открыт
# правилами 20, 30 и 40 — значит его читают с уровня 20, и супервайзер там свой.
#
# Правила БЕЗ порога в счёт не идут. Это именные исключения («открыть регламент
# конкретному оператору»), и считай мы их за уровень оператора, одно такое
# правило обнуляло бы ранг раздела ровно там, где он и нужен.
#
# Раздел, у которого порога нет ни в одном правиле (ветка отдела, витрина
# верхнего уровня), высоты не имеет — границей ему остаётся отдел, как и раньше.
# Иначе супервайзер лишился бы вкладки «Структура» целиком: правил на чтение ему
# может не быть выписано вовсе, а настраивать свою ветку он обязан (см.
# routes_structure — «раздел, которым человек управляет, остаётся в ответе,
# даже если он его не читает»).
#
# ПОЧЕМУ НЕ «РАЗДАВАТЬ МОЖНО ТАМ, ГДЕ САМ ЧИТАЕШЬ». Соседняя формулировка,
# заманчивая и неверная в обе стороны: читать раздел можно по именной выдаче и
# по гостевому доступу на две недели — раздавать в нём права от этого нельзя;
# а ветку своего отдела без единого правила супервайзер не читает — настраивать
# её всё равно должен он.
def may_manage_section_level(otp_role, section_role_level, *, unbounded=False):
    """Не выше ли раздел самого раздающего.

    section_role_level — уровень должности, с которого раздел читают (минимум
    порогов его правил); None — раздел уровня не имеет и этой границей не
    закрыт.

    Сравнение НЕСТРОГОЕ: свой раздел настраивает и супервайзер, и руководитель
    группы — «свой и ниже» сказано владельцем прямо. Строгое сравнение оставило
    бы каждого управлять только чужим, нижним разделом.

    unbounded — мастер-ключ (супер-админ, роль вики с can_manage_access): у него
    сняты и потолок, и граница отдела, снимается и эта.
    """
    if unbounded:
        return True
    if section_role_level is None:
        return True
    return role_level_of(otp_role) >= int(section_role_level)


# ─────────────────────────────────────────────────────────────────────────────
# Гостевой доступ: кто выдаёт и кому
# ─────────────────────────────────────────────────────────────────────────────
#
# Таблица, а не арифметика «на ступень ниже», — по той же причине, что и у
# GRANT_CEILING выше: у супервайзера ступенька ПЕРЕПРЫГИВАЕТ тренера. Владелец
# перечислил роли поимённо 25.08.2026:
#
#     Коммерческий директор  → ВСЕМ, включая других директоров
#     Руководитель           → супервайзерам и операторам
#     Супервайзер            → операторам
#     Тренер, оператор       → не выдают вовсе
#
# Формула, которая «почти совпадает», разошлась бы с этим решением молча.
#
# Ниже супервайзера право не опускается вообще: раздел «Гостевой доступ» виден
# супервайзеру и выше, и это тот же список. Одна таблица на оба вопроса — «вижу
# ли я раздел» и «кому вправе выдать», — потому что вопрос по сути один.
#
# Прежний механизм — тумблер в правиле раздела (wiki_section_access_rules.
# can_grant_guest) — снят 25.08.2026 тем же решением. Он давал право адресно, в
# обход должности, и с появлением лестницы стал вторым источником истины о том
# же самом: два механизма на одно право однажды разойдутся, и разойдутся молча.
GUEST_GRANT_CEILING = {
    'super_admin': ROLE_LEVELS['super_admin'],  # «может всем»
    'admin': ROLE_LEVELS['sv'],                 # супервайзер и ниже
    'sv': ROLE_LEVELS['operator'],
    'supervisor': ROLE_LEVELS['operator'],
}


def guest_grant_ceiling(otp_role, *, is_wiki_admin=False):
    """До какого уровня должности человек вправе выдавать гостевой доступ.

    None — не вправе вовсе, и по этому же признаку прячется весь раздел
    «Гостевой доступ». is_wiki_admin (способность can_manage_access, пришедшая
    РОЛЬЮ ВИКИ, а не должностью) поднимает потолок до максимума: администратора
    вики назначают руками именно за этим, и должность у него бывает любая.
    """
    if is_wiki_admin:
        return ROLE_LEVELS['super_admin']
    return GUEST_GRANT_CEILING.get(normalize_role(otp_role))


def may_grant_guest_to(actor_role, target_role, *, is_wiki_admin=False):
    """Вправе ли носитель роли выдать гостевой доступ этому человеку.

    Только «по чину». Второй вопрос — «своим ли людям» — задаётся отдельно и
    отделом (may_grant_guest_in_department ниже): у директора потолок максимален,
    но и границы отдела у него нет, а у супервайзера ограничены оба измерения.
    """
    ceiling = guest_grant_ceiling(actor_role, is_wiki_admin=is_wiki_admin)
    if ceiling is None:
        return False
    target = normalize_role(target_role)
    # Незнакомая роль не проходит. Без этой строки её ноль от role_level_of
    # оказался бы меньше любого потолка — то есть опечатка в должности
    # проходила бы проверку, которая должна была её отклонить.
    if target not in ROLE_LEVELS:
        return False
    return role_level_of(target) <= ceiling


def may_grant_guest_in_department(department_id, grant_departments):
    """Свой ли это человек. «СВ из СЗоВ видит операторов СЗоВ» (владелец, 25.08.2026).

    grant_departments — отделы, внутри которых человек раздаёт; None означает
    «без границы» (коммерческий директор и администратор вики — им сказано
    «может всем»).

    Отдела нет — под границу не проходит: пустое поле это «неизвестно чей», а не
    «ничей». То же правило и по той же причине, что в may_grant_to_subject.
    """
    if grant_departments is None:
        return True
    try:
        department = int(department_id)
    except (TypeError, ValueError):
        return False
    return department in {int(value) for value in grant_departments}


# ─────────────────────────────────────────────────────────────────────────────
# Граница отдела для АДРЕСАТА правила
# ─────────────────────────────────────────────────────────────────────────────
#
# Потолок должности отвечает на вопрос «кому по чину», отдел — на вопрос «чьим
# людям». Второй вопрос до 21.08.2026 задавался только правилу на КОНКРЕТНОГО
# ЧЕЛОВЕКА, а у остальных субъектов адресат не проверялся вовсе. Проверялся
# лишь РАЗДЕЛ (его ветка отдела), и это оставляло дверь настежь: супервайзер
# СЗоВ на своём же разделе «Оператор» мог выписать правило на отдел продаж, на
# чужую группу или на чужое направление — то есть открыть свою ветку соседям.
#
# Хуже того, роль в системе и роль вики адресуют людей ПО ВСЕЙ КОМПАНИИ: у
# правила otp_role='operator' без порога нет ни отдела, ни границы — оно
# открывает раздел каждому сотруднику, включая отделы, которым вики не
# показывают вовсе. Форма предлагала оба субъекта наравне с остальными, так что
# дойти до этого можно было в два нажатия, не имея никакого умысла.
#
# Поэтому раздающий С ГРАНИЦЕЙ (супервайзер, руководитель — все, у кого
# _grant_departments вернул список) адресует правило только своему отделу:
# людям, группам, направлениям и самому отделу. Директору и администратору вики
# границы нет — у них _grant_departments отдаёт None, и здесь ничего не меняется.
COMPANY_WIDE_SUBJECTS = ('otp_role', 'wiki_role')


def may_grant_to_subject(subject_type, *, grant_departments,
                         subject_department=None):
    """Проходит ли АДРЕСАТ правила под границу отдела раздающего.

    grant_departments — отделы, внутри которых человек вправе настраивать
    доступ; None означает «без границы».
    subject_department — отдел самого адресата: для субъектов 'department' и
    'department_head' это он сам, для человека, группы и направления — их отдел
    (его достаёт вызывающий, здесь только решение).

    Отдел, которого нет (адресат без отдела), под границу не проходит: пустое
    поле — это «неизвестно чей», а не «ничей».
    """
    if grant_departments is None:
        return True
    if subject_type in COMPANY_WIDE_SUBJECTS:
        return False
    try:
        department = int(subject_department)
    except (TypeError, ValueError):
        # Отдела нет или он не число — граница не пройдена. Не исключение:
        # значение приходит из базы, и «неизвестно чей» обязано читаться как
        # отказ, а не как пятисотка на пустом поле.
        return False
    return department in {int(value) for value in grant_departments}


# ─────────────────────────────────────────────────────────────────────────────
# ЖУРНАЛ
# ─────────────────────────────────────────────────────────────────────────────
#
# «Возможность просматривать журнал начиная с должности СВ и выше» — решение
# владельца 25.08.2026. До этого журнал открывала способность can_manage_access,
# то есть его видел администратор доступов и супер-админ с мастер-ключом, а
# супервайзер — нет.
#
# Право живёт в ДОЛЖНОСТИ, а не в способностях, по той же причине, что и
# гостевая выдача: «кому по чину» и «что человек делает с содержимым» — разные
# вопросы, и способностью первый не выражается. Правилом раздела такое право
# тоже не поднять — can_manage_access нет в PERMISSION_COLUMNS.
#
# Администратор доступов остаётся в списке отдельной веткой: журнал у него уже
# был, и отнимать его вместе с расширением доступа было бы регрессом.
AUDIT_MIN_LEVEL = ROLE_LEVELS['sv']


def may_read_audit(otp_role, *, is_wiki_admin=False):
    """Вправе ли человек читать журнал раздела.

    is_wiki_admin — способность can_manage_access, пришедшая РОЛЬЮ ВИКИ: её
    носителя назначают руками, и должность у него бывает любая.

    'supervisor' приводится к 'sv' ЗДЕСЬ, а не в normalize_role: в ROLE_LEVELS
    этой роли нет (уровень 0), но в CHECK на users.role она есть, и без
    приведения носитель такого написания не прошёл бы проверку, которую
    владелец описал как «СВ и выше». Глобально их не сливаем намеренно —
    expand_otp_roles на этом различии стоит (см. шапку ROLE_LEVELS).
    """
    if is_wiki_admin:
        return True
    role = normalize_role(otp_role)
    if role == 'supervisor':
        role = 'sv'
    return role_level_of(role) >= AUDIT_MIN_LEVEL
