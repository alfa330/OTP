"""Чистая логика прав раздела «Вики».

Модуль намеренно НЕ импортирует ни database, ни flask, ни bot_schedule2:
импорт database.py открывает пул к боевой БД, из-за чего тесты проекта вынуждены
парсить его через ast. Здесь только функции над данными — их можно импортировать
в тестах напрямую и гонять без базы.

Всё, что требует SQL (собрать группы пользователя, вытащить правила), живёт в
методах Database и передаётся сюда готовыми структурами.

── Порядок вычисления прав на статью ────────────────────────────────────────
1. Собрать субъекты пользователя: отдел + возглавляемые отделы, направление,
   активные группы (как оператор и как супервайзер), роль + все роли ниже по
   иерархии, роли вики, сам пользователь.
2. Если у статьи visibility_mode='restricted' — база берётся ТОЛЬКО из правил
   статьи; правила разделов игнорируются. Иначе — ИЛИ по правилам всех разделов
   статьи, а правила статьи применяются поверх как оверрайд.
3. Правило mode='deny' сильнее любого grant. Без этого нельзя выразить «скрыть
   от одного человека внутри разрешённого отдела».
4. Способность can_manage_access обходит deny — иначе администратор способен
   заблокировать сам себя без возможности восстановить. Но strict_mode обходит
   только super_admin, и такой обход обязан попасть в журнал.
"""

from .schema import CAPABILITY_COLUMNS, PERMISSION_COLUMNS

# Копия ROLE_HIERARCHY из bot_schedule2.py:1501. Дублируется сознательно —
# импортировать bot_schedule2 отсюда нельзя (он поднимает Flask и бота).
# ВНИМАНИЕ: роли 'supervisor' в иерархии OTP нет (её уровень 0), хотя в CHECK
# на users.role она присутствует. Поэтому правило на 'operator' НЕ
# распространяется на 'supervisor' автоматически — см. expand_otp_roles.
ROLE_LEVELS = {
    'operator': 10,
    'trainee': 10,
    # Отделы без линии (Бухгалтерия, HR, Маркетинг). Десятка обязательна: на
    # ней expand_otp_roles подводит их под уже написанные правила на
    # 'operator', а role_level_of перестаёт возвращать 0 — иначе вика у
    # них была бы пустой, не пройдя ни одного min_role_level.
    # Эту же таблицу читает news/access.py — без строки роль перестала бы
    # быть адресатом «Новости дня».
    'hr_manager': 10,
    'accounting_manager': 10,
    'marketing_manager': 10,
    'trainer': 20,
    'sv': 30,
    'admin': 40,
    'super_admin': 50,
}

# Должности, которым вход в чувствительные разделы открывает подтверждение QR.
# Явный список, а не «все, кроме начальства»: неизвестная роль не должна
# получать доступ молча, но и запирать по ошибке нового admin'а перечисление не
# даст. Стажёра здесь намеренно нет — до появления бэк-офиса гейт стоял ровно
# на 'operator', и расширять его заодно значило бы менять чужое правило.
#
# 'marketing_manager' здесь ОБЯЗАТЕЛЕН, и это не «по аналогии»: сегодня люди
# «Маркетинга» заведены обычными 'operator' и подтверждение QR проходят.
# Перевод их на собственную должность без этой строки снял бы подтверждение
# молча — тот же дефект, что был у 'trainee' в «Посылках».
QR_GATED_ROLES = frozenset({'operator', 'hr_manager', 'accounting_manager', 'marketing_manager'})


def role_level_of(role):
    """Уровень должности по шкале ROLE_LEVELS. Незнакомая роль — 0.

    Ноль, а не None: уровень участвует в сравнении `уровень >= min_role_level`,
    и незнакомая роль обязана не проходить ни одно ограничение по уровню.
    """
    return ROLE_LEVELS.get(normalize_role(role), 0)


NO_PERMISSIONS = {name: False for name in PERMISSION_COLUMNS}
NO_CAPABILITIES = {name: False for name in CAPABILITY_COLUMNS}


# В базе исторически встречаются оба написания. _normalize_user_role
# (bot_schedule2.py:1492) приводит их к канону — повторяем то же самое, иначе
# носитель роли 'superadmin' не подпал бы ни под одно правило.
_ROLE_ALIASES = {
    'superadmin': 'super_admin',
    'super admin': 'super_admin',
}


def normalize_role(role):
    value = str(role or '').strip().lower()
    return _ROLE_ALIASES.get(value, value)


# ─────────────────────────────────────────────────────────────────────────────
# QR-подтверждение сессии
# ─────────────────────────────────────────────────────────────────────────────

def requires_sensitive_qr(otp_role, *, is_department_head=False):
    """Нужно ли оператору подтвердить сессию QR-кодом, чтобы раздел открылся.

    Вики — это база знаний компании целиком: регламенты, тарифы, инструкции,
    телефоны офисов и парков. Читать её должен человек за рабочим местом и с
    ведома старшего, а не любая забытая открытой сессия.

    Ключ общий с «Моими оценками» и «Обращениями» (bot_schedule2:
    sensitive-access): QR генерирует сам оператор, подтверждает админ или
    супервайзер, доступ живёт до конца ЭТОЙ сессии. Своего второго ключа раздел
    не заводит намеренно — два разных QR на один экран человек не различит.

    Гейт стоит ДО прав раздела и статьи, а не вместо них: подтверждённая сессия
    открывает ровно тот же периметр, что и был, — не больше.

    Роли вики (wiki_roles) на это не влияют: они раздают способности внутри
    раздела, а речь о входе в раздел с рабочего места. Главу отдела и
    администратора гейт не касается — подтверждать доступ им не у кого.
    """
    if is_department_head:
        return False
    # Бэк-офис здесь наравне с операторами. Их роль отделена от
    # 'operator' ради разделов и полей карточки, а не ради этого гейта:
    # переименование должности не повод молча снять подтверждение,
    # которое до него действовало.
    return normalize_role(otp_role) in QR_GATED_ROLES


# ─────────────────────────────────────────────────────────────────────────────
# Способности (глобальные, не привязаны к разделу)
# ─────────────────────────────────────────────────────────────────────────────

def capabilities_from_otp_role(role, is_department_head=False):
    """Способности по умолчанию, когда у человека нет ни одной роли вики.

    Заменяет getLegacyCapabilities оригинала, где ролевая модель была второй,
    параллельной, и расходилась с основной.

    is_department_head — глава отдела. В OTP это НЕ роль, а поле
    headed_department_id в профиле, и isAdminLikeRole специально вычитает таких
    из глобальных админов. На способности он с 21.08.2026 не влияет: любой
    руководитель, с возглавляемым отделом или без, ведёт содержимое и не трогает
    структуру. Параметр оставлен — его передают все вызывающие, и он же отвечает
    за QR-гейт (requires_sensitive_qr).
    """
    role = normalize_role(role)
    caps = dict(NO_CAPABILITIES)

    if not role:
        return caps

    # Читать может любой аутентифицированный сотрудник; что именно он увидит,
    # решают правила разделов и статей, а не эта способность.
    caps['can_read'] = True

    if role == 'super_admin':
        for name in CAPABILITY_COLUMNS:
            caps[name] = True
        return caps

    # Руководитель ведёт СОДЕРЖИМОЕ, а не устройство раздела — решение
    # владельца 21.08.2026: «руководитель не может добавлять разделы и
    # подразделы, не может их удалять либо править, только раздавать доступы;
    # к другому отделу он не может притронуться, ему доступен свой отдел».
    #
    # Поэтому у роли 'admin' нет ни can_manage_structure (дерево разделов —
    # только у директора), ни can_manage_users (роли вики), ни мастер-ключа
    # can_manage_access. Мастер-ключ убран не «за компанию»: именно он открывал
    # руководителю ЧУЖИЕ отделы — витрину `?scope=all`, обход запретов в
    # resolve_article_permissions и признак master_key в периметре. Право
    # раздавать доступ у него осталось, но идёт оно теперь по лестнице
    # (GRANT_CEILING) и только внутри своего отдела.
    #
    # Статьи он по-прежнему заводит, правит, публикует и согласовывает — там,
    # где это разрешено ПРАВИЛОМ раздела: правила «Оператор», «Супервайзер» и
    # «Общий сотрудник» такие права ему дают, а чужая ветка правила не имеет и
    # закрыта. Глава отдела и руководитель без отдела теперь неотличимы:
    # границу держит правило раздела, а не отдельная ветка в способностях.
    if role == 'admin':
        caps.update(can_create=True, can_edit=True, can_delete=True,
                    can_publish=True, can_approve=True)
        return caps

    # Супервайзер ведёт содержимое своего направления целиком, включая выпуск:
    # решение владельца 19.08.2026. До него способность публиковать была только
    # у админов, и выданное в ПРАВИЛЕ РАЗДЕЛА can_publish молча гасилось ниже
    # (право записи требует и правила, и способности) — владелец выдал право в
    # интерфейсе, правило сохранилось, а портал продолжал отвечать «нет права
    # публиковать в этом разделе». Способность — это «вправе ли в принципе»,
    # а где именно, по-прежнему решают правила разделов: там, где can_publish
    # не выписан (например «Оператор» без соответствующего правила), публикации
    # не будет.
    if role in ('sv', 'supervisor'):
        caps.update(can_create=True, can_edit=True,
                    can_publish=True, can_approve=True)
        return caps

    # Тренер остаётся без публикации намеренно: он ведёт обучение, а не выпуск
    # регламентов, и в «Ивентах» право публикации ему тоже не дано.
    if role == 'trainer':
        caps.update(can_create=True, can_edit=True)
        return caps

    # operator, trainee и всё неизвестное — только чтение.
    return caps


def has_write_capability(capabilities):
    """Есть ли у человека хоть одна способность СВЕРХ чтения.

    Этим гейтятся справочники «Парки» и «Офисы» (решение владельца 19.08.2026):
    их правит всякий, кто вообще что-то делает с содержимым, а не только
    носитель can_manage_structure. Раньше супервайзер и тренер могли завести и
    отредактировать статью, но не могли поправить телефон парка — хотя это тот
    же справочный контент, и держать его в актуальном виде некому, кроме них.

    Считается по фактическим способностям, а не по списку ролей: способности
    могут прийти и от роли вики, назначенной руками, и такой человек тоже
    должен попадать под правило.

    ВАЖНО, какой словарь сюда подавать. С 21.08.2026 способности бывают двух
    видов: должностные (ctx['role_capabilities']) и итоговые (ctx['capabilities'],
    туда входят и права, выписанные ПРАВИЛАМИ разделов — queries.load_capabilities).
    Справочники подают ИТОГОВЫЕ: решение владельца 21.08.2026 — «правит всякий,
    кому право выписали, неважно, должностью или правилом». Порог тот же, что и
    был, шире стал источник права.

    Любой НОВЫЙ общекомпанейский гейт обязан сделать этот выбор осознанно, а не
    по умолчанию: у назначения обязательного чтения, например, выбор обратный
    (routes_ack: capability_from_role=True) — оно про людей, а не про содержимое.
    """
    return any(capabilities.get(name) for name in CAPABILITY_COLUMNS
               if name != 'can_read')


def merge_capabilities(*sources):
    """ИЛИ по способностям. Deny-правил на уровне способностей нет и не будет:
    в оригинале их тоже нет, а вводить второй механизм запрета — путь к тому,
    что две проверки разойдутся."""
    result = dict(NO_CAPABILITIES)
    for source in sources:
        if not source:
            continue
        for name in CAPABILITY_COLUMNS:
            if source.get(name):
                result[name] = True
    return result


def resolve_capabilities(otp_role, wiki_role_rows, is_department_head=False):
    """Итоговые способности: роли вики, а при их отсутствии — роль OTP.

    wiki_role_rows — список словарей из wiki_roles (уже отфильтрованных по
    пользователю). Пустой список означает «ролей вики не назначено».
    """
    if wiki_role_rows:
        merged = merge_capabilities(*wiki_role_rows)
        # Роль вики никогда не отнимает право читать раздел целиком:
        # запрет выражается правилами, а не отсутствием способности.
        merged['can_read'] = True
        return merged
    return capabilities_from_otp_role(otp_role, is_department_head)


def capabilities_from_grants(granted):
    """Способности, поднятые ПРАВИЛАМИ, которые человеку уже выписаны.

    Инцидент 21.08.2026. Оператору СЗоВ выписали персональное правило на раздел
    «Супервайзер» со всеми шестью правами — читать, создавать, править, удалять,
    публиковать, согласовывать. Правило сохранилось, в «Структуре» показывалось,
    а человек не мог ни завести статью, ни поправить букву.

    Причина в том, что право записи требует И способности, И разрешения на
    объекте (resolve_article_permissions ниже), а способность выводилась ТОЛЬКО
    из должности — у роли 'operator' сверх чтения нет ничего. Поэтому POST
    /articles отсекал сам декоратор роута (capability='can_create'), а can_edit
    обнулялся в конце resolve_article_permissions. Оба раза молча: раздающий
    видел выписанное право и не видел, что оно не работает.

    Ровно эта ловушка уже срабатывала 19.08.2026 у супервайзера с публикацией, и
    лечили её точечно — добавили способность роли. Пока способность выводится из
    одной лишь должности, ловушка возвращается при каждой следующей выдаче: у
    должностей ниже супервайзера прав записи нет вовсе, а выписывать им доступ
    интерфейс позволяет.

    Поэтому «вправе ли в принципе» читается буквально: должность и роли вики
    ПЛЮС то, что человеку уже выписали правилами. Сам по себе союз ничего не
    открывает — где именно правом можно воспользоваться, по-прежнему решает
    правило объекта. Союз лишь перестаёт гасить решение того, кто раздавал
    доступ.

    До управления структурой, ролями и доступами это не дотягивается ПО
    ПОСТРОЕНИЮ: в правиле живут только шесть прав PERMISSION_COLUMNS, а
    can_manage_* есть исключительно в CAPABILITY_COLUMNS (wiki/schema.py).
    Именно поэтому перебираем PERMISSION_COLUMNS поимённо, а не всё, что пришло
    в словаре: лишний ключ не должен превращаться в способность.
    """
    caps = dict(NO_CAPABILITIES)
    for name in PERMISSION_COLUMNS:
        if (granted or {}).get(name):
            caps[name] = True
    return caps


