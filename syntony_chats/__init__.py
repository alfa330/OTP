"""Чаты сети Syntony в базе iCORE: вебхуки чатов (документ Syntony «API истории чатов
и вебхуки чатов», версия 1, 18.11.2026).

Syntony шлёт на наш адрес каждое новое сообщение во всех чатах сети и каждую смену
статуса доставки:

    Syntony  ──POST /api/syntony/chats/webhook (подпись HMAC)──▶  iCORE  ──▶  база

Адрес приёмника вписывает владелец аккаунта сети в Syntony («Настройки → API и ключи →
Вебхуки чатов»); секрет подписи Syntony показывает ему один раз — он живёт в окружении
сервера (SYNTONY_CHATS_WEBHOOK_SECRET), в базе и в журналах его нет. Пока секрета нет,
приёмник отвечает 503: Syntony повторит событие (30 с, 2 мин, 10 мин, 30 мин, 1 ч), а не
выбросит его, как выбросила бы при 4xx.

Хранится по строке на диалог и на сообщение — снимок последнего, что сказала Syntony.
Повтор события ничего не портит: снимок диалога пишется, только если он новее записанного,
содержимое сообщения — только новее и отличающееся, статус исходящего — только «вперёд»
(sent → delivered → read, failed — конечный), а моменты sent/delivered/read/failed
запоминаются, в каком бы порядке ни пришли.

Модули:
    rules.py   чистые правила: подпись, разбор события, строки для базы
    schema.py  таблицы диалогов и сообщений
    store.py   SQL поверх готового курсора
    routes.py  Flask Blueprint /api/syntony/chats
"""
