# Рамка для озвучки: Live-модель разговорная, а не диктор. Без этой строки она
# начинает ОТВЕЧАТЬ на поданный текст вместо того, чтобы его произнести.
# Правило формата для НАСТАВНИКА. Добавляется к системному промпту чат-помощника
# вики, а не заменяет его: поиск, периметр и защита от выдумки остаются общими.
#
# Зачем оно вообще нужно. Помощник вики пишет для ЧТЕНИЯ и по своему промпту
# обязан оформлять данные списками и таблицами Markdown — в интерфейсе они
# рисуются. Наставника СЛУШАЮТ, и там это выходит боком дважды: синтез читает
# звёздочки вслух, а ответ на тысячу знаков превращается в 76 секунд монолога.
# Замер 22.08.2026 на вопросе про фотоконтроль: 1047 знаков и 4,8 с генерации
# против 353 знаков и 1,9 с с этим правилом.
#
# Второй абзац появился не сразу. С одной только краткостью модель перестала
# признаваться, что ответа в статьях НЕТ: на том же вопросе она молча
# пересказала соседние требования вместо честного «прямой инструкции нет,
# обратитесь к супервайзеру». Краткость не должна покупаться честностью.
