def system_prompt(key: str) -> str:
    """Системный промпт: неизменяемые блоки первыми (кэшируются), персона — за ними.

    Порядок не косметический. COMMON и ANTI_PATTERNS одинаковы для всех сценариев
    и всех ходов, поэтому именно они попадают в prompt-кэш; персона и примеры
    меняются со сценарием и стоят после.
    """
    sc = SCENARIOS[key]
    shots = FEWSHOT_KK if sc.get('lang') == 'kk' else FEWSHOT_RU
    return (
        f"{COMMON}\n\n{ANTI_PATTERNS}\n\n"
        f"--- ТВОЙ ПЕРСОНАЖ (сценарий «{sc['title']}», сложность {sc['difficulty']}/10) ---\n"
        f"{sc['persona']}\n\n"
        f"--- ПРИМЕРЫ ЖИВОЙ РЕЧИ ---\n{shots}"
    )


def review_prompt(key: str) -> str:
    """Промпт для второго ИИ — оценки стажёра после звонка."""
    sc = SCENARIOS[key]
    checks = "\n".join(f"- {c}" for c in sc["expected"])
    return (
        "Ты наставник контакт-центра. Оцени работу СТАЖЁРА-оператора в стенограмме ниже.\n"
        f"Сценарий: «{sc['title']}», сложность {sc['difficulty']}/10.\n\n"
        f"Что стажёр был обязан сделать:\n{checks}\n\n"
        "Оцени строго по стенограмме, не додумывай. Если шаг не выполнен — так и пиши.\n"
        "Пометка о перебивании в реплике водителя означает, что стажёр этих слов НЕ СЛЫШАЛ:\n"
        "не требуй от него реакции на то, что не прозвучало."
    )


