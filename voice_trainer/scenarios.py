def say_exactly(key: str | None = None, mode: str | None = None) -> str:
    """Заголовок промпта озвучки: манера говорящего плюс команда «произнеси ровно».

    Манера выбирается сначала по сценарию (у каждого водителя своя), потом по
    режиму: у наставника сценария нет вовсе, а манера ему нужна.
    """
    style = TTS_STYLE.get(key or "") or (MENTOR_STYLE if mode == 'mentor' else None)
    return f"{style}\n\n{SAY_EXACTLY}" if style else SAY_EXACTLY


# Пометка о перебивании в истории диалога.
#
# Молча обрезать реплику по услышанному нельзя: модель придумает окончание
# заново, и у водителя на следующем ходу меняются фамилия и сумма — этот класс
# ошибок в разделе уже ловили браузерной проверкой. Оставить текст целиком тоже
# нельзя: модель уверена, что человек всё слышал, и продолжает мысль, которой не
# было ни одним звуком. Поэтому услышанное отдаётся как есть, а непрозвучавшее —
# отдельной пометкой.
CUT_MARK = (' […ТЕБЯ ПЕРЕБИЛИ ЗДЕСЬ. Вслух НЕ ПРОЗВУЧАЛО: «{unsaid}» — '
            'собеседник этих слов не слышал]')

# Отдельный случай: перебили в первые доли секунды, и вслух не прозвучало
# НИЧЕГО. Тогда пометка «часть слов не прозвучала» врёт, а реплика в истории
# состояла бы из одной служебной строки без единого своего слова.
UNHEARD_MARK = ('[ЭТА ТВОЯ РЕПЛИКА НЕ ПРОЗВУЧАЛА ВООБЩЕ. Собеседник её не '
                'слышал ни одним словом. Ты хотел сказать: «{unsaid}». '
                'Скажи это заново, если это ещё нужно.]')

