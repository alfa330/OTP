"""Окно Syntony в iCORE: чаты и заявки сети таксопарков во встроенном окне.

ТЗ Syntony от 09.11.2026 («Окно Syntony в iCORE»). Окно — это <iframe> с
одноразовой ссылкой, которую сервер Syntony выдаёт по запросу НАШЕГО сервера:

    браузер  ──POST /api/syntony/window──▶  iCORE  ──POST /v1/iframe + ключ──▶  Syntony
    браузер  ◀──────── { url } ───────────  iCORE  ◀───────── { url } ────────  Syntony

Ключ Syntony живёт только в окружении сервера (client.py) и не попадает ни в
ответы браузеру, ни в журналы: с ним можно открыть окно от имени любого оператора.

Решения владельца 11.11.2026:

* **Кому открыто — список в самом разделе.** Супер-админ кнопкой «Доступ» добавляет
  сотрудников поимённо; пункты меню видят только они. Список — это и есть «операторы
  iCORE» для Syntony: за человека вне списка запрос к Syntony не уходит вовсе, даже
  если он супер-админ (иначе он появился бы у Syntony оператором).
* **Рядовым — после QR.** Оператор открывает окно только в сессии, подтверждённой
  обычным QR портала, как «Чаты ОП»; руководителям и админам QR не нужен.
* **Переписка водителя** — кнопкой в карточке водителя «Чатов ОП» (окно по номеру).

Связь с сотрудником Syntony делает её администратор по рабочей почте. Почта лежит
в строке доступа (а не берётся из карточки сотрудника молча): совпасть она должна с
почтой учётной записи Syntony, и поправить её нужно там же, где видно «не связан».

Модули:
    rules.py    чистые правила: разбор запроса браузера, тело запроса к Syntony, коды ошибок
    access.py   чистые правила доступа: кто ведёт список, кому окно, кому нужен QR
    client.py   разговор с Syntony: ключ из окружения, один POST, ответ «как есть»
    schema.py   таблицы списка доступа и следа выдач
    queries.py  SQL
    report.py   файл «список операторов» для Syntony
    routes.py   Flask Blueprint /api/syntony
"""
