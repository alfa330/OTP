"""Обзвон водителей из iCORE Phone без передачи номера оператору.

Как это устроено (решение владельца от 22.09.2026):

  * оператор видит в телефоне порцию из N (по умолчанию 20) строк — только ФИО
    и кнопку «Позвонить»; номера водителя телефон не получает ни в списке, ни
    по клику;
  * клик уходит сюда идентификатором строки, а звонок инициирует СЕРВЕР через
    Binotel API (`calls/internal-number-to-external-number`): АТС звонит на
    внутреннюю линию оператора, тот принимает плечо автоматически, и АТС
    дозванивается водителю. Номер живёт только в базе и в АТС;
  * исход подтверждается не словами телефона, а Binotel: вебхук «API Call
    Completed» и опрос `stats/call-details` по generalCallID, который АТС
    вернула на запрос. Телефон лишь подсказывает, что плечо пришло/ответили/
    закончилось, чтобы интерфейс не ждал вебхука;
  * следующая порция выдаётся только когда по каждой строке текущей есть
    попытка с подтверждённым исходом.

Модули:
  schema.py      — таблицы dial_list_* (идемпотентно, из Database._init_db)
  service.py     — правила выдачи, звонок, сверка исходов, вебхук, журнал
  signing.py     — подписание документов: общий статус, месяц документов (чистые правила)
  sign_check.py  — проверка подписания в Sapar раз в 3 часа и засчитывание успешек
  analytics.py   — вкладка «Аналитика»: воронка базы, документы, дни, операторы
  routes.py      — Flask Blueprint /api/operator/dial_list и /api/dial_list

База водителей — своя у отдела (`dial_list_leads`): загружается файлом ФИО +
телефон + ИИН (ИИН обязателен с 29.09.2026), номер и ИИН уникальны в базе месяца.
Подписавший документы водитель уходит из обзвона, успешка — оператору, который
последним поговорил с ним ≥10 с до подписи. Клиент Binotel API — общий пакет
`binotel/`, Sapar — `crm/sapar.py`, разбор файла и нормализация номера — `common/`.

Секреты (ключ API компании Binotel, токен вебхука) — только в окружении сервера,
в базе и интерфейсе их нет.
"""
