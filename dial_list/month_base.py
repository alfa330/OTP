"""Кто входит в базу месяца «Удаленного КЦ» — одно условие для всех мест, где видна база.

Владелец, 10.11.2026: после исключения 14 534 водителей, которых нет в списке Sapar (Салтанат), «Аналитика»,
выбор месяца и журнал всё ещё показывали 44 тыс. «в базе». Исключение строку не удаляет — у неё остаются звонки
и история, — поэтому каждое место считало её как раньше.

База месяца — строки dial_list_leads месяца, КРОМЕ исключённых, которых нет в списке месяца. Список месяца —
dial_list_report_roster (загрузка «Города по ИИН»; он же — состав отчёта о подписании). Почему именно так:

  * исключённый водитель ИЗ списка остаётся в базе: в октябре 11 769 исключены с пометкой «передан на внешний
    обзвон вне iCORE» — это наши водители, они в отчёте и в аналитике месяца;
  * водитель НЕ из списка, но не исключённый, остаётся (решение владельца 21.10.2026: «не из списка — в обзвоне,
    но не в отчёте»);
  * исключённый и не из списка — не наш водитель за этот месяц (10.11.2026: «ушедшие» и «только акт комиссии»):
    его нет ни в цифрах, ни в журнале месяца; строка и история звонков остаются в таблице;
  * у месяца без списка (Тез, ранние месяцы) база — все строки, как раньше.

Строки «только для отчёта» (водитель списка без номера, status 'excluded') — в списке, значит в базе.
"""


def in_month_base_sql(alias="l"):
    """SQL-условие «строка `alias` (dial_list_leads) входит в базу своего месяца». Без параметров и без «%»:
    вставляется в любой запрос как есть. Месяц у строки — её собственный (l.period), поэтому годится и для
    выборки по всем месяцам."""
    return (
        f"NOT ({alias}.status = 'excluded'"
        f" AND EXISTS (SELECT 1 FROM dial_list_report_roster mb_list"
        f" WHERE mb_list.department_id = {alias}.department_id AND mb_list.period = {alias}.period)"
        f" AND NOT EXISTS (SELECT 1 FROM dial_list_report_roster mb_iin"
        f" WHERE mb_iin.department_id = {alias}.department_id AND mb_iin.period = {alias}.period"
        f" AND mb_iin.iin = {alias}.iin))"
    )
