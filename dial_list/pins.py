# -*- coding: utf-8 -*-
"""Закреплённые водители: водитель базы месяца выдаётся только «своему» оператору.

Владелец, 18.11.2026: «В удаленном кц надо взять именно этих водителей не подписавших и по кому есть документы
и направить самим менеджерам на обзвон т.е именно по ним закрепить этих водителей что бы они их обрабатывали» —
файл «СМЗ по операторам»: листы — менеджеры фронт-офиса (они сидят на линиях удалённого КЦ), строки — водители,
которых каждый из них зарегистрировал. Решение владельца в тот же день (вопрос «что давать менеджеру, когда он
прозвонит своих»): «Потом общий список» — сначала свои водители, когда кончатся — общий список, как у всех.

dial_list_leads.pinned_operator_id — за кем закреплён водитель (NULL — общий). Правила:

  * пул выдачи (_POOL_SQL) оператора: свои закреплённые — первыми и мимо отметок файлов «в работу» (закрепление —
    решение руководителя о конкретном водителе), чужие закреплённые — никогда, общие — как раньше;
  * недозвон закреплённому: строка выдачи закрывается как обычно, водитель остаётся закреплённым — повтор снова
    только своему оператору;
  * закрепление действует, пока оператор работает в отделе водителя: не уволен и либо сотрудник отдела не на
    чужой линии, либо сидит на линии этого отдела — то же правило, что у списка операторов отдела
    (_ACTIVE_MEMBER_SQL). Уволили или сняли с линии — его водители сами возвращаются в общий список, правка
    данных не нужна, а вернётся на линию — закрепление снова в силе;
  * «Позвонить ещё раз» водителю, закреплённому за другим, — отказ (recall_lead).

Условия — без параметров (кроме pool_sql: плейсхолдер вызывающего), без «%» и фигурных скобок: вставляются в
строки, которые потом проходят через str.format (_POOL_SQL — «{lock}»), и в запросы с именованными параметрами.
"""
from dial_list import batch_focus

# Статусы «не работает» — те же, что у панели SIP и списка операторов отдела (database._SIP_INACTIVE_STATUSES).
INACTIVE_STATUSES = ("fired", "dismissal")

# Сколько водителей за один запрос закрепления (ручка руководителя).
PIN_BATCH_MAX = 1000


def active_members_sql():
    """Подзапрос «кто сейчас работает в каком отделе» — пары (сотрудник, отдел) по правилу списка операторов отдела
    (_ACTIVE_MEMBER_SQL): не уволен, и либо сотрудник отдела, не сидящий на линии ДРУГОГО отдела, либо сидит на
    линии этого отдела. Без NULL в колонках: NOT IN по такому списку всегда да или нет.

    Не коррелирован со строкой водителя — Postgres строит из него хэш один раз на запрос (сотрудников — сотни). Тот
    же смысл подзапросом EXISTS на каждого водителя планировщик оценивал как подзапрос на каждую из ~30 тыс. строк
    базы месяца: оценка пула переходила порог JIT, и компиляция добавляла пулу 100–200 мс (замер на боевых данных
    18.11.2026: 24 мс без закреплённых против 70–480 мс с 350 закреплёнными)."""
    statuses = ", ".join(f"'{s}'" for s in INACTIVE_STATUSES)
    return (
        f"SELECT pin_u.id, pin_u.department_id FROM users pin_u"
        f" WHERE pin_u.department_id IS NOT NULL AND LOWER(COALESCE(pin_u.status, '')) NOT IN ({statuses})"
        f" AND NOT EXISTS (SELECT 1 FROM dial_list_line_members pin_o WHERE pin_o.user_id = pin_u.id"
        f" AND pin_o.released_at IS NULL AND pin_o.department_id <> pin_u.department_id)"
        f" UNION ALL SELECT pin_m.user_id, pin_m.department_id FROM dial_list_line_members pin_m"
        f" JOIN users pin_mu ON pin_mu.id = pin_m.user_id"
        f" WHERE pin_m.released_at IS NULL AND LOWER(COALESCE(pin_mu.status, '')) NOT IN ({statuses})"
    )


def pin_active_sql(alias="l"):
    """SQL-условие «оператор, за которым закреплён водитель строки `alias`, ещё работает в отделе этой строки». У
    незакреплённого — NULL (сравнение с NULL), поэтому само по себе не используется: только внутри pinned_sql и
    free_sql, где сначала проверено IS [NOT] NULL — там условие всегда да или нет."""
    return f"({alias}.pinned_operator_id, {alias}.department_id) IN ({active_members_sql()})"


def pinned_sql(alias="l"):
    """Водитель закреплён, и закрепление в силе (оператор работает в отделе). Никогда не NULL."""
    return f"({alias}.pinned_operator_id IS NOT NULL AND {pin_active_sql(alias)})"


def free_sql(alias="l"):
    """Водитель общий: не закреплён или закреплён за тем, кто в отделе больше не работает. Никогда не NULL."""
    return f"({alias}.pinned_operator_id IS NULL OR NOT {pin_active_sql(alias)})"


def pool_sql(alias, operator_param):
    """Условие пула оператора `operator_param` (готовый плейсхолдер вызывающего, например «%s»): свой закреплённый —
    всегда, мимо отметок файлов; общий — по отметкам файлов (batch_focus); чужой закреплённый — никогда.
    Свой закреплённый не проверяется на «работает в отделе»: выдачу просит сам оператор."""
    return (f"({alias}.pinned_operator_id = {operator_param}"
            f" OR ({free_sql(alias)} AND {batch_focus.in_work_sql(alias)}))")


def department_pool_sql(alias="l"):
    """То же без оператора — «кому-то в отделе этого водителя выдадут»: закреплённого в силе — да (своему
    оператору), общего — по отметкам файлов. Сводка «Доступно сейчас», этапы журнала, «База на паузе»."""
    return f"({pinned_sql(alias)} OR {batch_focus.in_work_sql(alias)})"
