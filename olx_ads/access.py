# -*- coding: utf-8 -*-
"""Права раздела «Объявления OLX». Чистая логика: ни базы, ни Flask.

Периметр тот же, что у «Лидов OLX», и берётся он ОТТУДА, а не переписывается:
`olx_amo/access.py` уже отвечает на вопрос «кто в компании занимается OLX», и
второй список отделов под ту же аудиторию гарантированно разъехался бы с первым
на первом же изменении. Импорт дешёвый — тот модуль тоже не тянет ни базу, ни
Flask.

    глобальный админ              всё, включая запись в OLX
    глава «Маркетинга» и «ОП»     всё, включая запись в OLX
    сотрудник «Маркетинга»        готовит тексты; в OLX пишет, только если ему
                                  это разрешили поимённо (задача #371)
    остальные                     раздела не видят

Почему запись разведена с подготовкой текста
--------------------------------------------
Это ровно та же граница, что у ответа кандидату в «Лидах OLX»: наружу, от лица
компании — отдельное право. Здесь цена ошибки выше: одно нажатие меняет текст
сразу у сотен боевых объявлений живого бизнеса, и откат стоит второго такого же
прохода. Поэтому сочинять, править и складывать черновики может весь раздел, а
отправлять в OLX — админ, главы отделов и маркетологи, которым это разрешили.

Решение владельца 14.09.2026: периметр как в «Лидах OLX», «но обязательно нужна
история правок». История поэтому не право, а устройство: пишется всегда и всем,
и отключить её нельзя (см. `schema.py`, таблица `olx_ads_history`).

Поимённое разрешение публиковать (задача #371, 01.10.2026)
---------------------------------------------------------
Глава «Маркетинга» попросил дать право публиковать одному из своих
маркетологов. Граница «запись наружу — по должности у админа и глав» не снята, а
дополнена: рядовому маркетологу запись открывается ПОИМЁННО, строкой в
`olx_ads_publishers`, а не всей должности. Должность `marketing_manager` носят и
таргетолог, и видеограф — выдать им заодно право переписывать сотни боевых
объявлений значило бы расширить просьбу, а не выполнить её.

Разрешение само ничего не открывает: оно действует только у того, кто и так
работает в разделе рядовым маркетологом. Перевели человека в другой отдел или
сменили должность — разрешение перестаёт действовать вместе с доступом к разделу.

Кому разрешить, решают админ и глава «Маркетинга» — тот, чьи это люди. Глава
«ОП» публикует сам, но чужим отделом не распоряжается: граница отдела у глав в
портале строгая.

На «Лиды OLX» разрешение не распространяется: ответ кандидату — другое действие
с прежней границей (`olx_amo.access.can_reply`).
"""

from olx_amo import access as leads_access

# Пере-экспорт: раздел опирается на тот же периметр отделов, и держать его
# видимым здесь удобнее, чем заставлять читателя идти в соседний пакет.
SECTION_HEAD_DEPARTMENT_CODES = leads_access.SECTION_HEAD_DEPARTMENT_CODES
SECTION_MEMBER_DEPARTMENT_CODE = leads_access.SECTION_MEMBER_DEPARTMENT_CODE
SECTION_MEMBER_ROLE = leads_access.SECTION_MEMBER_ROLE


def is_global_admin(ctx):
    return leads_access.is_global_admin(ctx)


def heads_section_department(ctx):
    return leads_access.heads_section_department(ctx)


def works_in_section_department(ctx):
    return leads_access.works_in_section_department(ctx)


def can_view(ctx):
    """Пускать ли в раздел вообще."""
    return leads_access.can_view(ctx)


def can_write_content(ctx):
    """Готовить тексты: бриф месяца, генерация ИИ, правка черновика.

    Это работа маркетолога, и она НЕ выходит за пределы портала: пока черновик
    не применён, в OLX ничего не изменилось.
    """
    return can_view(ctx)


def heads_member_department(ctx):
    """Глава того отдела, чьи рядовые сотрудники работают в разделе."""
    if not ctx or not ctx.get('headed_department_ids'):
        return False
    codes = {str(code).strip().lower()
             for code in (ctx.get('headed_department_codes') or []) if code}
    return SECTION_MEMBER_DEPARTMENT_CODE in codes


def has_publish_permission(ctx):
    """Рядовой маркетолог с поимённым разрешением публиковать (#371).

    Флаг `publish_granted` кладёт в контекст routes.py — из `olx_ads_publishers`
    и только рядовому сотруднику раздела. Проверка отдела и должности здесь всё
    равно повторена: разрешение не должно открывать запись тому, кто в разделе
    не работает, даже если флаг оказался в контексте по ошибке.
    """
    return bool(works_in_section_department(ctx) and ctx.get('publish_granted'))


def can_apply(ctx):
    """Писать в OLX: применять текст к боевому объявлению и откатывать.

    По должности — та же граница, что у `olx_amo.access.can_reply`, и по той же
    причине: действие наружу. Берём её напрямую оттуда, чтобы два раздела не
    разъехались в ответе на вопрос «кому по должности можно действовать от лица
    компании в OLX». Поверх неё — поимённое разрешение маркетологу.
    """
    return bool(leads_access.can_reply(ctx) or has_publish_permission(ctx))


def can_manage_publishers(ctx):
    """Решать, кому из маркетологов публиковать: админ и глава «Маркетинга»."""
    return bool(is_global_admin(ctx) or heads_member_department(ctx))


def capabilities(ctx):
    """Что клиенту рисовать. Одна форма ответа на все роли — фронт не гадает."""
    return {
        'can_view': can_view(ctx),
        'can_write_content': can_write_content(ctx),
        'can_apply': can_apply(ctx),
        'can_manage_publishers': can_manage_publishers(ctx),
    }
