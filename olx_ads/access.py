# -*- coding: utf-8 -*-
"""Права раздела «Объявления OLX». Чистая логика: ни базы, ни Flask.

Периметр тот же, что у «Лидов OLX», и берётся он ОТТУДА, а не переписывается:
`olx_amo/access.py` уже отвечает на вопрос «кто в компании занимается OLX», и
второй список отделов под ту же аудиторию гарантированно разъехался бы с первым
на первом же изменении. Импорт дешёвый — тот модуль тоже не тянет ни базу, ни
Flask.

    глобальный админ              всё, включая запись в OLX
    глава «Маркетинга» и «ОП»     всё, включая запись в OLX
    сотрудник «Маркетинга»        готовит тексты, но САМ В OLX НЕ ПИШЕТ
    остальные                     раздела не видят

Почему запись разведена с подготовкой текста
--------------------------------------------
Это ровно та же граница, что у ответа кандидату в «Лидах OLX»: наружу, от лица
компании — отдельное право. Здесь цена ошибки выше: одно нажатие меняет текст
сразу у сотен боевых объявлений живого бизнеса, и откат стоит второго такого же
прохода. Поэтому сочинять, править и складывать черновики может весь раздел, а
отправлять в OLX — админ и главы отделов.

Решение владельца 14.09.2026: периметр как в «Лидах OLX», «но обязательно нужна
история правок». История поэтому не право, а устройство: пишется всегда и всем,
и отключить её нельзя (см. `schema.py`, таблица `olx_ads_history`).
"""

from olx_amo import access as leads_access

# Пере-экспорт: раздел опирается на тот же периметр отделов, и держать его
# видимым здесь удобнее, чем заставлять читателя идти в соседний пакет.
SECTION_HEAD_DEPARTMENT_CODES = leads_access.SECTION_HEAD_DEPARTMENT_CODES
SECTION_MEMBER_DEPARTMENT_CODE = leads_access.SECTION_MEMBER_DEPARTMENT_CODE
SECTION_MEMBER_ROLE = leads_access.SECTION_MEMBER_ROLE


def is_global_admin(ctx):
    return leads_access.is_global_admin(ctx)


def heads_section_department(ctx):
    return leads_access.heads_section_department(ctx)


def works_in_section_department(ctx):
    return leads_access.works_in_section_department(ctx)


def can_view(ctx):
    """Пускать ли в раздел вообще."""
    return leads_access.can_view(ctx)


def can_write_content(ctx):
    """Готовить тексты: бриф месяца, генерация ИИ, правка черновика.

    Это работа маркетолога, и она НЕ выходит за пределы портала: пока черновик
    не применён, в OLX ничего не изменилось.
    """
    return can_view(ctx)


def can_apply(ctx):
    """Писать в OLX: применять текст к боевому объявлению и откатывать.

    Та же граница, что у `olx_amo.access.can_reply`, и по той же причине —
    действие наружу. Берём её напрямую оттуда, чтобы два раздела не разъехались
    в ответе на вопрос «кому можно действовать от лица компании в OLX».
    """
    return leads_access.can_reply(ctx)


def capabilities(ctx):
    """Что клиенту рисовать. Одна форма ответа на все роли — фронт не гадает."""
    return {
        'can_view': can_view(ctx),
        'can_write_content': can_write_content(ctx),
        'can_apply': can_apply(ctx),
    }
