"""Раздел «Реестр тестовых номеров» и исключение этих номеров из расчётов.

Сотрудники звонят на наши линии и пишут в наши WhatsApp со своих номеров, чтобы
проверить IVR, очередь, бота, рабочее место. Такие разговоры — не работа с
водителем: их нельзя брать в ИИ-оценку, считать на табло, в отчётах, планах,
успешках и расчёте ресурсов, заводить по ним сделки. Номер вносят в реестр с
владельцем-сотрудником — и все эти расчёты перестают его видеть, в том числе за
прошлые дни там, где цифры считаются при чтении.

Сами звонки и чаты НЕ удаляются и не помечаются в исходных таблицах: мост
перезаписывает сутки касаний целиком, вебхуки и синки пишут сырьё как есть, а
раздел показывает тесты по дням именно из этих таблиц. Исключение делается при
чтении — условием по ключу номера (keys.sql_not_test) или фильтром в Python для
живых источников (keys.cached_keys).

Состав пакета (как у parcels/ и thermoboxes/):
    keys.py      ключ номера (последние 10 цифр) и способы исключения: SQL, T-SQL, Python
    schema.py    DDL, идемпотентный
    access.py    права — ни базы, ни Flask
    rules.py     разбор введённого номера и вид на экране
    queries.py   SQL реестра поверх готового курсора
    routes.py    Blueprint /api/test_numbers
"""

