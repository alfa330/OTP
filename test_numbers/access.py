"""Права «Реестра тестовых номеров». Чистая логика: ни базы, ни Flask.

Решение владельца 09.10.2026: реестр ведут админы и главы отделов — добавляют
номер, выбирают владельца, убирают. Остальным раздел не виден. Супервайзерам не
даём: номер в реестре убирает звонки из ИИ-оценки и табло, и через реестр можно
было бы спрятать звонок своего оператора.

Смотреть и править — один круг: «смотрит, но не правит» никто не просил.
Глава отдела здесь не ограничен своим отделом: номер не принадлежит отделу —
тестовый звонок на линию СЗоВ делает и сотрудник ОП.
"""

from parcels.access import is_department_head, normalize_role

_ADMIN_ROLES = ('super_admin', 'admin')


def can_open_section(ctx):
    """Пускать ли в раздел. Проверяется на КАЖДОМ роуте: спрятанный пункт меню
    доступом не является. Зеркало — canAccessTestNumbersSectionForUser в App.jsx."""
    if not ctx:
        return False
    if normalize_role(ctx.get('role')) in _ADMIN_ROLES:
        return True
    return is_department_head(ctx)


def can_edit(ctx):
    """Добавить номер, сменить владельца, убрать номер — тот же круг."""
    return can_open_section(ctx)
