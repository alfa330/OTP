import React from 'react';
import ResourceFteView from './ResourceFteView';

/*
  Расчет ресурсов · Чат — тонкая обёртка над общим разделом.

  Решение владельца 28.08.2026: «нужно просто переиспользовать раздел линии, но под
  чат направление». Поэтому здесь нет ни собственной витрины, ни своей копии
  компонентов: всё живёт в ResourceFteView, а направление выбирается пропом.
  Что именно различается — вкладки, ключ хранения тумблеров, набор ставок,
  подписи единиц и признаки «есть ли такой показатель» — лежит в DIRECTION_CONFIG
  того же файла. Заголовок «Расчет ресурсов · Чат» и объяснение расчёта от цели
  «ответ внутри чата» приходят оттуда же.

  Модель принципиально отличается от линии: среднего времени обработки НЕТ. Время
  жизни обращения в Chat2Desk (медиана ~1,6 часа) меряет ожидание клиента, а не
  работу оператора, поэтому умножать объём на него нельзя. Считаем от цели по
  сервису: нужно чатников в час = чаты в час ÷ чатов в час на одного чатника.

  Цели две, и путать их нельзя:
    • «ответ внутри чата» — рычаг, из него выводится ёмкость;
    • «первый ответ (реакция)» — единственная измеримая по нашей базе, именно по
      ней считается «в цель» на вкладке «Чаты».

  Сигнатуру не меняем: её использует src/App.jsx.
*/
const ResourceChatFteView = ({ user, showToast, apiBaseUrl, withAccessTokenHeader, initialDashboardView }) => (
  <ResourceFteView
    direction="chat"
    user={user}
    showToast={showToast}
    apiBaseUrl={apiBaseUrl}
    withAccessTokenHeader={withAccessTokenHeader}
    initialDashboardView={initialDashboardView}
  />
);

export default ResourceChatFteView;
