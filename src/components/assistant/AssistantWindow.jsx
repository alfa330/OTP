import React from 'react';
import Orb from './Orb.jsx';

/* Содержимое откреплённого окна: тот же шарик и тот же чат, что в портале.
 *
 * ПОЧЕМУ ШАРИК ЕДЕТ В ОКНО ВМЕСТЕ С ЧАТОМ. Первой версией в окно уезжала одна
 * панель, и окно приходилось закрывать целиком, чтобы убрать чат с глаз. Но
 * помощник в портале устроен иначе: пузырь висит всегда, а чат из него
 * раскрывается и складывается. Решение владельца — перенести в окно ИМЕННО это
 * поведение: свёрнутое окно это пузырь, тычок по нему раскрывает чат, пузырь
 * остаётся на месте.
 *
 * РАЗМЕР ОКНА МЕНЯЕТ САМ ТЫЧОК. Document PiP разрешает window.resizeTo только
 * при свежем жесте пользователя («resizeTo() requires user activation in
 * document picture-in-picture»), поэтому менять размер из эффекта или таймера
 * нельзя — исключение прилетит молча. Клик по пузырю жестом является, и это
 * единственный вход: другого способа сложить окно в пузырь у нас нет.
 *
 * ПОЧЕМУ СВЁРНУТОЕ ОКНО НЕ КРУЖОК 56px. У окна PiP есть жёсткий минимум —
 * Chrome не даёт уже 240 пикселей по ширине и ниже 66 по высоте содержимого
 * (промерено: запрос 96×96 отдаёт 240×66, запрос 150×520 отдаёт 240×486).
 * Поэтому свёрнутое состояние — компактная плашка: пузырь и слово «Помощник».
 * Пустая полоса рядом с кружком читалась бы как недорисованное окно, подпись
 * делает её осмысленной, а заодно говорит, что это, когда окно затерялось
 * среди чужих.
 *
 * Перетаскивания здесь нет намеренно: окно двигают за его собственный
 * заголовок, и второй способ таскать то же самое — лишний.
 */

/* Внешние размеры окна. Высота содержимого = внешняя минус 34 (рамка окна),
   поэтому раскрытое даёт 600: панель 520 + отступы 16 + зазор 8 + пузырь 56. */
export const WINDOW_SIZE = {
    open: { width: 384, height: 634 },
    collapsed: { width: 240, height: 108 },
};

export default function AssistantWindow({ open, onToggle, children }) {
    return (
        <div className={`aorb-win${open ? '' : ' aorb-win--collapsed'}`}>
            {open && <div className="aorb-win__panel">{children}</div>}
            <div className="aorb-win__dock">
                {!open && <span className="aorb-win__label">Помощник</span>}
                <button
                    type="button"
                    className="aorb-win__orb"
                    onClick={onToggle}
                    aria-label={open ? 'Свернуть чат' : 'Открыть чат'}
                    aria-expanded={open}
                    title={open ? 'Свернуть чат' : 'Открыть чат'}
                >
                    {/* Свёрнутый пузырь дышит, раскрытый — нет: рядом с лентой
                        ответов постоянное движение отвлекает от текста, а в
                        плашке оно и есть признак, что помощник жив. */}
                    <Orb animated={!open} />
                </button>
            </div>
        </div>
    );
}
