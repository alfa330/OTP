/* Куда встать ленте помощника, когда сменился список сообщений. Правило одно
 * на вкладку «Помощник» в вике и на мини-чат шарика; исполняет его
 * useReplyScroll в assistantThread.jsx.
 *
 * Ответ помощника почти всегда выше ленты: текст, оговорки, источники, оценка.
 * Лента, которая на каждое обновление уезжала к концу, показывала человеку
 * источники, а сам ответ приходилось искать прокруткой вверх (жалоба
 * 15.09.2026). Поэтому новый ответ встаёт к верхнему краю НАЧАЛОМ: сначала
 * читают ответ, до источников доходят сами.
 *
 * Решение принимается по двум спискам — прежнему и новому. Оценка, пометка
 * «передан супервайзеру» и перечитка ленты тоже дают новый список, и если бы
 * лента ехала от каждого, человек, нажавший «Помогло» под источниками, улетал
 * бы обратно к началу ответа.
 *
 *   'end'   — к концу: разговор только что открыт, или человек сам задал
 *             вопрос и ждёт ответа под ним;
 *   'reply' — к началу последнего ответа. Исполняется, только если человек
 *             стоял у конца: ушедшего читать старое лента не трогает;
 *   null    — не двигать: оценка, передача, перечитка той же ленты, откат
 *             упавшего вопроса, загрузка.
 *
 * Ответ супервайзера — такая же реплика помощника (role 'assistant', kind
 * 'supervisor', wiki/questions.py) и встаёт так же.
 */
export const threadScrollIntent = (prev, next) => {
    if (!Array.isArray(next) || !next.length) return null;
    if (!Array.isArray(prev)) return 'end';
    if (next.length <= prev.length) return null;
    return next[next.length - 1]?.role === 'user' ? 'end' : 'reply';
};
