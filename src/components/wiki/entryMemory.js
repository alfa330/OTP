/* Память входа в раздел: последние ответы сервера, пока жива страница.
 *
 * ЗАЧЕМ. Раздел при уходе размонтируется целиком, и каждый вход начинался с
 * пустого места: ни прав, ни пространства, ни набора вкладок — всё это приезжает
 * ответом /ping. До него шапка рисовалась «по умолчанию» (семь вкладок вместо
 * одиннадцати, без переключателя вики и кнопок), а витрина успевала запросить
 * оглавление и подборки БЕЗ пространства — чтобы через полсекунды запросить их
 * заново. Жалоба владельца 13.10.2026: «сначала выходят некоторые разделы,
 * пролаг и разделы, которые имеются».
 *
 * Первый вход теперь ждёт ответа под заготовкой, а второй и следующие сразу
 * рисуют то, что сервер ответил в прошлый раз. Свежий запрос уходит как и
 * раньше, на каждый вход: права считает сервер, здесь лежит его же прошлый
 * ответ, а не своя формула. Разошлись — экран поправится тем же путём, каким
 * он переживает «права сузились между заходами».
 *
 * ТОЛЬКО В ПАМЯТИ, не в localStorage: в ответе — способности человека, его
 * отделы и срок гостевого доступа, и на общем компьютере смены они не должны
 * переживать закрытие вкладки. Ключ начинается с сервера и учётки: вход под
 * другим логином в той же вкладке чужого ответа не покажет.
 */

const answers = new Map();

/** Ключ памяти. Без учётки ключа нет — и запоминать нечего. */
export const memoryKey = (base, userId, ...rest) => (
    userId ? [base, userId, ...rest].join('|') : ''
);

/** Прошлый ответ или null. */
export const recall = (key) => (key && answers.has(key) ? answers.get(key) : null);

/** Запомнить ответ; null — забыть (сервер отказал, верить прошлому нельзя). */
export const remember = (key, answer) => {
    if (!key) return;
    if (answer == null) answers.delete(key);
    else answers.set(key, answer);
};

/* ОТКАЗ ИЛИ СБОЙ — от этого зависит, верить ли дальше запомненному.
 *
 * Отказ (4xx) — ответ сервера про этого человека: раздел не выдан отделу, доступ
 * сняли, сессию не подтвердили. Ему верим, а прошлое забываем.
 * Сбой (ответа нет вовсе, 5xx) — не ответ: моргнула сеть или сервер
 * перезапускается после выкладки. Права от этого не изменились, и стирать с
 * экрана то, что человек видит и с чем работает, не с чего.
 */
export const isRefusal = (error) => {
    const status = Number(error?.response?.status);
    return status >= 400 && status < 500;
};

/* Новый ответ, в котором неизменившиеся части остались ПРЕЖНИМИ объектами.
 *
 * Свежий ответ почти всегда равен запомненному, но это другой объект — и всё,
 * что от него считается (пространства → активное → тумблеры → вкладки),
 * получило бы новую идентичность: эффекты, завязанные на неё, отработали бы
 * второй раз, а каталог запросился бы повторно на каждое «Обновить». С прежними
 * ссылками рендер после такого ответа не меняет на экране ничего.
 */
export const keepUnchanged = (prev, next) => {
    if (prev === next) return prev;
    if (!prev || !next || typeof prev !== 'object' || typeof next !== 'object') return next;
    if (Array.isArray(prev) !== Array.isArray(next)) return next;

    if (Array.isArray(next)) {
        let same = prev.length === next.length;
        const merged = next.map((item, index) => {
            const kept = keepUnchanged(prev[index], item);
            if (kept !== prev[index]) same = false;
            return kept;
        });
        return same ? prev : merged;
    }

    const keys = Object.keys(next);
    let same = Object.keys(prev).length === keys.length;
    const merged = {};
    keys.forEach((key) => {
        merged[key] = keepUnchanged(prev[key], next[key]);
        if (merged[key] !== prev[key] || !Object.prototype.hasOwnProperty.call(prev, key)) same = false;
    });
    return same ? prev : merged;
};
