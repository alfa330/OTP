import React from 'react';
import { BotOff } from 'lucide-react';
import { IosBadge } from '../ui/ios';

/* Метка статьи из раздела, закрытого от ИИ-помощника, — именем этого раздела.
 *
 * Решение владельца 04.11.2026 («Да, меткой «Старая вики»»): после публикации
 * статьи старой вики встали в поиске рядом с живыми, и два «Номера телефонов» —
 * старый и живой — выглядели одинаково. Имя приходит с сервера готовым
 * (ai_closed_in, wiki/perimeter.py::ai_closed_names): это имя ПОМЕЧЕННОГО
 * раздела, а не подпапки, иначе на метке стояло бы «actions».
 *
 * Значок тот же, что у метки «Без помощника» в дереве «Структуры»: одно и то же
 * решение обязано выглядеть одинаково, где бы его ни встретили. Цвет нейтральный —
 * это пометка места, а не предупреждение.
 *
 * Одна метка на три двери в одну выдачу — витрина, выпадашка поиска в шапке и
 * «Все статьи» каталога; скопированная трижды, она однажды разошлась бы. */
export default function AiClosedBadge({ name }) {
    if (!name) return null;
    return (
        <IosBadge tone="slate" title={`Раздел «${name}» — ИИ-помощник его не читает`}>
            <BotOff size={11} /> {name}
        </IosBadge>
    );
}
