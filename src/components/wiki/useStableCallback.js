import { useCallback, useLayoutEffect, useRef } from 'react';

/* Колбэк-пропс, который НЕ должен попадать в зависимости эффектов.
 *
 * Зачем. `showToast` объявлен обычной функцией в теле App, а часть колбэков
 * приходит инлайновыми стрелками (`onSearchTargetConsumed={() => …}`) — и то и
 * другое получает новую идентичность на КАЖДЫЙ рендер родителя. Стоит такой
 * функции попасть в deps useCallback/useEffect, и раздел перезапрашивает
 * /articles на любой чужой рендер: свернули сайдбар, пришло уведомление,
 * обновился таймер — новый запрос. Именно это и выглядело как «раздел стал
 * нестабильным по запросам».
 *
 * Компонент не должен зависеть от того, мемоизировал ли родитель свои функции.
 * Актуальная функция живёт в ref, наружу отдаётся стабильная обёртка, и в
 * списках зависимостей она больше ничего не ломает.
 *
 * ref обновляется в useLayoutEffect, а не прямо при рендере: обычные эффекты
 * выполняются ПОСЛЕ layout-эффектов, поэтому к моменту вызова там уже лежит
 * свежая функция, и при этом сам рендер остаётся чистым.
 */
export default function useStableCallback(fn) {
    const ref = useRef(fn);
    useLayoutEffect(() => { ref.current = fn; });
    return useCallback((...args) => ref.current?.(...args), []);
}
