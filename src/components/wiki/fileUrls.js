/* Адреса файлов внутри тела статьи.
 *
 * В базе они хранятся ОТНОСИТЕЛЬНЫМИ: `/api/wiki/file/<uuid>`. Так их пишет
 * загрузка картинки (wiki/routes_import.py:_store_file) и импорт документа, и
 * так они лежат в проде с самого переноса.
 *
 * Проблема в том, что фронт и API живут на РАЗНЫХ доменах: страница отдаётся
 * с GitHub Pages, а API — с Render. Браузер разрешает относительный адрес
 * относительно страницы, то есть `<img src="/api/wiki/file/…">` уходил на
 * alfa330.github.io и получал 404. Картинок не было видно НИ В ОДНОЙ статье с
 * загруженными файлами — на 19.08.2026 таких девять, включая «О компании» и
 * «Аренда транспорта»; заметили это только на свежей инструкции.
 *
 * Чиним отрисовкой, а не хранением: в теле статьи адрес остаётся относительным
 * (иначе смена домена API протухла бы во всех статьях разом), а перед показом
 * он раскрывается до абсолютного. Bearer-токен сюда не годится в принципе: тег
 * <img> заголовков не отправляет.
 *
 * НА ТЕЛЕФОНЕ ЭТОГО МАЛО, и отсюда второй механизм — карта подписанных адресов.
 * Ручку /api/wiki/file/<id> авторизует кука сессии (заголовка у <img> нет), а
 * мобильному браузеру кука выдаётся с SameSite=Lax — замер на боевом 11.09.2026:
 *
 *     UA iPhone → Set-Cookie: ...; Secure; SameSite=Lax
 *     UA macOS  → Set-Cookie: ...; Secure; SameSite=None; Partitioned
 *     GET /api/wiki/file/<id> без куки → 401
 *
 * Страница на Pages и API на Render — разные сайты, значит кука с Lax в запрос
 * картинки не кладётся вовсе, и на телефоне пропадали ВСЕ картинки из бакета:
 * в статьях (те, что перенесены из старой вики как base64, оставались — они
 * часть текста) и все логотипы парков. Поэтому сервер кладёт в ответ статьи
 * поле file_urls: {id файла -> подписанный адрес GCS}, и показываем мы его.
 * Разбор, срок подписи и оговорка про пересылку — в шапке wiki/file_urls.py.
 *
 * В РЕДАКТОР подписанные адреса не идут (там absolutizeFileUrls зовётся без
 * карты) — он сохраняет то, что ему показали, и подпись протухла бы прямо в
 * теле статьи, а файл перестал бы привязываться к ней при сохранении.
 */

// Тот же префикс, что зашит в _store_file и в регулярку привязки файлов
// (wiki/edit.py: _FILE_REF). Меняется — менять в обоих местах.
const FILE_PREFIX = '/api/wiki/file/';

/* Происхождение API из базового адреса раздела (`https://host/api/wiki`). */
export const originOf = (base) => String(base || '').replace(/\/api\/wiki\/?$/, '');

/* Экранирование для значения HTML-атрибута.
 *
 * Подпись GCS — это query из полудюжины параметров через `&`, а подставляем мы
 * её в разметку, которую браузер потом разбирает сам (dangerouslySetInnerHTML).
 * Голый `&` в атрибуте формально разбирается как начало символьной ссылки, и
 * параметр вида `&copy…` превратился бы в «©» — адрес молча перестал бы
 * совпадать с подписанным. Поэтому `&` и кавычка уходят сущностями.
 *
 * Подстановка идёт ПОСЛЕ санитайзера, то есть мимо него, — экранировать обязаны
 * мы. Адрес приходит от нашего же API, но полагаться на это без экранирования
 * значит держать в разметке дыру «на честном слове». */
const attrValue = (url) => String(url).replace(/&/g, '&amp;').replace(/"/g, '&quot;');

/* Относительные адреса файлов → адреса, по которым картинка реально откроется.
 *
 * urls — карта {id файла: подписанный адрес} из ответа статьи (поле file_urls).
 * Её нет (редактор, старый ответ сервера, подпись не собралась) — работает
 * прежний путь через ручку раздела, который на компьютере ничем не хуже. */
export const absolutizeFileUrls = (html, base, urls = null) => {
    const origin = originOf(base);
    if (!html || html.indexOf(FILE_PREFIX) === -1) return html;
    if (!origin && !urls) return html;
    // Только адреса, начинающиеся со слеша: уже абсолютные (`https://…/api/wiki/file/…`)
    // трогать нельзя, иначе получится `https://hosthttps://host`.
    return String(html).replace(
        new RegExp('(src|href)="' + FILE_PREFIX + '([0-9a-f-]{36})([^"]*)"', 'gi'),
        (whole, attr, id, tail) => {
            // Хвост (query, якорь) у подписи отобрал бы саму подпись — такой
            // адрес отдаём ручке, как и раньше. В теле статьи хвостов нет:
            // адрес пишет wiki/storage.py одной строкой.
            const signed = !tail && urls ? urls[String(id).toLowerCase()] : null;
            if (signed) return `${attr}="${attrValue(signed)}"`;
            if (!origin) return whole;
            return `${attr}="${origin}${FILE_PREFIX}${id}${tail}"`;
        });
};

/* Один адрес файла (а не тело статьи) → абсолютный.
 *
 * Нужен там, где ссылка приезжает отдельным полем ответа, а не внутри HTML:
 * логотип парка (`logo_url`) рисуется в рельсе витрины, в карточке справочника
 * и на странице парка. Та же беда, что и с картинками статей: относительный
 * адрес браузер разрешил бы относительно домена страницы — то есть на Pages,
 * где никакого API нет. */
export const absoluteFileUrl = (url, base) => {
    const origin = originOf(base);
    if (!url || !origin || !String(url).startsWith(FILE_PREFIX)) return url || null;
    return origin + url;
};

/* Абсолютные → обратно относительные, перед сохранением.
 *
 * Нужно ровно потому же, почему абсолютизация делается на показе: если
 * редактор сохранит то, что ему подставили для отрисовки, в базе окажется
 * привязка к домену. Заодно это условие проверяет тест: адрес после круга
 * «показали → сохранили» обязан совпасть с исходным. */
export const relativizeFileUrls = (html) => {
    if (!html || html.indexOf(FILE_PREFIX) === -1) return html;
    return String(html).replace(
        new RegExp('(src|href)="https?://[^"]*?' + FILE_PREFIX, 'g'),
        '$1="' + FILE_PREFIX);
};
