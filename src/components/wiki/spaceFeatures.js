/* Из чего состоит раздел «Вики» в конкретном пространстве.
 *
 * Зеркало SPACE_FEATURES из wiki/schema.py: ключи обязаны совпадать, иначе
 * тумблер в конструкторе будет выключать то, чего сервер не знает, и наоборот.
 *
 * ГЛАВНОЕ ПРАВИЛО: чего нет в объекте — то ВКЛЮЧЕНО. У пространства, заведённого
 * до появления тумблеров, features пуст, и любая другая трактовка пустоты
 * означала бы «вики выключена целиком». Правило живёт здесь одной функцией:
 * разложенное по местам использования, оно однажды разойдётся с сервером.
 */

/* Вкладки в том же порядке, в каком они стоят в шапке раздела. Порядок здесь не
 * косметика: по нему рисуется и конструктор, и сам ряд вкладок, и разъехаться
 * им нельзя — человек настраивает список, глядя ровно на то, что получит. */
export const SPACE_TABS = [
    {
        key: 'library',
        label: 'Главная',
        /* Витрина статей — это и есть раздел: на неё ведут все ссылки, в неё
           возвращается читалка, редактор и поиск. Выключаемая главная оставила
           бы пространство без единственного экрана, куда можно прийти. */
        locked: true,
        lockedHint: 'Витрина статей есть всегда — на неё ведут ссылки из поиска, писем и уведомлений',
        children: [
            { key: 'library_park_rail', label: 'Рельс парков' },
        ],
    },
    { key: 'assistant', label: 'Помощник' },
    {
        key: 'catalog',
        label: 'Статьи',
        children: [
            { key: 'catalog_articles', label: 'Статьи' },
            { key: 'catalog_structure', label: 'Структура' },
            { key: 'catalog_trainers', label: 'Тренажёры' },
            { key: 'catalog_guests', label: 'Гостевой доступ' },
        ],
    },
    /* Новости пространству не принадлежат — тумблер решает только, есть ли
       дверь в этом пространстве. Подробности в wiki/schema.py. */
    { key: 'news', label: 'Новости' },
    { key: 'overview', label: 'Обзор' },
    { key: 'parks', label: 'Парки' },
    { key: 'offices', label: 'Офисы' },
    { key: 'analytics', label: 'Аналитика' },
    { key: 'audit', label: 'Журнал' },
];

/* Плоский список ключей — для нормализации и отправки на сервер. */
export const FEATURE_KEYS = SPACE_TABS.flatMap((tab) => [
    ...(tab.locked ? [] : [tab.key]),
    ...(tab.children || []).map((child) => child.key),
]);

/** Полный набор тумблеров: чего нет — то включено. */
export const spaceFeatures = (raw) => {
    const stored = raw && typeof raw === 'object' ? raw : {};
    return Object.fromEntries(FEATURE_KEYS.map((key) => [key, stored[key] !== false]));
};

/** Включён ли тумблер у пространства. Нет пространства — включено: пока ping не
 *  ответил, раздел обязан выглядеть как обычно, а не мигать пустой шапкой. */
export const featureOn = (space, key) => (space ? spaceFeatures(space.features)[key] : true);

/* Чего нет у ГОСТЯ.
 *
 * Пространство, в котором человеку выдали один раздел на две недели, приходит
 * с признаком guest_only (см. /api/wiki/ping). Гостя позвали ПРОЧИТАТЬ статью —
 * справочники парков и офисов, отчёт по базе знаний и журнал в приглашение не
 * входят, и сервер их такому человеку не отдаёт. Вкладка, которая отвечает
 * отказом, — тот же молчаливый отказ, только с обратной стороны стола.
 *
 * Витрина и помощник остаются: обе показывают ровно то, что человеку выдали,
 * и без них приглашение бессмысленно — прийти будет некуда.
 *
 * «Новости» в списке по той же причине: гостя позвали прочитать статью, а не
 * писать объявления сотрудникам чужого отдела. Должность у гостя бывает любая,
 * вплоть до супервайзера, и без этой строки вкладка ему бы открылась. */
const GUEST_HIDDEN = ['parks', 'offices', 'analytics', 'audit', 'overview', 'news'];

/* Родитель выключен — выключены и его половины. Возвращаем именно это, а не
 * «как записано»: половина, оставшаяся включённой под выключенной вкладкой,
 * однажды всплывёт где-нибудь ещё (в фильтре типов, в подборке, в счётчике). */
export const effectiveFeatures = (space) => {
    const flags = spaceFeatures(space?.features);
    if (space?.guest_only) GUEST_HIDDEN.forEach((key) => { flags[key] = false; });
    SPACE_TABS.forEach((tab) => {
        if (tab.locked || flags[tab.key]) return;
        (tab.children || []).forEach((child) => { flags[child.key] = false; });
    });
    return flags;
};
