export default {
    key: 'crm-ticket-create',
    title: 'Рабочее место оператора',
    subtitle: 'CRM · Диспетчерская · Oktell',
    app: 'Рабочее место',
    stage: 'desktop',
    /* Свободная среда: проигрыватель по этому флагу убирает список шагов, цель и
       кнопку подсказки — показывать их там, где шагов нет, значит обещать урок,
       которого не будет. */
    mode: 'sandbox',
    description: 'Три системы оператора в одном окне, как на смене: CRM с полным '
        + 'деревом категорий, Диспетчерская с карточкой водителя и ведомостью, '
        + 'Oktell с постановкой на линию. Урока нет — можно ходить и пробовать.',
    dataNote: 'Данные учебные: водитель, его телефон, номер В/У и суммы придуманы. '
        + 'Обращение никуда не отправляется и в рабочей CRM не появится.',
    checklist: [
        'CRM — завести обращение: источник, телефон, парк, город, категория',
        'Диспетчерская — карточка водителя, ведомость, заработок, GPS, фотоконтроль',
        'Oktell — войти в call-центр, справочник для перевода, журнал звонков',
    ],
    resultNote: 'Обращение сохранено.',

    createWorld: ({ today }) => {
        const clock = new Date();
        const two = (value) => String(value).padStart(2, '0');
        return {
            call: CALL,
            driver: DRIVER,
            now: `${two(today.day)}.${two(today.month)}.${today.year} `
                + `${two(clock.getHours())}:${two(clock.getMinutes())}:${two(clock.getSeconds())}`,

            // Какая вкладка браузера открыта.
            tab: 'crm',

            // Форма обращения. Меняется свободно (browse), а не шагами.
            form: emptyForm(),

            // Где мы внутри Диспетчерской.
            fleetView: 'contractors',
            fleetTab: 'details',
            fleetFilter: null,
            fleetPanel: null,
            fleetMenu: null,

            // Где мы внутри Oktell.
            oktLogged: false,
            oktView: 'cabinet',
            oktIn: false,
            oktStatus: null,
            oktPhoneMenu: false,

            saved: false,
        };
    },

    vars: (world) => ({
        phone: world.call.phone,
        park: world.call.park,
        city: world.call.city,
    }),

    traps: {},
    steps,

    /* Итог — заведённая карточка. «Верно/неверно» здесь больше нет: правильного
       ответа у свободной среды не существует, оператор выбирает сам. В
       статистике показывается то, что он выбрал, а судит об этом наставник. */
    result: (world) => {
        if (!world.saved) return null;
        const form = world.form || {};
        const fields = [
            ['Звонок/Чат', form.source],
            ['Номер телефона', form.phone],
            ['Номер В/У', form.license],
            ['ID водителя', form.account],
            ['Таксопарк', form.park],
            ['Город', form.city],
            ['Категория', (form.cats || []).filter(Boolean).join(' / ')],
            ['Комментарий', form.comment],
            ['Дублировать обращение', form.duplicate ? 'да' : ''],
        ].filter(([, value]) => value);
        return { title: 'Обращение в CRM', fields };
    },

    recordOnFinishOnly: true,
};
