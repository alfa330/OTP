/* Первое незаполненное поле — оно и подсвечивается на экране.
   Порядок здесь ровно тот же, что в CRM: источник → телефон → парк → город →
   категории → комментарий → сохранение. Отдельного списка полей рядом нет
   намеренно: он повторял бы этот порядок вторым экземпляром и разошёлся бы
   с ним при первой же правке формы. */
export const activeField = (form) => {
    if (!form.source) return 'source';
    if (!form.phone) return 'phone';
    if (!form.park) return 'park';
    if (!form.city) return 'city';
    for (let level = 0; level < ANSWER.cats.length; level += 1) {
        if (!form.cats[level]) return `cat${level + 1}`;
    }
    if (!form.comment) return 'comment';
    return 'save';
};

const setField = (patch) => (world) => ({ form: { ...world.form, ...patch } });

const setCat = (level, value) => (world) => {
    const cats = world.form.cats.slice(0, level);
    cats[level] = value;
    return { form: { ...world.form, cats } };
};

