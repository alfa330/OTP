const consultProblem = (node, right) => {
    if (node.path[2] === 'Запрос' && node.path[1] === 'Обычный водитель') {
        return `Это запрос с тикетом в отдел. Водителю нужно было объяснение — это «Консультация»: «${right}».`;
    }
    return null;
};

const commissionLeafProblem = (node) => {
    if (node.title === 'Консультация по Комиссии от Таксопарка') {
        return 'Это комиссия таксопарка. Водитель спрашивает про комиссию сервиса — «Консультация по Комиссии от Яндекс».';
    }
    return consultProblem(node, 'Консультация по Комиссии от Яндекс');
};

const withdrawLeafProblem = (node) => {
    if (/ошибк/i.test(node.title)) {
        return 'Ошибки при выводе у водителя не было — он спросил, КАК вывести деньги. Это «Консультация по выводу денег с аккаунта».';
    }
    return consultProblem(node, 'Консультация по выводу денег с аккаунта');
};

