        ...BROWSER_TRAPS,
        ...CABINET_TRAPS,
        refresh: 'Обновлять страницу сейчас незачем — сначала доведи шаг до конца.',
        sp_profile: 'Мы уже в профиле.',
        sp_park_login: 'Это вход для таксопарка, а не для водителя.',
