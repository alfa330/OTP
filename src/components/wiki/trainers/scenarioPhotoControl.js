/* Шаги строятся из списка кадров, а не переписываются руками.
 *
 * На каждый кадр их ДВА: открыть плитку в списке и нажать спуск. Так устроено
 * приложение — между снимками оно всякий раз возвращает на экран со списком, и
 * именно там видно, что уже снято, а что нет. Тренажёр, ведущий из камеры прямо
 * в камеру, эту половину фотоконтроля прятал. */
const shotSteps = SHOTS.flatMap((shot, index) => {
    const stage = index + 1;
    const text = SHOT_TEXT[shot.key];
    const turn = shot.hold === 'landscape' ? 'горизонтально' : 'вертикально';
    return [
        {
            key: `open_${shot.key}`,
            screen: 'pc_list',
            action: slotTap(shot.key),
            stage,
            msg: `Кадр ${stage} из 7. В списке нажми плитку «${shot.title}» — откроется камера `
                + `с силуэтом, снимать её нужно ${turn}.`,
            goal: `Открой плитку «${shot.title}».`,
            hint: `Нужная плитка подсвечена и подписана «${shot.title}».`,
            traps: {},
        },
        {
            key: `shot_${shot.key}`,
            screen: 'pc_camera',
            action: 'shutter',
            stage,
            msg: text.msg,
            goal: text.goal,
            hint: text.hint,
            check: (world, payload) => framingProblem(shot.key, world, payload),
            apply: keepShot(shot.key),
            traps: {},
        },
    ];
});

