/* Тренажёр «Фотоконтроль автомобиля в Яндекс Про».
 *
 * Сценарий повторяет семь кадров, которые просит Таксометр: спереди, левый
 * борт, правый борт, сзади, передний ряд сидений, задний ряд и открытый
 * багажник. Порядок тот же, что в приложении, — тренажёр не должен предлагать
 * свой маршрут по инструкции, рядом с которой он стоит.
 *
 * Почему тренажёр, а не список требований в статье. Фотоконтроль заваливают не
 * потому, что не знают список кадров, — список есть в приложении. Заваливают
 * на том, что не показывается текстом: багажник сняли закрытым, салон сняли
 * через стекло, кузов сняли с распахнутой дверью, встали в метре от бампера и
 * машина не поместилась. Всё это — про положение камеры и состояние машины,
 * то есть ровно то, что показывает 3D-сцена и не показывает абзац текста.
 *
 * Экран у всех семи шагов ОДИН («pc_camera»): это камера Таксометра с машиной в
 * объективе. Меняется не экран, а требуемый кадр, поэтому разводить семь почти
 * одинаковых экранов незачем — шаг говорит, что должно попасть в объектив.
 *
 * ДАННЫЕ УЧЕБНЫЕ. Госномер вымышлен, снимки никуда не отправляются, настоящий
 * фотоконтроль этим не проходят.
 */

