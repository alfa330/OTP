/* Человеческие названия открывающихся частей — для объяснений. Ключ здесь тот
   же, что в мире: разойдутся — и барс начнёт просить открыть то, чего нет. */
const PART = {
    doorFrontLeft: 'водительскую дверь',
    doorRearLeft: 'заднюю левую дверь',
    trunkOpen: 'багажник',
};

/* Куда человек смотрит сейчас — чтобы объяснение было про его кадр, а не общее
   «не тот ракурс». Название ракурса произносится ровно так же, как в реплике
   следующего шага, иначе один и тот же вид называется двумя словами. */
const VIEW_NAME = {
    front: 'перёд',
    left: 'левый борт',
    right: 'правый борт',
    rear: 'корма',
    inside_front: 'передний ряд сидений',
    inside_rear: 'задний ряд сидений',
    trunk: 'багажник',
};

/* Проверка кадра — одна на все семь шагов.
 *
 * Порядок проверок здесь смысловой, а не случайный: сначала состояние машины
 * (закрытый багажник виноват больше, чем полшага в сторону), потом ракурс,
 * и только потом дальность. Иначе человек с закрытым багажником получал бы
 * замечание про дальность, исправлял её и снова упирался в то же самое.
 */
const framingProblem = (shotKey, world, payload) => {
    const shot = shotByKey(shotKey);
    const view = payload.view || null;

    if (shot.open && !world[shot.open]) {
        return `${PART[shot.open][0].toUpperCase()}${PART[shot.open].slice(1)} закрыт${
            shot.open === 'trunkOpen' ? '' : 'а'} — снимать нечего. `
            + `Открой ${PART[shot.open]} и сними ещё раз.`;
    }

    if (!shot.open) {
        const openedPart = Object.keys(PART).find((key) => world[key]);
        if (openedPart) {
            return `Сейчас открыт${openedPart === 'trunkOpen' ? '' : 'а'} ${PART[openedPart]}. `
                + 'Кузов снимают собранным: закрой всё и повтори кадр.';
        }
    }

    if (view !== shot.view) {
        return `В кадре ${VIEW_NAME[view] || 'не то, что нужно'}, а нужен ${VIEW_NAME[shot.view]}. `
            + `Обойди машину и наведи камеру так, чтобы она легла в силуэт «${shot.title}».`;
    }

    if (payload.framing === 'close') {
        return 'Слишком близко: машина не помещается целиком. Отойди на три-четыре метра — '
            + 'в кадре должен быть весь автомобиль, от бампера до бампера, с запасом по краям.';
    }
    if (payload.framing === 'far') {
        return 'Слишком далеко: машина занимает четверть кадра, и разглядеть её не получится. '
            + 'Подойди ближе, чтобы она заполняла кадр.';
    }

    return null;
};

/* Отметка снятого кадра. Мир копируется, потому что на нём стоит React.
 * В плитку кладём миниатюру, которую прислал видоискатель: в приложении после
 * спуска в плитке появляется именно снимок, а не галочка. Не приехала (сцена
 * ещё не готова) — остаётся true, и плитка покажет отметку. */
const keepShot = (key) => (world, payload = {}) => ({
    shots: { ...world.shots, [key]: payload.thumb || true },
});

