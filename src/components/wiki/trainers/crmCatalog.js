/** Дети узла по пути из названий. Пустой путь — корень. */
export const childrenAt = (path) => {
    let level = CATEGORY_TREE;
    for (const step of path) {
        const hit = level.find((node) => node[0] === step);
        if (!hit || !hit[1]) return [];
        level = hit[1];
    }
    return level.map((node) => node[0]);
};
