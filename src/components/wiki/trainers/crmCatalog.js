export const PARKS = Object.keys(PARK_CITIES);

/* Дерево собирается один раз при загрузке модуля: форма спрашивает детей узла
   на каждый выбор, и пересчитывать их из плоского списка каждый раз незачем. */
const TREE = (() => {
    const byId = new Map();
    const byParent = new Map();
    for (const row of CATEGORY_ROWS) {
        const [id, parent, title, flags, fieldsAt, executorsAt, scheduleAt, slaTake, slaProcess] = row;
        const leaf = Boolean(flags & 1);
        const node = {
            id,
            parent,
            title,
            leaf,
            ticket: Boolean(flags & 2),
            file: Boolean(flags & 4),
            promotion: Boolean(flags & 8),
            directUsers: Boolean(flags & 16),
            fields: leaf ? (FIELD_SETS[fieldsAt] || []).map(([name, type, required]) => ({ title: name, type, required })) : [],
            executors: leaf ? EXECUTOR_SETS[executorsAt] || [] : [],
            schedules: leaf ? SCHEDULE_SETS[scheduleAt] || {} : {},
            slaTake: slaTake ?? null,
            slaProcess: slaProcess ?? null,
            path: [],
        };
        byId.set(id, node);
        if (!byParent.has(parent)) byParent.set(parent, []);
        byParent.get(parent).push(node);
    }
    for (const node of byId.values()) {
        for (let at = node; at; at = at.parent ? byId.get(at.parent) : null) node.path.unshift(at.title);
    }
    return { byId, byParent };
})();

export const CATEGORY_COUNT = CATEGORY_ROWS.length;

/** Дети узла; без аргумента — первый уровень. */
export const categoryChildren = (parentId = 0) => TREE.byParent.get(parentId) || [];

export const categoryNode = (id) => TREE.byId.get(id) || null;

/** Узел по цепочке названий от корня; null, если такой цепочки нет. */
export const nodeAtPath = (titles = []) => {
    let parent = 0;
    let node = null;
    for (const title of titles) {
        node = categoryChildren(parent).find((item) => item.title === title) || null;
        if (!node) return null;
        parent = node.id;
    }
    return node;
};

/** Названия детей по цепочке названий. Неизвестная цепочка — пустой список. */
export const childrenAt = (titles = []) => {
    if (!titles.length) return categoryChildren(0).map((node) => node.title);
    const node = nodeAtPath(titles);
    return node ? categoryChildren(node.id).map((item) => item.title) : [];
};

/** Конечная категория выбранной цепочки или null, пока цепочка не дошла до конца. */
export const leafAt = (titles = []) => {
    const node = titles.length ? nodeAtPath(titles) : null;
    return node && node.leaf ? node : null;
};

/*
 * Цепочка узлов выбранных категорий. Форма хранит НОМЕРА узлов, а не
 * названия: у одного родителя бывают два листа с одинаковым названием
 * («Регистрация › Перерегистрация» — 41 и 442, и уходят они в разные
 * отделы), и по названию форма открывала бы всегда первый. Названия
 * тоже понимаем — так записаны старые слепки дела.
 */
export const resolveChain = (cats = []) => {
    const chain = [];
    let parent = 0;
    for (const item of cats) {
        const node = categoryChildren(parent).find((candidate) => (typeof item === 'number'
            ? candidate.id === item
            : candidate.title === item));
        if (!node) break;
        chain.push(node);
        parent = node.id;
    }
    return chain;
};

/** Номера узлов от корня до узла — выбор из «Поиска категории» ставит всю цепочку. */
export const chainIds = (node) => {
    const ids = [];
    for (let at = node; at; at = at.parent ? categoryNode(at.parent) : null) ids.unshift(at.id);
    return ids;
};

export const LEAVES = [...TREE.byId.values()].filter((node) => node.leaf);

/** Подпись категории в поиске и в рамке под формой — как в CRM. */
export const pathLabel = (node) => (node ? node.path.join(' › ') : '');

/* Поиск категории ведёт себя как в CRM: подстрока во всём пути, регистр не
   важен, слова НЕ разбиваются — «выплат смз» найдёт только путь, где эти слова
   стоят подряд. Учить искать иначе, чем ищет рабочая форма, нельзя. */
export const searchLeaves = (query) => {
    const needle = String(query || '').toLowerCase().trim();
    if (!needle) return LEAVES;
    return LEAVES.filter((node) => pathLabel(node).toLowerCase().includes(needle));
};
