/* Вид спереди: широкий бампер, сужение к крыше и два зеркала — по ним и видно,
   что кадр строго анфас, а не в три четверти.
 *
 * Пропорции взяты у настоящей машины: 1,95 м с зеркалами на 1,45 м высоты, то
 * есть коробка почти квадратная. Прежний контур был вдвое шире нужного, и
 * силуэт растягивался во весь горизонтальный кадр — совместить с ним машину,
 * которая занимает середину, было нечем. */
const FRONT = 'M 22 96 C 16 96 13 92 13 86 L 13 58 C 13 52 16 48 22 46 '
    + 'L 34 43 L 46 16 C 48 12 52 10 57 10 L 70 10 C 75 10 79 12 81 16 '
    + 'L 93 43 L 105 46 C 111 48 114 52 114 58 L 114 86 C 114 92 111 96 105 96 Z';
const MIRROR_LEFT = 'M 13 54 L 6 52 C 3 51 2 54 2 58 L 2 65 C 2 69 4 71 7 70 L 13 68 Z';
const MIRROR_RIGHT = 'M 114 54 L 121 52 C 124 51 125 54 125 58 L 125 65 '
    + 'C 125 69 123 71 120 70 L 114 68 Z';

/* Вид сзади: те же пропорции, но крыша длиннее, а переход к багажнику короче.
   Зеркал в кадре нет — сзади их не видно. */
const REAR = 'M 20 96 C 14 96 11 92 11 86 L 11 56 C 11 50 14 46 20 44 '
    + 'L 31 41 L 41 18 C 43 14 47 12 52 12 L 75 12 C 80 12 84 14 86 18 '
    + 'L 96 41 L 107 44 C 113 46 116 50 116 56 L 116 86 C 116 92 113 96 107 96 Z';

/* Открытый багажник: ярко — проём, который и должен попасть в кадр. Машина под
   ним остаётся бледной подложкой, иначе кадр «сзади» и кадр «багажник»
   выглядят одинаково, и водитель шлёт закрытый багажник. */
const TRUNK_LID = 'M 32 40 C 32 34 36 30 42 30 L 85 30 C 91 30 95 34 95 40 '
    + 'L 95 70 C 95 76 91 80 85 80 L 42 80 C 36 80 32 76 32 70 Z';

/* ── Салон ────────────────────────────────────────────────────────────────
   Снимают в проём ОТКРЫТОЙ двери, поэтому контур здесь — не силуэт машины, а
   разметка того, что обязано попасть в кадр: проём, кресла целиком и ремни. */
const DOORWAY = 'M 14 52 C 42 24 112 16 148 32 L 150 196 C 108 210 44 206 16 190 Z';

const SEATS_REAR = [
    DOORWAY,
    // Спинка переднего кресла — она срезана краем кадра, как и в жизни.
    'M 18 84 C 28 76 42 76 52 84 L 54 152 C 40 162 26 160 16 150 Z',
    'M 26 66 C 34 60 46 60 52 66 L 52 78 C 42 72 34 72 26 78 Z',
    // Диван: спинка и подушка целиком — по ним проверяют и обивку, и ремни.
    'M 68 88 C 94 78 124 78 144 88 L 146 130 C 122 140 94 140 68 130 Z',
    'M 68 130 C 94 142 122 142 146 130 L 148 170 C 120 182 92 182 66 168 Z',
];

const SEATS_FRONT = [
    DOORWAY,
    // Приборная панель и руль: по ним видно, что кадр сделан с водительской
    // стороны, а не снят с улицы через заднее стекло.
    'M 100 68 C 116 72 128 78 138 86',
    'M 106 104 C 118 94 132 98 139 110',
    // Водительское кресло: спинка и подушка, обе целиком.
    'M 30 92 C 46 82 66 82 80 92 L 84 148 C 62 160 42 158 26 146 Z',
    'M 26 146 C 44 158 64 160 84 148 L 88 178 C 64 190 42 188 24 176 Z',
    // Переднее пассажирское — дальше и выше, но тоже обязано попасть в кадр.
    'M 92 86 C 104 78 122 78 132 86 L 134 130 C 118 140 104 140 90 132 Z',
];

/* Коробка у каждого контура — по самому рисунку, а не общая.
 *
 * Это не мелочь: пустые поля внутри viewBox вписываются в экран наравне с
 * линиями, и силуэт выходит заметно мельче машины в кадре — совместить их
 * становится нечем. Границы взяты по крайним точкам пути плюс небольшой запас
 * на толщину линии. У борта коробка почти повторяет пропорции повёрнутого
 * экрана, поэтому он ложится во всю его длину; у кадров анфас она уже — и это
 * правда, машина спереди занимает середину кадра, а не его целиком. */
const BOX_SIDE = { x: 4, y: 22, w: 198, h: 84 };
const BOX_FRONT = { x: -4, y: 4, w: 135, h: 98 };
const BOX_REAR = { x: 5, y: 6, w: 117, h: 96 };
/* Салон нарисован по проёму двери, а портретный кадр выше проёма: в исходных
   пропорциях силуэт ложился в середину экрана, оставляя пустыми верх и низ, и
   подсказывал не «встань вплотную», а «отойди». Поэтому рисунок растянут по
   вертикали до пропорций кадра — сиденья от этого чуть выше, но силуэт
   занимает экран целиком, как в приложении. */
const INSIDE_STRETCH = 1.3;
const BOX_INSIDE = { x: 8, y: 13, w: 148, h: 270 };

/* Растяжение задаётся группой, а не переписыванием координат в путях: пути
   правятся руками, и пересчитанные числа стало бы невозможно читать. */
const stretched = (paths, prefix) => (
    <g transform={`scale(1, ${INSIDE_STRETCH})`}>
        {paths.map((d, i) => stroke(d, `${prefix}${i}`))}
    </g>
);

const stroke = (d, key, dim = false) => (
    <path key={key} d={d} className={dim ? 'is-dim' : undefined} />
);

const OUTLINES = {
    side: { box: BOX_SIDE, art: stroke(SIDE, 'side') },
    front: {
        box: BOX_FRONT,
        art: [stroke(FRONT, 'body'), stroke(MIRROR_LEFT, 'ml'), stroke(MIRROR_RIGHT, 'mr')],
    },
    rear: { box: BOX_REAR, art: stroke(REAR, 'body') },
    trunk: {
        box: BOX_REAR,
        art: [stroke(REAR, 'body', true), stroke(TRUNK_LID, 'lid')],
    },
    seats_rear: { box: BOX_INSIDE, art: stretched(SEATS_REAR, 'sr') },
    seats_front: { box: BOX_INSIDE, art: stretched(SEATS_FRONT, 'sf') },
};

/**
 * Контур поверх кадра.
 * @param {string} kind    какой силуэт (поле outline у кадра)
 * @param {boolean} flip   отразить по горизонтали (правый борт)
 * @param {boolean} rotate развернуть на 90° — так приложение просит повернуть телефон
 */
export default function ShotOutline({ kind, flip = false, rotate = false }) {
    const spec = OUTLINES[kind];
    if (!spec) return null;
    const { x, y, w, h } = spec.box;
    /* Отражение и поворот делает САМ рисунок, а не CSS.
     *
     * Повернуть контейнер через transform: rotate(90deg) мало: коробка остаётся
     * прежней, и развёрнутый силуэт вылезает за края экрана либо жмётся в
     * четверть его высоты. Поворот внутри viewBox меняет и коробку — рисунок
     * честно становится высоким и узким, а вписывание берёт на себя
     * preserveAspectRatio. */
    const body = flip
        ? <g transform={`translate(${2 * x + w},0) scale(-1,1)`}>{spec.art}</g>
        : spec.art;
    /* Поворот меняет коробку местами: то, что было по X, становится по Y.
       Сдвиг в translate подобран так, чтобы повёрнутый рисунок остался в тех же
       границах, — иначе он уезжает за viewBox и обрезается краем экрана. */
    return (
        <div className={`wt-cam__outline${rotate ? ' is-turned' : ''}`} aria-hidden="true">
            <svg
                viewBox={rotate ? `${y} ${x} ${h} ${w}` : `${x} ${y} ${w} ${h}`}
                preserveAspectRatio="xMidYMid meet"
            >
                {rotate
                    ? <g transform={`translate(${2 * y + h},0) rotate(90)`}>{body}</g>
                    : body}
            </svg>
        </div>
    );
}
