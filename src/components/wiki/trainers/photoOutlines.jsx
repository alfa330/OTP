/* Контуры-подсказки поверх видоискателя — те же, что рисует Яндекс Про.
 *
 * В приложении это не рамка и не уголки, а СИЛУЭТ: белая линия, в которую надо
 * вписать машину. Она объясняет без слов сразу три вещи — какой ракурс ждут, с
 * какого расстояния снимать и как держать телефон. Уголки, которые тренажёр
 * рисовал раньше, не говорили ни об одном из трёх.
 *
 * Формы намеренно схематичны: приложение рисует обобщённый седан, а не обвод
 * конкретной модели, — иначе водитель на кроссовере пытался бы совместить свою
 * машину с чужим силуэтом.
 *
 * У каждого контура СВОЙ viewBox, и это не мелочь: кузов лежит поперёк
 * (200×140), салон стоит вдоль (160×220). Общая коробка на всех растягивала
 * салон в ленту, и сиденья превращались в полоски.
 */

/* Профиль: нос слева. Арки — вырезы кривыми, а не дугами: дуга задаётся флагами
   направления, и перепутанный флаг заворачивает вырез наружу, превращая колесо
   в пузырь под кузовом. */
const SIDE = 'M 10 100 L 10 76 C 10 69 14 65 22 63 L 58 58 L 80 30 L 128 28 '
