/* Список тренажёров — один на весь раздел.
 *
 * Отсюда берут данные ТРИ места, и разойтись им нельзя:
 *   выбор в редакторе статьи (какой тренажёр вставить кнопкой),
 *   чтение статьи (по ключу из кнопки поднимается сценарий),
 *   вкладка «Тренажёры» (список с описанием и запуском).
 *
 * Почему сценарии живут в коде, а не в базе. Тренажёр — это не запись, а экраны
 * приложения, реплики помощника и ловушки: «нажал не туда — вот почему это
 * ошибка». Такое не набирается в форме, его пишут вместе с интерфейсом. База
 * добавила бы конструктор экранов, которым никто не пользовался бы, и таблицу,
 * которую пришлось бы миграциями догонять за каждым изменением инструкции.
 *
 * Ключ (`key`) уезжает в текст статьи (data-wiki-trainer) и остаётся там
 * навсегда — переименовывать его нельзя, иначе кнопки в опубликованных статьях
 * перестанут находить сценарий. Название и описание менять можно свободно.
 *
 * Модуль намеренно БЕЗ JSX и без React: его импортирует и редактор, и вкладка,
 * а тянуть за собой экраны тренажёра (телефон, барс, стили) им незачем — они
 * приезжают отдельным чанком вместе с самим проигрывателем.
 */

import crmTicket from './scenarioCrmTicket.js';
import operatorCall from './scenarioOperatorCall.js';
import photoControl from './scenarioPhotoControl.js';
import saparSite from './scenarioSapar.js';
import taxiPro from './scenarioTaxiPro.js';
import yandexPro from './scenarioYandexPro.js';
import { stageCount } from './runner.js';

/* Порядок фиксирован и читается по адресату.
   Первыми — рабочее место САМОГО оператора: сначала свободная среда (осмотреться
   в трёх системах), следом смена со звонком (то же место, но приходит вызов).
   Дальше — приложения ВОДИТЕЛЯ в порядке его дел: сначала выбрать провайдера
   ЭДО (без него подписывать нечего), потом основной способ подписания, потом
   запасной, потом фотоконтроль. Тот же порядок в инструкции — тренажёр не
   должен спорить с текстом рядом. */
export const TRAINERS = [crmTicket, operatorCall, yandexPro, taxiPro, saparSite, photoControl];

const BY_KEY = new Map(TRAINERS.map((scenario) => [scenario.key, scenario]));

/** Сценарий по ключу или null. Незнакомый ключ — не повод падать: статья могла
 *  переехать с тренажёром, которого в этой версии портала уже нет. */
export const findTrainer = (key) => BY_KEY.get(String(key || '')) || null;

/** Короткая карточка для списков: без шагов и без функций мира. */
export const trainerCard = (scenario) => ({
    key: scenario.key,
    title: scenario.title,
    subtitle: scenario.subtitle,
    app: scenario.app,
    description: scenario.description,
    stages: stageCount(scenario),
    checklist: scenario.checklist || [],
    /* Среда урока нужна витрине: она рисует рядом с карточкой телефон, а
       тренажёр за компьютером телефоном не показать — это отвечало бы на
       «где я это увижу» неправдой. */
    stage: scenario.stage || 'phone',
});

export const TRAINER_CARDS = TRAINERS.map(trainerCard);

/** Подпись кнопки по умолчанию — она же попадёт в текст статьи. */
export const defaultButtonLabel = (scenario) => `Открыть тренажёр: ${scenario.title}`;
