import { categoryNode, pathLabel } from './crmCatalog.js';

export const ANCHOR = '2026-08-23';
const ANCHOR_UTC = Date.UTC(2026, 7, 23);
const DAY = 24 * 3600 * 1000;
const two = (value) => String(value).padStart(2, '0');
const round2 = (value) => Math.round(value * 100) / 100;

/** «-1 06:02» → «2026-08-22T06:02»; «-35» → «2026-07-19». */
export const rel = (text) => {
    const [day, time] = String(text).trim().split(/\s+/);
    const at = new Date(ANCHOR_UTC + Number(day) * DAY);
    const date = `${at.getUTCFullYear()}-${two(at.getUTCMonth() + 1)}-${two(at.getUTCDate())}`;
    return time ? `${date}T${time}` : date;
};

/** Секунды между двумя ISO одного дела. */
const secondsBetween = (from, to) => Math.round((Date.parse(`${to}Z`) - Date.parse(`${from}Z`)) / 1000);

/** «2026-08-22T06:02:11» + секунды → ISO с секундами. */
const plus = (iso, seconds) => {
    const at = new Date(Date.parse(`${iso.length === 16 ? `${iso}:00` : iso}Z`) + seconds * 1000);
    return `${at.getUTCFullYear()}-${two(at.getUTCMonth() + 1)}-${two(at.getUTCDate())}`
        + `T${two(at.getUTCHours())}:${two(at.getUTCMinutes())}:${two(at.getUTCSeconds())}`;
};

/* Ведомость: операции от свежих к старым, баланс — остаток после операции. */
const ledger = (balanceNow, ops) => {
    let after = balanceNow;
    return ops.map(([when, event, order, category, amount, comment = '', by = 'Платформа'], index) => {
        const row = {
            id: `t${index + 1}`,
            at: rel(when),
            event,
            order: order || null,
            category,
            amount,
            balance: round2(after),
            comment,
            by,
            park: /партн[её]ра/.test(category),
        };
        after = round2(after - amount);
        return row;
    });
};

const STAGES = ['Создан', 'Выехал', 'На месте', 'В пути', 'Выполнено'];

/* Заказ. Этапы с секундами: ожидание клиента — это «В пути» минус «На месте»,
   и спор о минутах без секунд не разрешить. Не заданы — ставятся типовые. */
const order = ({
    number, uuid, at, done, status = 'complete', cancel = '', cancelledBy = '', from, to, category,
    km, price, payment, stages = null,
}) => {
    const start = rel(at);
    const end = done ? rel(done) : null;
    const marks = stages
        ? stages.map((when) => rel(when))
        : [plus(start, 0), plus(start, 25), plus(start, 300), plus(start, 360), end ? plus(end, 0) : null];
    return {
        id: uuid,
        number,
        at: start,
        finished_at: end,
        status,
        cancel_reason: cancel,
        cancelled_by: cancelledBy,
        from,
        to,
        category,
        km,
        price,
        payment,
        stages: STAGES.map((name, index) => ({ name, at: marks[index] }))
            .filter((stage) => stage.at)
            .filter((stage) => status === 'complete' || stage.name !== 'Выполнено'),
        trip_sec: end && marks[3] ? secondsBetween(marks[3], end) : null,
    };
};

/* GPS: события водителя. type — как их красит CRM (shiftBadgeClass). */
const GPS_LABELS = {
    login: 'Вход в Яндекс Про',
    logout: 'Выход из Яндекс Про',
    free: 'Свободен',
    busy: 'Занят',
    in_order: 'На заказе',
    offline: 'Офлайн',
    mode: 'Смена режима дохода',
    tariffs: 'Смена тарифов',
};

const gps = (rows) => rows.map(([when, type, sec = null, km = null, orderNumber = null, details = '']) => ({
    at: rel(when),
    type,
    label: GPS_LABELS[type] || type,
    sec,
    km,
    order: orderNumber,
    details,
}));

const SHOTS = ['Машина слева', 'Машина спереди', 'Машина справа', 'Машина сзади',
    'Открытый багажник', 'Задний ряд сидений', 'Передний ряд сидений'];

const photos = (rows) => rows.map(([day, ok, reason = '']) => ({
    date: rel(day), ok, reason, shots: SHOTS,
}));

const changes = (rows) => rows.map(([when, field, from, to, author]) => ({ at: rel(when), field, from, to, author }));

/* История номера в CRM. Категория — номер узла дерева CRM, подпись — путь,
   как его пишет форма обращения. */
const history = ({ requests = [], tickets = [] } = {}) => ({
    requests: requests.map(([id, when, typeId, operator, source = 'Звонок', ticket = null]) => ({
        id,
        at: rel(when),
        type_id: typeId,
        category: pathLabel(categoryNode(typeId)),
        operator,
        source,
        ticket,
    })),
    open_tickets: tickets.map(([id, when, status, typeId]) => ({
        id,
        at: rel(when),
        status,
        type_id: typeId,
        category: pathLabel(categoryNode(typeId)),
    })),
});

