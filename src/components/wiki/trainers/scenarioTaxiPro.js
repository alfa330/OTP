/* Тренажёр «Подписание закрывающих документов через приложение Такси.Про».
 *
 * В приложении два способа, и тренажёр учит обоим — способ выбирают на старте
 * (шаг-развилка, см. runner): кнопка в статье одна, путей два.
 *
 * «Через ЭЦП» (Такси.Про 4.3.2 от 17.11.2026: «Подпись ставится вашей ЭЦП прямо
 * в приложении… ЭЦП можно получить через eGov или в ЦОН и добавить в разделе
 * «Ключ ЭЦП»») — пять шагов, все по кадрам водителей:
 *   1. окно «Добавьте ЭЦП на этот телефон» → «Продолжить» (кадр 09.11) — пока
 *      ключа на телефоне нет, приложение показывает его само, даже если ключ
 *      есть в eGov Mobile (водитель прислал оба кадра подряд);
 *   2. раздел «Документы»;
 *   3. вкладка «Через ЭЦП»: пакет месяца «подписываются одним пакетом» →
 *      одна «Подписать» на все документы;
 *   4. «Документы подписаны · Время подписи», «Подтверждено Sapar» → «Готово»;
 *   5. вкладка пустеет («Сейчас подписывать нечего») → «История подписаний» с
 *      пакетом месяца.
 * Экранов после «Продолжить» (выпуск ключа или файл) и после «Подписать»
 * (пароль ключа?) нет ни на одном кадре за 17.10–18.11.2026 — их не рисуем,
 * а объясняет барс. Добавлять — только по скриншоту.
 *
 * «Через eGov» повторяет инструкцию из восьми пунктов: раздел «Документы» →
 * «Подписать» → закрыть рекламу в кабинете Сапар → «Подписать все документы» →
 * eGov Mobile → «Подписать» → «Продолжить» → обновить и проверить «Подписан».
 *
 * Экраны сверены с кадрами водителей из Chat2Desk за 17.10–17.11.2026. С ноября
 * приложение выглядит иначе, чем летом, и два пункта инструкции получили по
 * под-шагу, без которых до цели в новом интерфейсе не дойти:
 *   • раздел «Документы» открывается на вкладке «Через ЭЦП» (пакет подписывают
 *     ключом, загруженным в приложение), а акты с кнопкой «Подписать» — на
 *     вкладке «Через eGov»;
 *   • кабинет Сапар открывается не браузером, а окном приложения «Подписание
 *     документов» с крестиком. После eGov человек возвращается в это окно и видит
 *     главную страницу кабинета с «Вы успешно подписали АВР и закрыли ЭДО» —
 *     закрыть окно нужно самому, чтобы проверить статус в Такси.Про.
 *
 * Почему тренажёр, а не скриншоты в статье. Шаги, которые читаются как лишние,
 * именно на них водитель застревает: не та вкладка, рекламное окно поверх
 * кабинета, возврат из eGov и проверка статуса в конце. Ловушки на этих экранах
 * отвечают на «а что будет, если» — текстом инструкции такое не передаётся.
 *
 * ДАННЫЕ УЧЕБНЫЕ. ФИО, ИИН, госномер, телефон, суммы и номера документов
 * вымышлены, настоящая подпись не создаётся, наружу ничего не уходит.
 */

