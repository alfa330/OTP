/*
 * Цепочка открытых статей — путь, которым человек шёл по сети вики.
 *
 * До сих пор открытая статья была одним значением, и кнопка возврата означала
 * ровно «закрыть статью». Пока в статью попадали только из списка, это совпадало
 * с ожиданием. Со ссылками внутри текста и блоками «Связанные материалы» /
 * «Сюда ссылаются» совпадать перестало: человек читает «Тарифы», уходит по
 * ссылке в «Штрафы», жмёт возврат — и вместо «Тарифов» получает главную витрину.
 * Обратной дороги нет вообще: браузерное «назад» тоже не помогает, портал
 * намеренно не роутер (см. syncArticleDeepLink в articleLink.js), а найти
 * исходную статью заново — это поиск и ещё один заход.
 *
 * Поэтому открытая статья — не значение, а ВЕРШИНА цепочки. Каждый шаг вперёд
 * по сети статей кладёт новую запись, возврат снимает одну. Кончилась цепочка —
 * значит человек вернулся туда, откуда пришёл в статью, то есть в список.
 *
 * Модуль намеренно чистый и без React: правила цепочки — это единственное, что
 * в этой фиче можно сломать незаметно (лишний шаг, потерянная подпись, растущий
 * до бесконечности путь), и проверяются они без браузера — tests/wiki_article_trail.test.mjs.
 *
 * Запись цепочки:
 *   slug       — статья;
 *   highlight  — слово, по которому её нашли (подсветка в тексте);
 *   prefill    — заготовка для статьи-классификатора;
 *   title      — заголовок, известный ТОЛЬКО когда из этой статьи ушли дальше:
 *                до перехода витрина знает про статью один слаг;
 *   scrollTop  — где человек оборвал чтение, когда ушёл по ссылке.
 */

/* Потолок глубины. Цепочка — это «как я сюда попал», а не журнал чтения: два
   десятка шагов назад никто не отматывает, зато они держат в памяти позиции
   прокрутки и мешают понять, что кнопка вообще делает. Двенадцати хватает на
   любой реальный обход сети, а лишнее отрезается с ХВОСТА (самое старое). */
export const TRAIL_LIMIT = 12;

/** Статья на экране. null — открытой статьи нет, показывается витрина. */
export const trailTop = (trail) => (
    Array.isArray(trail) && trail.length ? trail[trail.length - 1] : null);

/** Куда уведёт возврат. null — возврат уведёт в список, а не в статью. */
export const trailBack = (trail) => (
    Array.isArray(trail) && trail.length > 1 ? trail[trail.length - 2] : null);

/** Открыть статью С НУЛЯ: из списка, из поиска, по ссылке из чата.
 *
 * Именно замена, а не добавление. Список — не шаг по сети статей: человек,
 * открывший статью из оглавления, ждёт от возврата список, а не статью, которую
 * читал десять минут назад в другой ветке.
 */
export const openTrail = (slug, extra = null) => (
    slug ? [{ slug, ...(extra || {}) }] : []);

/** Шаг ВПЕРЁД по сети статей: ссылка в тексте или строка в блоке связей.
 *
 * from — то, что известно про статью, ИЗ КОТОРОЙ уходим: её заголовок (для
 * подписи кнопки возврата) и позиция прокрутки (чтобы вернуть человека в то же
 * место текста, а не в начало). Дописывается вершине цепочки, потому что раньше
 * этого момента витрина заголовка не знает.
 *
 * Возврат НА УЖЕ ПРОЙДЕННУЮ статью цепочку не удлиняет, а обрезает до неё. Без
 * этого взаимная пара статей (а такие в вике помечены «Взаимная» и встречаются
 * штатно) наматывала бы «Тарифы → Штрафы → Тарифы → Штрафы», и кнопка возврата
 * обещала бы шаг назад там, где человек уже стоит.
 */
export const pushTrail = (trail, slug, from = null) => {
    const path = Array.isArray(trail) ? trail : [];
    if (!slug) return path;
    if (!path.length) return openTrail(slug);

    const top = path[path.length - 1];
    const marked = path.slice(0, -1).concat({
        ...top,
        title: from?.title || top.title || null,
        scrollTop: Number.isFinite(from?.scrollTop) ? from.scrollTop : (top.scrollTop || 0),
    });

    const seen = marked.findIndex((entry) => entry.slug === slug);
    if (seen !== -1) return marked.slice(0, seen + 1);

    const next = marked.concat({ slug });
    return next.length > TRAIL_LIMIT ? next.slice(next.length - TRAIL_LIMIT) : next;
};

/** Шаг НАЗАД. Пустая цепочка — статья закрыта, на экране снова список. */
export const popTrail = (trail) => (
    Array.isArray(trail) && trail.length ? trail.slice(0, -1) : []);

/** Подпись кнопки возврата. Длинный заголовок режем: кнопка стоит в строке с
 *  «Править», «Историей» и «Во весь экран», и на телефоне «Назад: Регламент
 *  подключения водителей на личном авто» выдавил бы их за край экрана.
 *
 *  Готовая подпись (`label`) старше заголовка: так подписана ДВЕРЬ, через
 *  которую вошли в статью с другой вкладки раздела — «К списку статей», «К
 *  журналу». Название статьи там взять неоткуда, да и незачем: возврат ведёт
 *  не в статью. */
export const backLabel = (entry, limit = 24) => {
    if (entry?.label) return String(entry.label);
    const title = String(entry?.title || '').trim();
    if (!title) return 'К списку';
    const short = title.length > limit ? `${title.slice(0, limit - 1).trimEnd()}…` : title;
    return `Назад: «${short}»`;
};
