/* Архив офисов: правила вкладки «Архив» без JSX — их читают тесты
 * (tests/wiki_office_archive.test.mjs). Файл не называется officeArchive.js:
 * на Mac имя без учёта регистра совпало бы с OfficeArchive.jsx.
 *
 * До вкладки архив жил тумблером «Показывать архивные» в панели фильтра: найти
 * его можно было, только зная, что он там есть, а архивные офисы приезжали
 * вперемешку с живыми и красились по своему графику — «Открыт до 19:00» у
 * офиса, которого больше нет. Теперь архив — отдельная вкладка рядом с
 * «Офисами», как у разделов и статей вики (WikiStructure, WikiCatalog).
 */

import { formatStamp } from './officeDayStatus.js';

/** Порядок вкладки «Архив»: недавно убранные сверху — за ними обычно и идут
 *  («только что убрал не тот офис»); без даты — в конце, по названию. */
export const archiveOrder = (offices, collator = new Intl.Collator('ru')) => (
    [...(offices || [])].sort((a, b) => {
        const left = a.archived_at || '';
        const right = b.archived_at || '';
        if (left !== right) {
            if (!left) return 1;
            if (!right) return -1;
            return left < right ? 1 : -1;
        }
        return collator.compare(a.name || '', b.name || '');
    })
);

/** «Убран в архив 12.10.2026 · Иванов Иван». Журнал не знает, кто убрал, —
 *  остаётся дата; не знает и когда — строки нет вовсе: «в архиве» про запись
 *  на вкладке «Архив» говорить незачем. */
export const archivedLine = (office) => {
    if (!office?.archived_at) return '';
    const by = String(office.archived_by || '').trim();
    return `Убран в архив ${formatStamp(office.archived_at)}${by ? ` · ${by}` : ''}`;
};

/** Вопрос перед архивацией. Тот же разговор, что у разделов и статей вики
 *  (WikiStructure, WikiCatalog): что пропадёт и где это потом найти. Без него
 *  офис уезжал в архив от одного промаха по значку 32 × 32 в строке таблицы.
 *
 *  Обещать здесь можно только то, что правда случится. Список, поиск вики
 *  (wiki/directory.py) и выбор офиса в других разделах (посылки, термобоксы,
 *  вода, CRM, обращения, города) читают только действующие офисы. А вот
 *  головным офисом парка («Парки», карточка парка у помощника) архивный офис
 *  остаётся — поэтому «из ответов помощника» в тексте нет. */
export const archiveConfirmText = (office) => (
    `Убрать офис «${office?.name || ''}» в архив?\n\n`
    + 'Он пропадёт из списка, из поиска и из выбора офиса в других разделах. '
    + 'Вернуть его можно на вкладке «Архив».'
);
