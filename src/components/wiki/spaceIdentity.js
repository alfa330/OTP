/* Как пространство узнаётся в списке: значок, монограмма, поиск по названию.
 *
 * Отдельным модулем, а не внутри переключателя: это чистые правила, и они
 * обязаны проверяться без браузера (tests/wiki_space_switch.test.mjs). Внутри
 * .jsx их пришлось бы либо экспортировать наружу «для теста», либо не
 * проверять вовсе — а ошибка здесь молчаливая: человек просто не находит свою
 * вику в списке и думает, что её отобрали.
 */

/* Со скольких пространств в меню появляется строка поиска.
 *
 * До семи список читается глазами целиком, и поле поиска над ним — лишний
 * элемент в окне, которое открывают на секунду. С восьми список уже
 * прокручивается, и найти в нём «Тез КЦ» среди похожих названий быстрее
 * набором двух букв. */
export const SPACE_SEARCH_THRESHOLD = 8;

/* Emoji-значок пространства (колонка wiki_spaces.icon).
 *
 * В колонке VARCHAR(64), и лежать там может что угодно — она осталась от
 * первой версии структуры, где предполагались имена иконок вроде 'book'.
 * Значком считаем только КОРОТКУЮ строку без латиницы и кириллицы: имя
 * иконки, отрисованное как текст, выглядит в списке как мусор («book» в
 * квадратике), а пустая строка из базы — как пропавший значок.
 */
export const spaceIcon = (space) => {
    const raw = typeof space?.icon === 'string' ? space.icon.trim() : '';
    if (!raw || raw.length > 4) return '';
    return /[a-zA-Zа-яА-ЯёЁ0-9_-]/.test(raw) ? '' : raw;
};

/** Монограмма — запасной значок, когда emoji не выбран.
 *
 *  Берём первые буквы первых двух слов («Тез КЦ» → «ТК»), а односложное имя
 *  сокращаем до одной буквы: две первые буквы одного слова («ТА» от
 *  «Таксопарки») читаются как чужая аббревиатура. */
export const spaceMonogram = (space) => {
    const words = String(space?.name || '')
        .split(/[\s—–-]+/)
        .map((word) => word.trim())
        .filter(Boolean);
    if (!words.length) return '#';
    if (words.length === 1) return words[0].slice(0, 1).toUpperCase();
    return (words[0].slice(0, 1) + words[1].slice(0, 1)).toUpperCase();
};

/* Поиск по списку пространств.
 *
 * Ищем и по названию, и по коду ('igroup'): код виден в адресах и в выгрузках,
 * и человек, пришедший из письма, набирает именно его. Регистр и лишние
 * пробелы не важны — это поле для быстрого набора, а не фильтр отчёта. */
export const matchesSpaceQuery = (space, query) => {
    const needle = String(query || '').trim().toLowerCase();
    if (!needle) return true;
    return [space?.name, space?.code, space?.description]
        .some((field) => String(field || '').toLowerCase().includes(needle));
};

/** Отбор для меню: сохраняем порядок сервера (он же position). */
export const filterSpaces = (spaces, query) =>
    (spaces || []).filter((space) => matchesSpaceQuery(space, query));
