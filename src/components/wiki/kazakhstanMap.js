/** Точка города на схеме или null, если координат нет. */
export const cityPoint = (name) => {
    const coords = CITY_COORDS[String(name || '').trim()];
    if (!coords) return null;
    const [x, y] = project(coords[0], coords[1]);
    return { x, y, side: LABEL_SIDE[String(name).trim()] || 'right' };
};
