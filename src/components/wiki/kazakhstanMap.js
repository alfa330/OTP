/* ── Вид схемы: приближение и сдвиг ─────────────────────────────────────────
 * Вид — окно в координатах схемы {x, y, w}; высота выводится из пропорции
 * схемы, поэтому окно никогда не искажает контур. Правила — здесь, без JSX,
 * чтобы их можно было проверить тестами (tests/wiki_city_rules.test.mjs). */

export const FULL_VIEW = { x: 0, y: 0, w: MAP_WIDTH };

/* Сильнее пятикратного приближать незачем: ближе всего стоят Караганда и
   Темиртау, и на ×5 они уже расходятся с запасом. */
export const MIN_VIEW_WIDTH = MAP_WIDTH / 5;

export const viewHeight = (view) => view.w * (MAP_HEIGHT / MAP_WIDTH);

/** Окно в допустимых границах: не мельче ×5, не крупнее всей схемы и не за краем. */
export const clampView = (view) => {
    const w = Math.min(MAP_WIDTH, Math.max(MIN_VIEW_WIDTH, view.w));
    const h = viewHeight({ w });
    return {
        w,
        x: Math.min(MAP_WIDTH - w, Math.max(0, view.x)),
        y: Math.min(MAP_HEIGHT - h, Math.max(0, view.y)),
    };
};

/** Приблизить в factor раз так, чтобы точка (cx, cy) осталась под пальцем. */
export const zoomView = (view, factor, cx, cy) => {
    const w = Math.min(MAP_WIDTH, Math.max(MIN_VIEW_WIDTH, view.w / factor));
    const ratio = w / view.w;
    return clampView({ w, x: cx - (cx - view.x) * ratio, y: cy - (cy - view.y) * ratio });
};

/** Окно, в которое целиком входят точки, с полями. Одна точка — ×3 вокруг неё. */
export const fitView = (points, margin = 70) => {
    const list = (points || []).filter(Boolean);
    if (!list.length) return FULL_VIEW;
    const xs = list.map((p) => p.x);
    const ys = list.map((p) => p.y);
    const minX = Math.min(...xs) - margin;
    const maxX = Math.max(...xs) + margin;
    const minY = Math.min(...ys) - margin;
    const maxY = Math.max(...ys) + margin;
    const w = Math.max(maxX - minX, (maxY - minY) * (MAP_WIDTH / MAP_HEIGHT), MAP_WIDTH / 3);
    const cx = (minX + maxX) / 2;
    const cy = (minY + maxY) / 2;
    return clampView({ w, x: cx - w / 2, y: cy - viewHeight({ w }) / 2 });
};
