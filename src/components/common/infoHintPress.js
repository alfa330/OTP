/*
 * Правила подсказки «i» для разных способов ввода. Вынесены из компонента,
 * чтобы проверяться без браузера: на глаз их не поймать — на компьютере
 * подсказка работает при любой ошибке здесь, ломается только телефон.
 */

/* Наведение открывает подсказку только у мыши. Касание тоже порождает
   «наведение»: браузер достраивает его перед кликом, и, если на него
   откликаться, подсказка открывается ещё до клика. */
export const hoverOpensHint = (pointerType) => pointerType === 'mouse';

/* Закрывает ли клик подсказку.
   `openOnPress` — была ли она открыта В МОМЕНТ НАЖАТИЯ указателем; `null` —
   нажатия не было (Enter, пробел, экранный диктор): тогда переключаем по тому,
   что на экране сейчас.
   Смотреть на «сейчас» при нажатии указателем нельзя: между нажатием и кликом
   кнопка получает фокус, фокус подсказку открывает, и клик тут же закрыл бы
   её. Так и было на телефоне — с первого касания «i» не показывал ничего. */
export const clickClosesHint = ({ openOnPress, open }) => (
  openOnPress === null || openOnPress === undefined ? Boolean(open) : Boolean(openOnPress)
);
