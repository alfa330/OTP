/* Почему звонок кончился без разговора — приписка под попыткой в истории водителя.
 *
 * Трубку мог положить сам телефон оператора (автосброс):
 *   • на гудках — водитель не взял трубку за заданное отделом число гудков
 *     (владелец, 11.10.2026);
 *   • на сообщении сети «абонент недоступен» — телефон с 3.22.34 слышит его и не
 *     заставляет оператора дослушивать (владелец, 12.10.2026).
 * И то и другое — обычный недозвон: попытка засчитана, итог по ней не нужен. Это
 * не отмена оператором, поэтому и подпись своя.
 *
 * Отдельный модуль без React — на него написан node-тест
 * (tests/dial_list_attempt_hints.test.mjs). Здесь то, в чём нельзя разойтись с
 * сервером (dial_list/service.py, lead_card): какой ключ что значит и когда
 * приписка была бы неправдой.
 */

export const RING_TIMEOUT_HINT = ' · сброшен автоматически: водитель не взял трубку';
export const ANNOUNCEMENT_HINT = ' · сброшен автоматически: сообщение сети «абонент недоступен»';

/**
 * Приписка автосброса для попытки из карточки водителя; '' — трубку клал не телефон.
 *
 * attempt.auto_hangup — причина словом ('announcement' | 'ring_timeout' | ''), её
 * отдаёт сервер с 12.10.2026; attempt.ring_timeout — прежний флаг сброса на гудках
 * (у сообщения сети сервер его не ставит: сборка сайта, которая ключа auto_hangup
 * ещё не знает, написала бы «водитель не взял трубку»). Сервер постарше ключа не
 * присылает — тогда решает один флаг, как раньше.
 *
 * Разговор (водитель ответил в последний момент) и отменённая попытка приписки не
 * получают: про них она была бы неправдой.
 */
export const autoHangupHint = (attempt) => {
    if (!attempt) return '';
    const result = attempt.result;
    if (result === 'answered' || result === 'cancelled') return '';
    if (attempt.auto_hangup === 'announcement') return ANNOUNCEMENT_HINT;
    if (attempt.ring_timeout || attempt.auto_hangup === 'ring_timeout') return RING_TIMEOUT_HINT;
    return '';
};
