/*
 * Какие отделы в «Настройках SIP» ведёт раздел «Обзвон из телефона».
 *
 * У такого отдела линию Binotel сотруднику назначают во вкладке «Линии» раздела,
 * учётка АТС проставляется сама — и карточка сотрудника показывает здесь только
 * подсказку: полей и кнопки «Сохранить» в ней нет.
 *
 * Признак — ВКЛЮЧЁННЫЙ режим обзвона, а не то, что отдел подключён к разделу.
 * «Подключить отдел» заводит строку настроек одним нажатием и с выключенным
 * режимом: операторы такого отдела вкладку «Обзвон» в телефоне не видят,
 * работают на обычном телефоне, и учётку АТС им вводят именно здесь. 01.10.2026
 * так подключили Тез КЦ — и карточки всех его операторов остались без полей:
 * новому сотруднику нельзя было завести ни SIP-логин, ни кабинет.
 *
 * Логика без React: её сторожит tests/sip_dial_list_card.test.mjs.
 */

/**
 * departments — список из GET /api/dial_list/departments (поле departments;
 * кандидаты на подключение сюда не передаются). Возвращает Set числовых id.
 */
export const dialListManagedDepartmentIds = (departments) => new Set(
    (Array.isArray(departments) ? departments : [])
        .filter((d) => d && d.enabled === true)
        .map((d) => Number(d.department_id))
        .filter((id) => Number.isFinite(id))
);
