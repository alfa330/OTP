/* Высота карточки раздела «Обращения» — счётом, а не константой.
 *
 * Было `lg:h-[calc(100vh-300px)]`: 300 px это «шапка раздела с фильтрами, на
 * глаз». Ошибка вычитаемого видна сразу — под карточкой оставалась полоса
 * пустоты в полтораста пикселей, а на другом разрешении вылезала бы обратная
 * беда: поле ответа под краем экрана. Причём высота шапки не постоянна вовсе:
 * фильтры переносятся по строкам, у части людей сверху висит баннер дня
 * рождения, а на телефоне фильтры при открытом обращении убраны совсем.
 *
 * Поэтому карточка занимает ровно то, что осталось до низа видимой области, и
 * пересчитывается при изменении размеров. Здесь — сама арифметика, отдельно от
 * React: в разметке её нельзя было бы проверить, а ошибка в ней выглядит как
 * «раздел криво сверстан».
 */

// Пол высоты: ниже карточка перестаёт быть рабочей — от переписки остаётся
// одна реплика. Дальше пусть лучше едет страница.
export const MIN_HEIGHT = 380;

/* Сколько отдать карточке.
 *
 *   viewport      — высота видимой области прокрутчика (clientHeight);
 *   offsetTop     — от верха его области прокрутки до верха карточки;
 *   paddingBottom — нижний отступ прокрутчика: он тоже занимает место;
 *   gap           — воздух под карточкой.
 *
 * Возвращает null, когда мерить нечего: до первого кадра размеров нет, и
 * навязывать в этот момент высоту значило бы мигнуть неправильной.
 */
export const fitHeight = ({ viewport, offsetTop, paddingBottom = 0, gap = 0 } = {}) => {
    if (!viewport || !Number.isFinite(viewport) || !Number.isFinite(offsetTop)) return null;
    const free = viewport - offsetTop - paddingBottom - gap;
    return Math.round(Math.max(MIN_HEIGHT, free));
};

/* Размеры прокрутчика и карточки в нём — в одном месте, чтобы эффект в
 * компоненте оставался в три строки.
 *
 * Прокрутчик у портала свой (.main-content), а не окно: раздел живёт внутри
 * него, и высота окна к делу не относится — от неё ещё отнимаются его
 * собственные отступы. Если разметка изменится и .main-content не найдётся,
 * падать нельзя: считаем по документу, это хуже, но работает.
 */
export const measureShell = (node) => {
    if (!node || typeof window === 'undefined') return null;
    const scroller = node.closest('.main-content') || document.documentElement;
    const style = window.getComputedStyle(scroller);
    return {
        viewport: scroller.clientHeight,
        // Разница верхов + прокрутка = положение карточки в области прокрутки.
        // Через rect, а не offsetTop: между ними может стоять сколько угодно
        // обёрток без position, и offsetTop считался бы не от прокрутчика.
        offsetTop: node.getBoundingClientRect().top
            - scroller.getBoundingClientRect().top
            + scroller.scrollTop,
        paddingBottom: parseFloat(style.paddingBottom) || 0,
    };
};
