import React from 'react';
import { Quote } from 'lucide-react';

/*
 * Слова оператора в заявке по смене (задача #349).
 *
 * Раньше причина была самой бледной строкой карточки: мельче и светлее
 * интервала, без всякой отметки, — руководитель её пропускал. Теперь это
 * цитата по образцу оценки звонков (CriteriaReviewPanel): нейтральный фон и
 * кавычки. Цвета нет намеренно: причина есть у каждой второй заявки, и
 * красить её значило бы красить половину очереди.
 *
 * Текст не обрезается — ради него блок и существует. Переносы строк оператора
 * сохраняются, длинное слово без пробелов рвётся, а не раздвигает карточку.
 *
 * Не flex и не сетка: оболочка телефона (mobile-shell.css) даёт скруглённому
 * серому flex-блоку боковую прокрутку, а произвольную сетку схлопывает в одну
 * колонку. Значок стоит абсолютно, текст — обычным блоком.
 *
 * Ширина — по тексту, но не шире места (w-fit max-w-full): короткая причина
 * остаётся короткой цитатой, а не полосой во всю карточку. Отступ слева блоку
 * задаёт обёртка на месте вставки, а не margin на нём самом — с margin
 * «не шире места» превратилось бы в «шире на величину отступа».
 */
export default function ShiftRequestComment({ text, className = '' }) {
  const value = String(text || '').trim();
  if (!value) return null;
  return (
    <p className={`relative w-fit max-w-full whitespace-pre-line break-words rounded-lg bg-slate-50 py-1.5 pl-7 pr-2.5 text-[13px] leading-snug text-slate-800 ring-1 ring-slate-100 ${className}`}>
      <Quote size={13} className="absolute left-2.5 top-[9px] text-slate-400" aria-hidden="true" />
      {value}
    </p>
  );
}
