/*
 * Тип звонка в окне «Случайный звонок»: ОДИН выбор из трёх, а не две галочки.
 *
 * Почему это отдельный файл и почему выбор один. Раньше в окне стояли две галочки,
 * обе включённые: «Исходящие» и «Входящие». Супервайзер, которому нужен входящий,
 * нажимал «Входящие» — и этим СНИМАЛ галочку, оставляя одни исходящие. Ровно это и
 * приходило: за 12–19.09.2026 по кнопке пришло 23 исходящих звонка против двух
 * входящих. Ошибка была не в подборе (фильтр по типу верен во всех трёх АТС), а в
 * том, что нажатие означало обратное намерению.
 *
 * Здесь же перевод выбора в пару флагов запроса: сервер по-прежнему принимает
 * incoming/outgoing, и «Любые» — это оба, как было по умолчанию.
 */

export const CALL_KIND_ANY = 'any';
export const CALL_KIND_IN = 'in';
export const CALL_KIND_OUT = 'out';

export const CALL_KIND_OPTIONS = [
    { value: CALL_KIND_ANY, label: 'Любые' },
    { value: CALL_KIND_IN, label: 'Входящие' },
    { value: CALL_KIND_OUT, label: 'Исходящие' },
];

/** Выбор → флаги запроса. Незнакомое значение считается «Любые»: пустой запрос
 *  (ни одного типа) сервер отвергает, и окно молча ничего бы не дало. */
export function callKindFlags(kind) {
    if (kind === CALL_KIND_IN) return { incoming: true, outgoing: false };
    if (kind === CALL_KIND_OUT) return { incoming: false, outgoing: true };
    return { incoming: true, outgoing: true };
}
