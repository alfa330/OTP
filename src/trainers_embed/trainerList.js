/* Какие тренажёры показывать в iCORE Phone.
 *
 * Реестр общий с вики (components/wiki/trainers/registry.js), но телефону нужны не
 * все. Владелец (25.09.2026) убрал со страницы телефона три:
 *   - «Рабочее место оператора» и «Звонок водителя» — тренажёры рабочего места за
 *     компьютером (CRM, Oktell): оператор на смене и так сидит в этих системах,
 *     а в узком окне телефона «окно браузера на компьютере» не помещается;
 *   - «Фотоконтроль машины» — 3D-сцена, в телефоне ей не место.
 * Остаются тренажёры приложений ВОДИТЕЛЯ (Яндекс Про, Такси.Про, сайт Сапар) —
 * ровно то, по чему оператор подсказывает водителю во время разговора.
 *
 * Список скрытых, а не разрешённых: новый тренажёр приложения водителя должен
 * появиться в телефоне сам, без правки здесь. Ключи — те же, что в статьях вики
 * (data-wiki-trainer), они не переименовываются.
 *
 * Модуль без React: его читают тесты через node.
 */

export const PHONE_HIDDEN_TRAINERS = Object.freeze(new Set([
    'crm-ticket-create',   // Рабочее место оператора
    'operator-call',       // Звонок водителя
    'photo-control-car',   // Фотоконтроль машины
]));

/** Тренажёры для страницы телефона — в порядке реестра, без скрытых. */
export const phoneTrainers = (all) => (all || []).filter(
    (scenario) => scenario && !PHONE_HIDDEN_TRAINERS.has(scenario.key),
);
