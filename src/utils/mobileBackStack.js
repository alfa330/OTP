/* Системное «назад» на телефоне: свайп от края в iOS и кнопка «назад» в Android.
 *
 * ЧЕГО НЕ ХВАТАЛО. Портал — одна страница: разделы и окна живут состоянием, а
 * не адресом, и записей в истории браузера не заводит НИ ОДНА из них (во всём
 * App.jsx только history.replaceState, чистящий адрес). Поэтому жест «назад»
 * на телефоне не делал ничего — владелец так и написал: «просто делаю назад, а
 * оно не идёт назад». Здесь каждый открытый экран и каждый переход между
 * разделами кладётся в СВОЙ стек, а браузеру достаётся ровно одна запись —
 * сторожевая, — которую жест и снимает.
 *
 * ПОЧЕМУ У КАЖДОГО СЛОЯ СВОЯ ЗАПИСЬ. Это решает не удобство, а iOS: во время
 * маха пальцем от края система показывает не живую страницу, а СНИМОК той
 * записи, куда человек возвращается. Снимок делается в момент УХОДА с записи и
 * больше не обновляется.
 *
 * Пока запись была одна на все слои, снимок у неё был один — сделанный в ту
 * секунду, когда открылся первый слой, то есть с разделом, а не с тем, что
 * лежит под закрываемым окном. Владелец 11.09.2026 прислал видео: экран
 * «Пароль» уезжает вправо, а из-под него выезжает раздел «Супервайзеры», и
 * только через треть секунды, когда переход завершился, появляется живой
 * профиль. Со стороны это «свайп перекидывает в другой раздел и обратно в
 * профиль»; ни в одном замере состояния этого не видно — DOM и адрес всё это
 * время правильные, потому что показанное системой к DOM отношения не имеет.
 *
 * С записью на слой снимок берётся ровно тогда, когда надо: открывая экран
 * поверх профиля, мы уходим с записи профиля — и её снимком становится профиль.
 * Жест возвращается на неё и показывает его же.
 *
 * ЧЕМ ЭТО БЕЗОПАСНО. Записи плодились и раньше, и от них отказались, потому что
 * публикация на Pages подменяет сборку разом: у открытого приложения остаётся
 * прежняя, первый ленивый кусок отвечает 404, портал лечится перезагрузкой
 * (src/staleBundleRecovery.js), и записи, положенные ДО неё, принадлежат
 * ПРЕЖНЕМУ документу — шаг назад в них грузит приложение заново. Но это про
 * записи НИЖЕ дна, а дно кладётся сразу после перезагрузки: ниже него жест не
 * пускает вовсе (см. handlePop). Наши записи всегда лежат ВЫШЕ дна и всегда
 * принадлежат живому документу, сколько бы их ни было.
 *
 * Своих шагов назад у стека при этом по-прежнему нет: лишние записи не
 * снимаются, а срезаются следующим pushState — он отбрасывает всё, что было
 * впереди.
 *
 * ПОЧЕМУ ОДИН СТЕК И ОДИН СЛУШАТЕЛЬ. Экраны вкладываются друг в друга (окно
 * поверх окна), и «назад» обязано снимать РОВНО верхний. Разложенные по
 * компонентам слушатели popstate сработали бы все разом и закрыли бы всё
 * стопкой.
 *
 * ПОЧЕМУ СВЕРКА ОТЛОЖЕНА ДО МИКРОЗАДАЧИ. Один кадр React закрывает один экран и
 * открывает другой: шторку разделов сменяет «Сменить логин». Сначала отработают
 * ВСЕ уборки, потом ВСЕ подписки — порядок не наш, его задаёт React. Правя
 * историю на месте, мы бы успели снять сторожевую запись и положить её заново,
 * а `history.back()` в браузере ОТЛОЖЕН, тогда как pushState мгновенен: шаг
 * назад уводил бы уже из-под новой записи. Поэтому история сверяется один раз
 * за кадр, когда он собран целиком: нужна сторожевая или нет.
 */

/* Что открыто: экраны и переходы между разделами, верхний — последний. */
const stack = [];
let listening = false;
/* Заведено ли своё дно — запись, ниже которой «назад» уводить не должно.
   Ставится один раз и живёт до конца сеанса. */
let rooted = false;
/* Номера наших записей над дном, снизу вверх: по одной на каждый открытый слой.
   Не счётчик, а список: жест может утащить сразу несколько, и тогда лишние
   отсекаются по номеру приземления, а не вычитанием. */
let guards = [];
let syncScheduled = false;
/* Номер дна. Каждой своей записи мы кладём в состояние возрастающий номер, а
 * номер ДНА помним здесь, в переменной.
 *
 * Зачем. Мах пальцем от края отдаёт браузеру ДВА перехода: первый снимает
 * сторожевую (мы закрываем слой и кладём сторожевую заново), второй приходит
 * уже НИЖЕ ДНА. Отличить его от честного второго жеста по флагу нельзя — флаг к
 * тому времени снова поднят.
 *
 * По ВРЕМЕНИ между переходами — тоже нельзя, и это проверено дорогой ценой:
 * разрыв меряется не между переходами, а между ВЫЗОВАМИ обработчика, а
 * обработчик бывает долгим — закрытие окна и отрисовка раздела занимают больше
 * сотни миллисекунд, и хвост переставал быть хвостом.
 *
 * Номер отвечает точно: приземлились на дно — шаг был ровно один. Приземлились
 * куда-то ещё (номера нет — запись не наша) — жест утащил глубже, закрывать
 * нечего.
 *
 * Читаем номер ТОЛЬКО у записи, на которую приземлились: она лежит НИЖЕ нас, и
 * чужой replaceState до неё не дотягивается — он правит текущую. Именно на этом
 * сгорела попытка судить по меткам otpRoot/otpBack у ТЕКУЩЕЙ записи: роутер
 * «Курсов» переписывает её состояние, метка гасла, и жест в этом разделе
 * умирал целиком. */
let floorSeq = null;
let seq = 0;
/* Чем вернуть адрес, когда жест уводит НИЖЕ дна. Там лежит запись с прежним
   адресом — обычно с экрана входа, ещё без ?view=, — и, восстановив дно молча,
   мы оставили бы человека с адресом без раздела. Сам он этого не увидит, но
   следующая перезагрузка (а её приносит каждая публикация) открыла бы ему
   раздел по умолчанию вместо того, где он стоит. */
let floorUrl = null;

const canTouchHistory = () => typeof window !== 'undefined'
    && typeof window.history?.pushState === 'function';

/* Стоим ли мы прямо сейчас на своём дне. Метку может стереть чужой
   replaceState (так делает роутер «Курсов»), и тогда ответ будет «нет» — это
   безопасная сторона ошибки: лишнее дно ничего не ломает, пропущенное выводит
   из портала. */
const standingOnFloor = () => {
    try {
        return window.history.state?.otpRoot === true;
    } catch (error) {
        return false;
    }
};

/* Своя запись-дно. Именно pushState, а не replaceState: заменять текущую
   запись нельзя — под нами может лежать адрес, с которого человек в портал
   пришёл, и он бы пропал. */
const armRoot = () => {
    if (!canTouchHistory()) return;
    let url = null;
    try {
        url = floorUrl?.() || null;
    } catch (error) {
        url = null;
    }
    /* Метку дна ставим, а метку сторожевой СНИМАЕМ: состояние копируется с
       текущей записи, и унаследованный otpBack сделал бы дно неотличимым от
       сторожевой — а отличать их приходится (см. standingOnFloor). */
    seq += 1;
    floorSeq = seq;
    window.history.pushState(
        { ...(window.history.state || {}), otpRoot: true, otpBack: false, otpSeq: seq },
        '',
        url || window.location.href,
    );
    rooted = true;
    /* Дно — не слой: над ним снова пусто. */
    guards = [];
};

/* Вернуть СВОЙ адрес на текущую запись истории.
 *
 * ЗАЧЕМ. Наши записи — дно и сторожевая — держат тот адрес, который был в
 * строке в момент их появления, и он в них ЗАМЕРЗАЕТ: сменив раздел, портал
 * правит адрес только у ТЕКУЩЕЙ записи (replaceState), до лежащих ниже ему не
 * дотянуться. Замер 11.09.2026 (плёнка history с самого входа): дно получает
 * `?view=wiki` в ту секунду, когда человек первый раз уходит из стартового
 * раздела, и держит его весь сеанс. Дальше любой шаг назад приземляется на
 * дно, браузер восстанавливает ЕГО адрес, роутер послушно читает и уводит
 * портал в Вики — хотя жест закрывал всего лишь экран поверх профиля.
 *
 * Ровно это владелец описывал трижды: «свайп перекидывает в другой раздел, а
 * не в профиль». И это же было источником «пролагов»: подмена раздела тянет за
 * собой полную перерисовку чужого раздела на каждый жест.
 *
 * Поэтому адрес возвращается ПЕРВОЙ же строкой обработчика — до того, как его
 * прочитает роутер (подписка стека идёт раньше, см. layout-эффект в App).
 * Раздел, который жест открывает по-настоящему (шаг между разделами), ставит
 * свой адрес сам, уже после нас. */
const restoreOwnUrl = () => {
    if (!canTouchHistory() || typeof floorUrl !== 'function') return;
    let url = null;
    try {
        url = floorUrl();
    } catch (error) {
        url = null;
    }
    if (!url) return;
    try {
        /* Состояние оставляем как есть: в нём лежит счётчик роутера (idx), и
           подмена его своим сбила бы роутеру собственный учёт. */
        window.history.replaceState(window.history.state, '', url);
    } catch (error) {
        /* Адрес другого происхождения — правило не про нас. */
    }
};

/* Есть ли прямо сейчас на экране открытое окно. Метку `otp-modal-root` ставят
   все примитивы окон и экраны разделов; уезжающее окно (`is-leaving`) уже
   закрыто и в счёт не идёт. */
const hasOpenScreen = () => {
    try {
        return Boolean(document.querySelector('.otp-modal-root:not(.is-leaving)'));
    } catch (error) {
        return false;
    }
};

/* Привести историю к тому, что у нас открыто: на каждый слой — своя запись.
   Никаких многошаговых перемоток и никаких своих шагов назад. */
const sync = () => {
    syncScheduled = false;
    if (!canTouchHistory()) return;
    /* ДНО ПОД ЗАПИСЯМИ ОБЯЗАНО БЫТЬ. Мах пальцем отматывает две записи разом
       (замерено), дно при этом проскакивается, и следующая запись легла бы уже
       на загрузочную запись документа — а с неё любой шаг уводит из портала. */
    if (!guards.length && !standingOnFloor()) armRoot();
    while (guards.length < stack.length) {
        seq += 1;
        guards.push(seq);
        /* Прежнее состояние сохраняем: в нём лежит то, что положил роутер
           адреса (urlHygiene зовёт replaceState с window.history.state).
           Адрес не меняем — запись служебная, человек её не видит. */
        window.history.pushState(
            { ...(window.history.state || {}), otpRoot: false, otpBack: true, otpSeq: seq },
            '',
        );
    }
    /* Слоёв стало меньше, чем записей? Лишние ОСТАЮТСЯ ВИСЕТЬ. Снимать их своим
     * шагом назад нельзя: этот шаг складывается с ходом пальца в один переход
     * на две записи, и портал уходит ниже дна без всякого жеста (замер
     * 11.09.2026 — так уводило из документа совсем).
     *
     * Цена названа честно: закрыв слой крестиком, человек потратит один мах
     * впустую — тот израсходует оставшуюся запись. Закрывать в этот момент и
     * правда нечего, а «жест ничего не сделал» несравнимо лучше, чем
     * «приложение ушло из портала». */
};

const scheduleSync = () => {
    if (syncScheduled || !canTouchHistory()) return;
    syncScheduled = true;
    /* Микрозадача, а не таймер: к её выполнению кадр уже собран, а нажать
       человек ещё не успел. Через Promise, а не queueMicrotask: вынутый из
       window, он в Chrome падает с «Illegal invocation». */
    Promise.resolve().then(sync);
};

const handlePop = () => {
    /* ПЕРВЫМ ДЕЛОМ — СВОЙ АДРЕС. Браузер только что восстановил адрес чужой
       записи, и роутер прочитает его следующим же слушателем. */
    restoreOwnUrl();

    /* СЧИТАЕМ СВОИ ЗАПИСИ, А НЕ ЧИТАЕМ ИХ СОСТОЯНИЕ.
     *
     * Метку в history.state читать нельзя: роутер «Курсов» переписывает
     * состояние ТЕКУЩЕЙ записи своим, и наша метка на ней гаснет. Замер
     * 11.09.2026: после захода в «Курсы» первый же шаг назад приходил «на чужую
     * запись», мы возвращали дно и не закрывали ничего — «назад» из Курсов
     * переставал работать с первого раза.
     *
     * Счёт живёт в переменной модуля: его не сотрёт никто. Пока над дном есть
     * хоть одна наша запись — шаг назад наш, и он закрывает верхний слой. Когда
     * их не осталось, жест ушёл ниже дна: там закрывать нечего, а уйти из
     * портала нельзя — возвращаем дно на место. */
    if (!guards.length) {
        armRoot();
        scheduleSync();
        return;
    }
    guards.pop();

    /* ПОД ОТКРЫТЫМ ОКНОМ РАЗДЕЛ НЕ МЕНЯЕТСЯ.
     *
     * Окно портала обязано само проситься в этот стек (`useScreenBackGesture`),
     * но забыть об этом легко: на 11.09.2026 так было у девяти окон — пять из
     * них в «Задачах». Жест тогда перешагивал через окно и снимал запись
     * ПЕРЕХОДА МЕЖДУ РАЗДЕЛАМИ: человек свайпал, чтобы закрыть окно, а получал
     * чужой раздел. Общая страховка на всё, что напишут дальше. */
    const top = stack[stack.length - 1];
    if (top?.section && hasOpenScreen()) {
        scheduleSync();
        return;
    }

    if (top) {
        stack.pop();
        /* close вернул false — слой решил остаться (обязательная новость,
           неоконченная отправка). Возвращаем его в стек: сверка положит запись
           заново, и следующий жест снова придёт к нему, а не провалится мимо и
           сменит раздел ПОД ним. */
        if (top.close() === false) stack.push(top);
        scheduleSync();
        return;
    }

    /* СТЕК ПУСТ — ЭТО ДНО, И УХОДИТЬ С НЕГО НЕКУДА. Возвращаем указатель на
       место своей же записью.

       Почему это обязательно. Портал — одно приложение на одной странице, и
       «назад» ниже его корня выводит из ДОКУМЕНТА: человек остаётся на белом
       экране. В браузере оттуда есть выход адресной строкой, а в установленном
       портале нет ни строки, ни кнопки «вперёд» — только закрыть приложение и
       открыть заново.

       Так же ведут себя обычные приложения: на первом экране «назад» ничего не
       делает, а не выбрасывает наружу. */
    armRoot();
};

const listen = () => {
    if (listening || typeof window === 'undefined') return;
    window.addEventListener('popstate', handlePop);
    listening = true;
    /* Дно кладём ДО сторожевой записи: иначе «назад» после единственного
       экрана снял бы его и ушёл за пределы приложения. */
    if (!rooted) armRoot();
};

/**
 * Поставить дно СРАЗУ, не дожидаясь первого экрана.
 *
 * Зачем отдельная дверь. Дно кладётся при первой записи, а до неё жест не наш:
 * человек запустил портал и свайпнул назад — и ушёл в то, что лежит в истории
 * ниже. Обычно это безобидно, но после аварийной перезагрузки (устаревшая
 * сборка после публикации) там лежат записи ПРЕЖНЕГО документа, и шаг в них —
 * полная загрузка приложения: белый экран и чужой раздел. С дном на месте
 * первый же жест приходит к нам, и мы никуда не уходим.
 *
 * Зовётся только на телефоне: на компьютере «назад» означает «предыдущая
 * страница», и лишняя запись там ни к чему.
 */
export const armBackFloor = (urlProvider) => {
    if (typeof urlProvider === 'function') floorUrl = urlProvider;
    listen();
};

/**
 * Положить в стек экран, который системное «назад» закроет вызовом close.
 * Возвращает функцию отмены — её зовут, когда экран закрыли своими средствами.
 *
 * close может вернуть false — «остаюсь»: тогда жест ничего не закрывает, но и
 * мимо экрана не проваливается.
 */
export const pushBackEntry = (close, options) => {
    if (!canTouchHistory()) return () => {};
    listen();
    /* `section: true` ставит только переход между разделами (App.jsx). По нему
       жест узнаёт записи, которые нельзя снимать из-под открытого окна. */
    const entry = { close, section: Boolean(options?.section) };
    stack.push(entry);
    scheduleSync();
    return () => {
        const at = stack.indexOf(entry);
        /* Уже снят системным «назад» — истории ничего не должны. */
        if (at === -1) return;
        stack.splice(at, 1);
        scheduleSync();
    };
};

/**
 * Выход из учётки: всё, что открыл прежний человек, закрывать нечего.
 *
 * Сторожевую запись сверка снимет сама — одним шагом и только если она наша.
 */
export const clearBackStack = () => {
    stack.length = 0;
    scheduleSync();
};

/** Только для тестов: состояние стека между прогонами не должно течь. */
export const resetBackStack = () => {
    stack.length = 0;
    guards = [];
    floorSeq = null;
    seq = 0;
    syncScheduled = false;
    rooted = false;
    floorUrl = null;
};

export const backStackDepth = () => stack.length;
