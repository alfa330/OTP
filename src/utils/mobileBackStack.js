/* Системное «назад» на телефоне: свайп от края в iOS и кнопка «назад» в Android.
 *
 * ЧЕГО НЕ ХВАТАЛО. Портал — одна страница: разделы и окна живут состоянием, а
 * не адресом, и записей в истории браузера не заводит НИ ОДНА из них (во всём
 * App.jsx только history.replaceState, чистящий адрес). Поэтому жест «назад»
 * на телефоне не делал ничего — владелец так и написал: «просто делаю назад, а
 * оно не идёт назад». Здесь на каждый открытый экран и на каждый переход между
 * разделами кладётся запись истории, а на popstate снимается верхняя.
 *
 * ПОЧЕМУ ОДИН СТЕК НА ВСЁ, А НЕ ПО ЭКРАНУ. Экраны вкладываются друг в друга
 * (окно поверх окна), и «назад» обязано снимать РОВНО верхний. Разложенные по
 * компонентам слушатели popstate сработали бы все разом и закрыли бы весь
 * стопкой.
 *
 * ЗАЧЕМ history.back() ПРИ ОБЫЧНОМ ЗАКРЫТИИ. Если экран закрыли крестиком, его
 * запись в истории останется, и следующий жест «назад» уйдёт впустую — человек
 * свайпнет, а экран уже закрыт и ничего не произойдёт. Поэтому свою запись
 * снимаем сами; вызванный ею popstate гасится счётчиком pendingBacks, иначе он
 * закрыл бы ещё и соседний экран.
 *
 * ПОЧЕМУ ЗАПИСИ КЛАДУТСЯ НЕ СРАЗУ, А ОДНИМ СВЕДЁННЫМ ИТОГОМ. Один кадр React
 * закрывает один экран и открывает другой: шторку разделов сменяет «Сменить
 * логин». Сначала отработают все уборки (отмена → history.back()), потом все
 * подписки (новый экран → pushState) — и порядок этот не наш, его задаёт React.
 * Беда в том, что back() в браузере ОТЛОЖЕН, а pushState мгновенен, и цель
 * шага назад считается по указателю на момент ВЫЗОВА: новая запись ложится
 * выше указателя, шаг уводит под неё, и на два наших экрана у браузера
 * остаётся один шаг назад. Дальше всё едет: жест снимает верхний экран, а
 * указатель уже на дне — следующее нажатие уводит через раздел.
 *
 * Поэтому обе половины откладываются до микрозадачи (кадр к тому времени
 * собран, а нажать человек ещё не успел) и сводятся в одно число: закрыли и
 * открыли поровну — историю не трогаем вовсе, запись просто достаётся новому
 * экрану. Итог — ровно то, что и требуется: шагов назад у браузера столько же,
 * сколько у нас открытых экранов.
 */

const stack = [];
let listening = false;
/* Заведено ли своё дно — запись, ниже которой «назад» уводить не должно.
   Ставится один раз и живёт до конца сеанса. */
let rooted = false;
/* Сколько popstate мы вызвали сами (history.back при обычном закрытии) — их
   надо пропустить. Счётчик, а не флаг: два экрана можно закрыть подряд быстрее,
   чем браузер успеет доставить первое событие. */
let pendingBacks = 0;
/* Сколько записей история ДОЛЖНА получить (или вернуть) по итогам текущего
   кадра. Сводится в микрозадаче — см. шапку. */
let pendingSlots = 0;
let flushScheduled = false;

/* Своя запись-дно. Именно pushState, а не replaceState: заменять текущую
   запись нельзя — под нами может лежать адрес, с которого человек в портал
   пришёл, и он бы пропал. */
const armRoot = () => {
    if (typeof window === 'undefined' || typeof window.history?.pushState !== 'function') return;
    window.history.pushState({ ...(window.history.state || {}), otpRoot: true }, '');
    rooted = true;
};

/* Свести итог кадра и привести историю в соответствие со стеком. */
const flush = () => {
    flushScheduled = false;
    const delta = pendingSlots;
    pendingSlots = 0;
    if (delta > 0) {
        for (let i = 0; i < delta; i += 1) {
            /* Прежнее состояние сохраняем: в нём лежит то, что положил роутер
               адреса (urlHygiene зовёт replaceState с window.history.state). */
            window.history.pushState({ ...(window.history.state || {}), otpBack: stack.length }, '');
        }
        return;
    }
    if (delta < 0) {
        /* go(-n) — одна перемотка и ОДИН popstate на всю глубину, поэтому и в
           счётчик пропусков добавляется один. */
        pendingBacks += 1;
        window.history.go(delta);
    }
};

const scheduleFlush = () => {
    if (flushScheduled) return;
    flushScheduled = true;
    /* Микрозадача, а не таймер: к её выполнению кадр уже собран, а нажать
       человек ещё не успел. Через Promise, а не queueMicrotask: вынутый из
       window, он в Chrome падает с «Illegal invocation». */
    Promise.resolve().then(flush);
};

const handlePop = () => {
    if (pendingBacks > 0) {
        pendingBacks -= 1;
        return;
    }
    const top = stack.pop();
    if (top) {
        /* close вернул false — экран решил остаться (обязательная новость,
           неоконченная отправка). Тогда возвращаем и запись: иначе следующий
           жест провалился бы мимо экрана и сменил бы раздел ПОД ним. */
        if (top.close() === false) {
            stack.push(top);
            pendingSlots += 1;
            scheduleFlush();
        }
        return;
    }
    /* СТЕК ПУСТ — ЭТО ДНО, И УХОДИТЬ С НЕГО НЕКУДА. Возвращаем указатель на
       место своей же записью.

       Почему это обязательно. Портал — одно приложение на одной странице, и
       «назад» ниже его корня выводит из ДОКУМЕНТА: человек остаётся на белом
       экране. В браузере оттуда есть выход адресной строкой, а в установленном
       портале нет ни строки, ни кнопки «вперёд» — только закрыть приложение и
       открыть заново. Ровно это владелец и описал: «при входе на разделы и
       назад сайт просто зависает». Воспроизводится с двух нажатий: вход в
       раздел, «назад» (вернулись в прежний), «назад» (стек пуст → about:blank).

       Так же ведут себя обычные приложения: на первом экране «назад» ничего не
       делает, а не выбрасывает наружу. */
    armRoot();
};

const listen = () => {
    if (listening || typeof window === 'undefined') return;
    window.addEventListener('popstate', handlePop);
    listening = true;
    /* Дно кладём ДО первой своей записи: иначе «назад» после единственного
       экрана снял бы его и ушёл за пределы приложения. */
    if (!rooted) armRoot();
};

/**
 * Положить в историю запись, которую системное «назад» снимет вызовом close.
 * Возвращает функцию отмены — её зовут, когда экран закрыли своими средствами.
 */
export const pushBackEntry = (close) => {
    if (typeof window === 'undefined' || typeof window.history?.pushState !== 'function') {
        return () => {};
    }
    listen();
    const entry = { close };
    stack.push(entry);
    pendingSlots += 1;
    scheduleFlush();
    return () => {
        const at = stack.indexOf(entry);
        /* Уже снят системным «назад» — истории ничего не должны. */
        if (at === -1) return;
        stack.splice(at, 1);
        pendingSlots -= 1;
        scheduleFlush();
    };
};

/**
 * Выход из учётки: записи прежней сессии обнуляем, дно оставляем.
 *
 * Закрывать по ним нечего — разделы ушли вместе с человеком, — а браузерные
 * записи над дном остаются: следующее «назад» придёт на пустой стек, то есть
 * на дно, и никуда не уведёт.
 */
export const clearBackStack = () => {
    stack.length = 0;
    /* Записи браузера над дном оставляем как есть: снимать их значило бы
       перематывать историю под руками у человека. */
    pendingSlots = 0;
};

/** Только для тестов: состояние стека между прогонами не должно течь. */
export const resetBackStack = () => {
    stack.length = 0;
    pendingBacks = 0;
    pendingSlots = 0;
    flushScheduled = false;
    rooted = false;
};

export const backStackDepth = () => stack.length;
