/* Системное «назад» на телефоне: свайп от края в iOS и кнопка «назад» в Android.
 *
 * ЧЕГО НЕ ХВАТАЛО. Портал — одна страница: разделы и окна живут состоянием, а
 * не адресом, и записей в истории браузера не заводит НИ ОДНА из них (во всём
 * App.jsx только history.replaceState, чистящий адрес). Поэтому жест «назад»
 * на телефоне не делал ничего — владелец так и написал: «просто делаю назад, а
 * оно не идёт назад». Здесь каждый открытый экран и каждый переход между
 * разделами кладётся в СВОЙ стек, а браузеру достаётся ровно одна запись —
 * сторожевая, — которую жест и снимает.
 *
 * ПОЧЕМУ ОДНА ЗАПИСЬ НА ВСЁ, А НЕ ПО ЗАПИСИ НА ЭКРАН. Так было сделано сперва,
 * и так делать нельзя. Фронт портала лежит на GitHub Pages, файлы сборки
 * названы по хэшу, и публикация подменяет их РАЗОМ. У человека с открытым
 * приложением в памяти остаётся прежняя сборка, и первый же ленивый кусок
 * (их 45 — «Сменить фотографию», карточки, тренажёры) отвечает 404. Портал
 * лечится сам: lazyWithRetry и staleBundleRecovery перезагружают страницу через
 * location.replace(?v=…). Вот после этой перезагрузки и начинается беда:
 * записи, положенные ДО неё, принадлежат ПРЕЖНЕМУ документу, и шаг назад в них
 * — не жест, а полная загрузка приложения заново. Замерено в браузере: три
 * нажатия «назад» после такой перезагрузки — три перехода документа. Владелец
 * 11.09.2026: «перекидывает из профиля в какой-то другой раздел и ловлю белый
 * экран» — белый экран это и есть загрузка, а «другой раздел» — адрес ?view=…,
 * записанный в той старой записи.
 *
 * Убрать записи из истории нельзя, поэтому их надо НЕ ПЛОДИТЬ. Глубина
 * хранится у нас, а браузеру всегда показывается одно и то же: пока открыт хоть
 * один экран или сделан хоть один переход — над дном висит ОДНА сторожевая
 * запись. Жест её снимает, мы снимаем верхний экран и, если внизу осталось
 * что-то ещё, кладём сторожевую снова. Сколько бы разделов человек ни обошёл,
 * после перезагрузки в истории останется хвост не длиннее двух записей вместо
 * десятка. Заодно исчезает и многошаговая перемотка: шаг всегда один, и только
 * по записи, которую положили мы.
 *
 * ПОЧЕМУ ОДИН СТЕК И ОДИН СЛУШАТЕЛЬ. Экраны вкладываются друг в друга (окно
 * поверх окна), и «назад» обязано снимать РОВНО верхний. Разложенные по
 * компонентам слушатели popstate сработали бы все разом и закрыли бы всё
 * стопкой.
 *
 * ПОЧЕМУ СВЕРКА ОТЛОЖЕНА ДО МИКРОЗАДАЧИ. Один кадр React закрывает один экран и
 * открывает другой: шторку разделов сменяет «Сменить логин». Сначала отработают
 * ВСЕ уборки, потом ВСЕ подписки — порядок не наш, его задаёт React. Правя
 * историю на месте, мы бы успели снять сторожевую запись и положить её заново,
 * а `history.back()` в браузере ОТЛОЖЕН, тогда как pushState мгновенен: шаг
 * назад уводил бы уже из-под новой записи. Поэтому история сверяется один раз
 * за кадр, когда он собран целиком: нужна сторожевая или нет.
 */

/* Насколько близко друг к другу приходят два перехода ОДНОГО маха пальцем.
   Замер 11.09.2026: браузер отдаёт их в соседних тактах, разрыв — единицы
   миллисекунд. Человек так быстро дважды не свайпнет: даже очень быстрый
   повтор жеста — это больше сотни миллисекунд. */
const GESTURE_TAIL_MS = 80;

/* Что открыто: экраны и переходы между разделами, верхний — последний. */
const stack = [];
let listening = false;
/* Заведено ли своё дно — запись, ниже которой «назад» уводить не должно.
   Ставится один раз и живёт до конца сеанса. */
let rooted = false;
/* Висит ли сейчас над дном сторожевая запись. */
let armed = false;
let syncScheduled = false;
/* Когда пришёл предыдущий popstate. Мах пальцем от края отдаёт браузеру ДВА
   перехода подряд, и второй из них — не второй жест человека, а ХВОСТ первого:
   между ними миллисекунды, тогда как между двумя нажатиями кнопки — всегда
   больше сотой доли секунды. Отличать их приходится по времени, а не по метке в
   history.state: метку стирает чужой replaceState (так делает роутер «Курсов»),
   и гадание по ней глушило жест в целом разделе. */
let lastPopAt = 0;
/* Чем вернуть адрес, когда жест уводит НИЖЕ дна. Там лежит запись с прежним
   адресом — обычно с экрана входа, ещё без ?view=, — и, восстановив дно молча,
   мы оставили бы человека с адресом без раздела. Сам он этого не увидит, но
   следующая перезагрузка (а её приносит каждая публикация) открыла бы ему
   раздел по умолчанию вместо того, где он стоит. */
let floorUrl = null;

const canTouchHistory = () => typeof window !== 'undefined'
    && typeof window.history?.pushState === 'function';

/* Стоим ли мы прямо сейчас на своём дне. Метку может стереть чужой
   replaceState (так делает роутер «Курсов»), и тогда ответ будет «нет» — это
   безопасная сторона ошибки: лишнее дно ничего не ломает, пропущенное выводит
   из портала. */
const standingOnFloor = () => {
    try {
        return window.history.state?.otpRoot === true;
    } catch (error) {
        return false;
    }
};

/* Своя запись-дно. Именно pushState, а не replaceState: заменять текущую
   запись нельзя — под нами может лежать адрес, с которого человек в портал
   пришёл, и он бы пропал. */
const armRoot = () => {
    if (!canTouchHistory()) return;
    let url = null;
    try {
        url = floorUrl?.() || null;
    } catch (error) {
        url = null;
    }
    /* Метку дна ставим, а метку сторожевой СНИМАЕМ: состояние копируется с
       текущей записи, и унаследованный otpBack сделал бы дно неотличимым от
       сторожевой — а отличать их приходится (см. standingOnFloor). */
    window.history.pushState(
        { ...(window.history.state || {}), otpRoot: true, otpBack: false },
        '',
        url || window.location.href,
    );
    rooted = true;
    /* Дно — не сторожевая запись: жест по ней ничего не закрывает. */
    armed = false;
};

/* Привести историю к тому, что у нас открыто: нужна сторожевая запись или нет.
   Никаких многошаговых перемоток — один шаг, и только по своей записи. */
const sync = () => {
    syncScheduled = false;
    if (!canTouchHistory()) return;
    const want = stack.length > 0;
    if (want === armed) return;
    if (want) {
        /* ДНО ПОД СТОРОЖЕВОЙ ОБЯЗАНО БЫТЬ. Короткий мах пальцем от края
           отматывает ДВЕ записи (замерено в браузере: два history.back() в
           одном такте уводят указатель на две записи). Дно при этом
           проскакивается, и следующая сторожевая легла бы уже НА ЗАГРУЗОЧНУЮ
           запись документа — а с неё любой шаг назад уводит из портала.
           Поэтому перед каждой сторожевой проверяем, стоим ли мы на своём дне,
           и если нет — кладём его заново. */
        if (!standingOnFloor()) armRoot();
        /* Прежнее состояние сохраняем: в нём лежит то, что положил роутер
           адреса (urlHygiene зовёт replaceState с window.history.state). */
        window.history.pushState({ ...(window.history.state || {}), otpRoot: false, otpBack: true }, '');
        armed = true;
        return;
    }
    /* Экранов не осталось, а сторожевая висит — И ПУСТЬ ВИСИТ.
     *
     * Раньше мы снимали её сами, шагом назад. Это ровно та же гонка, что и с
     * махом от края: наш `history.back()` и жест человека складываются в ОДИН
     * переход на две записи, а пришедший popstate счётчик засчитывает как наш —
     * шаг человека пропадает, а указатель уже стоит на чужой записи. Замер
     * 11.09.2026: «назад» на дне уводило в раздел, который был открыт двумя
     * шагами раньше.
     *
     * Цена решения названа честно: после закрытия последнего экрана крестиком
     * первый «назад» ничего не сделает — он израсходует оставшуюся сторожевую,
     * и мы вернём дно. Но закрывать в этот момент и правда нечего: пустой стек
     * означает, что и разделов позади нет. */
};

const scheduleSync = () => {
    if (syncScheduled || !canTouchHistory()) return;
    syncScheduled = true;
    /* Микрозадача, а не таймер: к её выполнению кадр уже собран, а нажать
       человек ещё не успел. Через Promise, а не queueMicrotask: вынутый из
       window, он в Chrome падает с «Illegal invocation». */
    Promise.resolve().then(sync);
};

const handlePop = () => {
    /* ХВОСТ ОДНОГО ЖЕСТА. Мах пальцем от края — это ДВА перехода браузера, а не
     * два жеста человека: второй приходит через считаные миллисекунды после
     * первого (замерено 11.09.2026). Закрывать по нему ещё один экран нельзя —
     * одно движение пальца обязано закрывать ровно одно. И оставлять его без
     * ответа тоже нельзя: он уже утащил указатель ниже дна, а с записи ниже дна
     * любой следующий шаг уводит из портала — в установленном приложении это
     * белый экран и загрузка заново.
     *
     * Поэтому хвост НИЧЕГО НЕ ЗАКРЫВАЕТ, но возвращает дно на место (armRoot
     * кладёт его вместе с адресом текущего раздела). Между двумя настоящими
     * нажатиями кнопки «назад» всегда есть кадр, и под это правило они не
     * попадают. */
    const now = typeof performance !== 'undefined' && typeof performance.now === 'function'
        ? performance.now()
        : Date.now();
    const tail = now - lastPopAt < GESTURE_TAIL_MS;
    lastPopAt = now;

    /* ДВА СЛУЧАЯ, В КОТОРЫХ ШАГ НАЗАД НЕ ЗАКРЫВАЕТ НИЧЕГО.
     *
     * Первый — хвост маха, о нём выше: одно движение пальца обязано закрывать
     * ровно один экран, сколько бы переходов браузер по нему ни сделал.
     *
     * Второй — шаг, пришедший БЕЗ сторожевой записи. Сторожевая одна, и
     * кладётся она в микрозадаче, то есть не раньше конца текущего такта; всё,
     * что браузер успел отмотать сверх неё, приходит сюда уже без неё. До
     * 11.09.2026 такой шаг закрывал ещё один экран, а дно оставалось снятым —
     * и следующий шаг уходил на загрузочную запись документа. Владелец
     * 11.09.2026: «кнопка назад работает корректно, но свайп рукой снова
     * выкидывает в другой раздел».
     *
     * Оба случая лечатся одинаково: дно возвращается на место (armRoot кладёт
     * его вместе с адресом текущего раздела), открытое остаётся открытым.
     * Снаружи это выглядит как «жест не сработал» — и это правильнее, чем
     * уехать в чужой раздел или из портала вовсе. */
    if (tail || !armed) {
        armRoot();
        /* И сразу сверяемся: если открытые экраны остались, над дном снова
           нужна сторожевая запись. Без этого следующий шаг тоже пришёл бы «без
           сторожевой», и жест перестал бы закрывать хоть что-нибудь. */
        scheduleSync();
        return;
    }
    /* Жест израсходовал сторожевую запись — что бы дальше ни случилось, её там
       больше нет. */
    armed = false;
    const top = stack.pop();
    if (top) {
        /* close вернул false — экран решил остаться (обязательная новость,
           неоконченная отправка). Возвращаем его в стек: сверка положит
           сторожевую заново, и следующий жест снова придёт к нему, а не
           провалится мимо и сменит раздел ПОД ним. */
        if (top.close() === false) stack.push(top);
        /* Внизу могло остаться что-то ещё — тогда сторожевая нужна снова. */
        scheduleSync();
        return;
    }
    /* СТЕК ПУСТ — ЭТО ДНО, И УХОДИТЬ С НЕГО НЕКУДА. Возвращаем указатель на
       место своей же записью.

       Почему это обязательно. Портал — одно приложение на одной странице, и
       «назад» ниже его корня выводит из ДОКУМЕНТА: человек остаётся на белом
       экране. В браузере оттуда есть выход адресной строкой, а в установленном
       портале нет ни строки, ни кнопки «вперёд» — только закрыть приложение и
       открыть заново. Ровно это владелец и описал: «при входе на разделы и
       назад сайт просто зависает».

       Так же ведут себя обычные приложения: на первом экране «назад» ничего не
       делает, а не выбрасывает наружу. */
    armRoot();
};

const listen = () => {
    if (listening || typeof window === 'undefined') return;
    window.addEventListener('popstate', handlePop);
    listening = true;
    /* Дно кладём ДО сторожевой записи: иначе «назад» после единственного
       экрана снял бы его и ушёл за пределы приложения. */
    if (!rooted) armRoot();
};

/**
 * Поставить дно СРАЗУ, не дожидаясь первого экрана.
 *
 * Зачем отдельная дверь. Дно кладётся при первой записи, а до неё жест не наш:
 * человек запустил портал и свайпнул назад — и ушёл в то, что лежит в истории
 * ниже. Обычно это безобидно, но после аварийной перезагрузки (устаревшая
 * сборка после публикации) там лежат записи ПРЕЖНЕГО документа, и шаг в них —
 * полная загрузка приложения: белый экран и чужой раздел. С дном на месте
 * первый же жест приходит к нам, и мы никуда не уходим.
 *
 * Зовётся только на телефоне: на компьютере «назад» означает «предыдущая
 * страница», и лишняя запись там ни к чему.
 */
export const armBackFloor = (urlProvider) => {
    if (typeof urlProvider === 'function') floorUrl = urlProvider;
    listen();
};

/**
 * Положить в стек экран, который системное «назад» закроет вызовом close.
 * Возвращает функцию отмены — её зовут, когда экран закрыли своими средствами.
 *
 * close может вернуть false — «остаюсь»: тогда жест ничего не закрывает, но и
 * мимо экрана не проваливается.
 */
export const pushBackEntry = (close) => {
    if (!canTouchHistory()) return () => {};
    listen();
    const entry = { close };
    stack.push(entry);
    scheduleSync();
    return () => {
        const at = stack.indexOf(entry);
        /* Уже снят системным «назад» — истории ничего не должны. */
        if (at === -1) return;
        stack.splice(at, 1);
        scheduleSync();
    };
};

/**
 * Выход из учётки: всё, что открыл прежний человек, закрывать нечего.
 *
 * Сторожевую запись сверка снимет сама — одним шагом и только если она наша.
 */
export const clearBackStack = () => {
    stack.length = 0;
    scheduleSync();
};

/** Только для тестов: состояние стека между прогонами не должно течь. */
export const resetBackStack = () => {
    stack.length = 0;
    armed = false;
    syncScheduled = false;
    rooted = false;
    floorUrl = null;
};

export const backStackDepth = () => stack.length;
