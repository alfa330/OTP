/* Общий порог «нажали или потащили» для плавающих элементов портала.
 *
 * Живёт отдельным модулем, потому что таких элементов уже два: шарик помощника
 * на компьютере и колокол в углу телефона. Разъехавшись, пороги дают разное
 * поведение у двух похожих кнопок на одном экране — а человек в этот момент
 * учится не «этой кнопке», а жесту вообще.
 */

/* Клик или перетаскивание — решается пройденным расстоянием, а не таймером.
   Порог в 4 пикселя пропускает дрожание руки на нажатии (особенно на тачскрине)
   и при этом не съедает намеренный короткий сдвиг. */
export const DRAG_THRESHOLD = 4;

export const movedEnough = (from, to) => (
    Math.abs(to.x - from.x) >= DRAG_THRESHOLD || Math.abs(to.y - from.y) >= DRAG_THRESHOLD
);
