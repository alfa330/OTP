"""Раздел «Рассылки» — сообщения водителям в приложение Yandex/Yango Pro прямо из
портала, без ручного входа в кабинет диспетчерской (задача #166).

До этого раздела так: человек открывает fleet.yandex.kz, входит в диспетчерскую,
собирает фильтры, отправляет; потом повторяет то же самое в следующей
диспетчерской, и так пять раз. Одинаковый текст набирается заново, охват нигде не
сохраняется, а «кому и что мы вчера отправили» живёт только в кабинете, где автор
у всех рассылок один и тот же служебный аккаунт.

Что даёт раздел: одна форма на пять диспетчерских, предпросмотр охвата до
отправки, свой журнал с настоящим автором и отзыв рассылки, пока не истекли пять
минут.

Устройство пакета:

    access.py   права раздела (чистая логика, без Flask и базы)
    schema.py   таблицы driver_mailing*
    queries.py  SQL поверх готового курсора
    client.py   HTTP-клиент кабинета Fleet: парки, лимиты, справочники,
                предпросмотр охвата, отправка, отзыв
    routes.py   Blueprint /api/driver_mailings

СЕССИЯ КАБИНЕТА — СВОЯ, А ПОКА ЕЁ НЕТ — ОБЩАЯ С «ПРОВАЙДЕРОМ ЭДО».
Сначала учётная запись в кабинете у портала была одна: куки живого логина лежат
в `fleet_edm_session` и обновляются в «Провайдере ЭДО», а «Рассылки» их только
читали. Но у того аккаунта рассылка разрешена в пяти диспетчерских из
девяноста, и 23.09.2026 под рассылки выдали отдельный аккаунт с правом
рассылать везде. Его куки живут в своей строке `driver_mailing_session`,
приносит их тот же скрипт с ключом `--target mailings`. Правило выбора — в
`routes.choose_session`: своя строка, если есть, всегда (даже протухшая —
молча откатиться на аккаунт с пятью парками было бы подменой отправителя),
общая — только пока своей нет вовсе.

В `fleet_edm_session.last_error` «Рассылки» по-прежнему НИКОГДА не пишут:
там смысл «куки протухли, нужен новый логин» для выгрузок ЭДО, а наши 403
«в этом парке рассылка не разрешена» к состоянию той сессии отношения не имеют.
Протухание своей сессии отмечается в своей же строке.

Автор в кабинете у всех наших рассылок один (служебный аккаунт рассылок),
поэтому кто отправил на самом деле — помним мы, в своей таблице.

Фильтры получателей собираются ТОЛЬКО на сервере из белого списка. Причина
измерена живьём: неизвестный ключ кабинет молча проглатывает и отдаёт ПОЛНЫЙ
охват ({"blah":"nope"} → те же 1144 человека, что и пустой фильтр). То есть
«прокинуть фильтр строкой снаружи» здесь означает не ошибку валидации, а
рассылку всем подряд.
"""
