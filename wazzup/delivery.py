"""Входящие Wazzup, доставленные с опозданием: ставим их туда, где их увидел оператор.

Канал Wazzup на обычном WhatsApp (транспорт `whatsapp`, работает через телефон;
у Верификаторов это «2ГИС — не писать первыми», остальные каналы — WABA) присылает
в вебхуке время сообщения по WhatsApp с точностью до минуты: секунды обнулены, в
миллисекундах — порядковый номер внутри минуты (…:00.001, …:00.002). На проде
06.10.2026 так выглядели 7 430 строк канала из 7 450; у WABA-каналов время точное.

Пока телефон канала не в сети, клиенты продолжают писать. Когда канал
возвращается, Wazzup досылает накопившееся со временем ОТПРАВКИ — у нас такие
сообщения вставали на дни назад, и чат «обрывался»: в простой 16.09–05.10
клиент написал 25.09 в 18:45, оператор увидел его 05.10 в 12:35 и там же
ответил, а у нас вопрос висел под 25 сентября. Сам Wazzup показывает такие
сообщения там, где получил, — туда их ставим и мы. Исходное время не теряется:
оно остаётся рядом, в `wazzup_messages.wazzup_dt`.

Опоздавшее — ВХОДЯЩЕЕ с минутным временем, вебхук которого пришёл позже этого
времени больше чем на LATE_DELIVERY. Исходящие не трогаем: их минута — момент
отправки в WhatsApp, а «эхо» Wazzup присылает с задержкой. Каналы с точным
временем (WABA) не трогаем тоже: их опоздание — задержка вебхука, время в нём
верное.

Куда именно встаёт опоздавшее внутри минуты доставки, решает то, что делал
оператор. Время ответов этого канала — тоже минута отправки (счётчик с …:00.001),
а когда оператор нажал «Отправить», Wazzup нам не сообщает. Разбор всех 33
спорных случаев на проде 06.10.2026 (входящее и ответ в одной минуте):

* обычно оператор отвечает ПОСЛЕ того, как сообщение пришло, — пропущенный звонок
  и «Мы не принимаем звонки по WhatsApp», первое сообщение после простоя и
  «Сәлеметсіз бе!». Опоздавшее встаёт в НАЧАЛО минуты доставки, раньше ответа;
* исключение — возврат канала, когда в чате уже висит неотвеченное опоздавшее
  сообщение: оператор ответил на него сразу, а телефон отправил ответ только
  когда догнал очередь, в той же минуте, что и следующие досланные вопросы
  (жалоба 06.10: «Қанша…» пришло в 12:22, приветствие нажато в 12:25, ушло в
  12:35, а «Вольт…» дошло в 12:35:10). Тогда опоздавшее встаёт в ТОЧНЫЙ момент
  прихода — после ответа, который уже был в пути.

Начало минуты — с долей: опоздавших в одну минуту бывает несколько (57 таких
минут), порядок прихода между ними сохраняется, а сама доля сжата в первую
миллисекунду (60 с → 600 мкс), до счётчика ответов.

Два уточнения из разбора правки:

* опоздавшее не встаёт раньше того, что к его приходу уже было в чате: ответ,
  пришедший в той же минуте раньше него, остаётся выше. Совпадение времени
  (сообщения одного вебхука, приход в пределах 0,1 с) разводится на микросекунду
  — иначе порядок решал бы случайный message_id, а подгрузка ленты курсором
  `dt < before` теряла бы второе из равных;
* если в те же минуты опаздывают и каналы с точным временем, задерживается
  доставка вебхуков (сбой у нас или у Wazzup), а не телефон канала: в Wazzup
  сообщение было вовремя, и время из вебхука верное — его не трогаем. На проде
  за 45 дней таких среди 378 сдвигов не было ни одного; правило — на будущее.

Ответы из окна iCORE (с 09.10.2026 операторы пишут из «Чатов ОП»). Время такого
ответа точное — момент отправки (wazzup/pilot.py), а входящие канала по-прежнему
приходят с минутой. Ответ клиента, пришедший в ту же минуту ПОСЛЕ ответа
оператора, вставал в начало минуты — выше вопроса, на который отвечал (жалоба
19.10.2026: вопрос «тіркелгіңіз келе ме?» отправлен в 11:23:29, «жок» пришёл в
11:23:54, а в ленте стоял над вопросом). Сам Wazzup хранит у сообщения и точное
время (timestampMsg его окна), и номер в минуте общий для входящих и ответов —
по обоим ответ стоит раньше. Поэтому сообщение с минутным временем, пришедшее
вовремя, не встаёт раньше сообщений с ТОЧНЫМ временем, которые к его приходу уже
были в чате: оно встаёт сразу за последним из них (+1 мкс — равного времени
нет; лента в браузере сравнивает время тоже до микросекунды, messageTime.js).
Сообщения с минутным временем между собой стоят по номеру, как стояли.

Правило — для обоих направлений. Ответ оператора с телефона или из окна Wazzup
тоже приходит с минутой: без правила он вставал бы над сдвинутым ответом
клиента, на который отвечает, и не снимал бы «ждут ответа». Но опоздавшее
входящее ответу не указ: его время — момент доставки, а ответ после простоя
телефон отправляет позже, чем оператор его написал (жалоба 06.10 выше:
приветствие нажато до досланных вопросов). Эхо ответа из окна iCORE время не
меняет: строка уже есть, время задаётся только вставкой.
Время Wazzup сдвинутому сообщению не сохраняем: оно в той же минуте, а «ждут
ответа» (wazzup/unread.py) сравнивает время ленты.

Форма «минута + номер» встречается и у точного времени WABA случайно (0,17 %).
Такое сообщение WABA тоже встаёт за сообщением, пришедшим раньше него, — на
секунды, по порядку прихода; на проде за 45 дней это 4 вложения клиента после
его же текста, отдельной проверки ради них нет.
"""
from datetime import datetime, timedelta, timezone

# Минутное время плюс доставка вебхука укладываются в ~90 секунд. Три минуты —
# явное опоздание: сообщение дошло до Wazzup позже, чем было написано.
LATE_DELIVERY = timedelta(minutes=3)

# Досылка после возврата канала длится около 25 минут: неотвеченное опоздавшее
# старше часа — уже не та очередь, ответ на него в пути не стоит.
PENDING_WINDOW = timedelta(hours=1)

# Доля минуты доставки → первая миллисекунда минуты (до счётчика ответов).
_ORDER_SCALE = 100_000

# Задержку доставки вебхуков узнаём по сообщениям каналов с точным временем,
# пришедшим за две минуты до этого. Сами они могли опоздать не больше чем на
# сутки — дальше в выборку не заглядываем (индекс по dt).
BACKLOG_LOOKBACK = timedelta(minutes=2)
_BACKLOG_MAX_LAG = timedelta(days=1)

_STEP = timedelta(microseconds=1)


def parse_wazzup_dt(value):
    """dateTime вебхука → datetime с поясом (без пояса — UTC, как читает его
    Postgres в UTC-сессии Render). None — пусто или не разобрали."""
    if isinstance(value, datetime):
        parsed = value
    else:
        text = str(value or '').strip()
        if not text:
            return None
        try:
            parsed = datetime.fromisoformat(text.replace('Z', '+00:00'))
        except ValueError:
            return None
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed


def is_minute_stamp(dt):
    """Время «минута + порядковый номер»: секунды 0, номер 1–99 мс без микросекунд.
    У точного времени (WABA) такая форма случайна — 0,17 % строк."""
    return (dt.second == 0 and dt.microsecond % 1000 == 0
            and 1 <= dt.microsecond // 1000 <= 99)


def is_late_inbound(dt, received_at, is_echo):
    """Входящее с минутным временем, дошедшее позже LATE_DELIVERY."""
    return (not is_echo and dt is not None and received_at is not None
            and is_minute_stamp(dt) and received_at - dt > LATE_DELIVERY)


def is_in_time(dt, received_at):
    """Сообщение с минутным временем (любого направления), дошедшее вовремя —
    не позже LATE_DELIVERY."""
    return (dt is not None and received_at is not None
            and is_minute_stamp(dt) and received_at - dt <= LATE_DELIVERY)


def after_known_replies(dt, known):
    """Время в ленте сообщения, дошедшего вовремя (см. «Ответы из окна iCORE»
    в докстринге модуля).

    known — время сообщений чата, известных к его приходу. Сообщения с точным
    временем позже dt (ответ из окна iCORE, опоздавшее, сдвинутое этим же
    правилом) уже были в чате — сообщение встаёт сразу за последним из них.
    Минутное время других сообщений не в счёт: их с dt рассудил номер в минуте."""
    after = max((k for k in known if k > dt and not is_minute_stamp(k)), default=None)
    return dt if after is None else after + _STEP


def replay_after_replies(history, keep=frozenset()):
    """Проход приёмника по уже лежащим сообщениям чата — для разовой починки.

    history — сообщения чата в порядке прихода (dict: message_id, dt,
    created_at — приход вебхука, late — у опоздавшего уже стоит время
    доставки). Возвращает [(message_id, старое время, новое)] для сообщений,
    которые after_known_replies ставит за ответом; id из keep остаются на месте,
    но и они, и всё остальное идут в «известное» к следующим. Новое время не
    совпадает ни с чьим в чате, в том числе с пришедшими позже (их ставил уже
    новый приёмник): иначе подгрузка ленты `dt < before` теряла бы одно из равных."""
    final = {msg['message_id']: msg['dt'] for msg in history}
    known, moves = [], []   # (время, опоздавшее входящее)
    for msg in history:
        dt = msg['dt']
        if (not msg['late'] and msg['message_id'] not in keep
                and is_in_time(dt, msg['created_at'])):
            placed = after_known_replies(dt, [k for k, late in known
                                              if not (late and msg['is_echo'])])
            if placed != dt:
                taken = {value for mid, value in final.items() if mid != msg['message_id']}
                while placed in taken:
                    placed += _STEP
                moves.append((msg['message_id'], dt, placed))
                final[msg['message_id']] = dt = placed
        known.append((dt, bool(msg['late'])))
    return moves


def history_since(received_at):
    """С какого прихода нужна история чата, чтобы решить reply_pending: окно
    плюс минута — ответ, стоящий после ожидающего входящего, пришёл не раньше
    начала его минуты."""
    return received_at - PENDING_WINDOW - timedelta(minutes=1)


def reply_pending(chat_messages, received_at):
    """Висит ли в чате неотвеченное опоздавшее входящее, пришедшее раньше минуты
    received_at (и не раньше PENDING_WINDOW до неё).

    chat_messages — сообщения чата: dict с is_echo, dt (время в ленте; у
    опоздавших — уже заменённое), created_at (приход) и late (входящее было
    опоздавшим). В расчёт идёт только пришедшее до received_at — так же, как это
    видел приёмник в ту секунду."""
    minute = received_at.replace(second=0, microsecond=0)
    known = [m for m in chat_messages if m['created_at'] < received_at]
    replies = [m['dt'] for m in known if m['is_echo']]
    for m in known:
        if m['is_echo'] or not m['late']:
            continue
        if not (received_at - PENDING_WINDOW <= m['created_at'] < minute):
            continue
        if not any(reply > m['dt'] for reply in replies):
            return True
    return False


def recent_window(received_at):
    """Окно для delivery_backlog: (dt не раньше, приход не раньше); оба — до received_at."""
    return received_at - _BACKLOG_MAX_LAG, received_at - BACKLOG_LOOKBACK


def delivery_backlog(recent):
    """Задерживается ли доставка вебхуков вообще.

    recent — пары (dt, created_at) сообщений аккаунта, пришедших за
    BACKLOG_LOOKBACK до этого (recent_window). Смотрим только каналы с точным
    временем: у минутного канала опоздание — его собственное. Нет таких
    сообщений (ночь) — судить не по чему, считаем, что доставка в порядке."""
    lags = [created_at - dt for dt, created_at in recent if not is_minute_stamp(dt)]
    if not lags:
        return False
    late = sum(1 for lag in lags if lag > LATE_DELIVERY)
    return late * 2 >= len(lags)


def delivery_time(received_at, pending, after=None):
    """Время опоздавшего входящего в ленте (см. докстринг модуля).

    after — самое позднее время среди сообщений чата, известных к его приходу
    (и записанных раньше него в том же вебхуке): опоздавшее встаёт после них."""
    if pending:
        moment = received_at
    else:
        minute = received_at.replace(second=0, microsecond=0)
        moment = minute + (received_at - minute) / _ORDER_SCALE
    if after is not None and moment <= after:
        moment = after + _STEP
    return moment
