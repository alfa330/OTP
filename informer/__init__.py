"""Автоинформатор удалённого КЦ: робот звонит водителю и проигрывает запись (владелец, 15.10.2026).

Как это устроено
----------------
* Робот — Asterisk на шлюзе в корпоративной сети (контейнер otp-informer, приватный репозиторий
  otp-gateway). Он «телефон» на внутренней линии Binotel удалённого КЦ: звонит обычным исходящим,
  водитель видит номер удалённого КЦ, а с момента ответа робот сам пускает звук записи. В API
  Binotel способа пустить в звонок свой звук нет — пускает только участник звонка.
* Диспетчер — рядом с роботом (cdr_bridge/informer.py): спрашивает портал, кому звонить, ставит
  звонки роботу и возвращает итоги — момент ответа, сколько секунд слушал, кто положил трубку.
  Соединение всегда открывает шлюз, подпись — та же, что у моста «Касаний» (cdr/agent_auth.py).
* Портал (этот пакет): рассылки, список водителей, очередь звонков, темп и аналитика.

Решения владельца
-----------------
* Запись — сначала казахская часть, потом русская (15.10.2026). Склеивает их браузер руководителя
  (src/components/dial_list/informerAudio.js): моно, тишина 0,5 с в начале, пауза 0,6 с.
* Голос — в полном качестве, не 8 кГц (15.10.2026): оригинал 24 кГц слушает руководитель, а робот
  играет телефонную версию 8 кГц — её один раз и с фильтром сводит сервер (telephone.py).
* Звонки идут с кабинета удалённого КЦ, не Тез КЦ.

Ограничения, которые держит код
-------------------------------
* Темп — сколько тянут линии робота (владелец, 16.10.2026: «сколько тянут линии, без предела»): поле
  формы сразу стоит на этом числе (rules.line_rate), общего минутного потолка нет — предел дают
  свободные места на линиях. Решение принято со знанием закона РК «О связи», ст. 21 п. 3-1 (с
  20.08.2026): автовызовы с записью чаще десяти соединений в минуту оператор вправе не пропускать
  без договора. Страховку на шлюзе можно вернуть числом INFORMER_MAX_PER_MINUTE (cdr_bridge/informer.py).
* Одна линия Binotel держит 2 звонка одновременно (замер 15.10.2026): третий Binotel отклоняет
  кодом 480 сразу, не набирая. Такой отказ — «линия занята» (rules.RESULT_LINE_BUSY), попыткой
  водителя он не считается и повторяется через полминуты.
* Номер водителя наружу не уходит: в ответах и в выгрузке — маска, как в журнале раздела.
"""
