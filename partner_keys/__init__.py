"""Ключи партнёров: один способ пускать сторонние сервисы в ручки портала.

Просьба владельца 29.10.2026: у ключа должно быть видно, «к чему есть доступ», а
входы, которые раньше уходили в CRM с ключами из переменных окружения, переводятся
на такие же ключи. Что здесь:

* **Ключ** — строка `partner_keys`: название (кому выдан), sha256 ключа, отпечаток,
  ОБЛАСТИ ДОСТУПА (`scopes`, см. scopes.py) и, для ручки знаний, от чьего имени
  считать права (otp_role + department_id). Выпускает и отзывает супер-админ во
  вкладке «Ключи» раздела «Сессии»; ключ показывается один раз.

* **Области доступа** — что ключ открывает: ручку знаний, внешний вход «Ссылок
  на подписание», окно «Чатов ОП» для CRM. Ручка проверяет ключ со СВОЕЙ областью
  (auth.lookup): ключ без неё получает 403, а не 401 — у партнёра ключ верный, ему
  просто не выдали эту дверь.

* **Журнал** — строка на вызов в `partner_key_calls`: область, ручка, исход,
  длительность, короткая сводка (вопрос водителя; «ИИН: 12, ссылок 3»; пользователь
  CRM) и подробности JSON. Хранится PARTNER_KEYS_CALLS_DAYS дней (90).

* **Переход без простоя.** Ключи из окружения (`SIGN_LINKS_API_KEY`,
  `POTOK_CRM_WEBHOOK_API_KEY`) продолжают приниматься: ручка сначала сверяет их,
  потом ищет ключ партнёра. Партнёр переходит на ключ из «Ключей», и переменную
  можно убрать. Ключ CRM в окружении остаётся ещё и для пересылки вебхуков в CRM
  и подписи пользователей CRM в адресе окна — это не вход, а наш секрет.

Состав пакета:
    schema.py        таблицы partner_keys и partner_key_calls (+ перенос с knowledge_api_*)
    keys.py          выпуск, хеш и отпечаток ключа — чистая логика
    scopes.py        справочник областей доступа
    queries.py       SQL ключей и журнала
    auth.py          проверка ключа с областью — для ручек
    journal.py       запись вызова — для ручек
    admin_routes.py  ключи и журнал для супер-админа: /api/admin/partner-keys
"""
