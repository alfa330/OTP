"""Раздел «Карточка клиента» — карточка звонка техподдержки в iCORE Phone (задача #335).

Что решает. Оператор линии принимает или делает звонок — телефон сам открывает карточку
с номером собеседника. Портал находит по номеру аккаунты Тез (водитель или клиент),
оператор выбирает нужный или прикладывает ссылку на аккаунт из админки Тез: ссылка
закрепляется за номером, и в следующий раз аккаунт подтянется сам — даже если человек
зарегистрирован на один номер, а звонит с другого. Дальше — причина обращения из
справочника, который ведёт руководитель, комментарий и, если вопрос не решается на линии,
запрос в другой отдел: он уходит в рабочую Telegram-группу, ответы возвращаются в карточку.

Сущности:

    аккаунт        водитель или клиент Тез: вид + ID из админки (client_card_accounts)
    привязка       номер телефона ↔ аккаунт, многие ко многим (client_card_phone_links)
    обращение      заполненная карточка одного звонка (client_cards) с причинами
                   (client_card_topics)
    причина        двухуровневый справочник отдела: категория → подтема
                   (client_card_categories)
    запрос         обращение в другой отдел с перепиской (client_card_requests,
                   client_card_request_messages); адресаты — client_card_destinations
    алерт          рост обращений по причине — сообщение руководителю в Telegram
                   (client_card_alerts — журнал, по нему же гасятся повторы)

Состав пакета (как у «Обращений» и «Аренды авто»):

    rules.py      чистая логика: номера, ссылки на аккаунт, состояния карточки, алерты
    access.py     чистая логика прав
    schema.py     DDL, идемпотентно
    queries.py    SQL поверх готового курсора
    tez.py        запросы в TEZ APP: аккаунты по номеру и по ID
    telegram.py   тексты сообщений в группы и руководителю (без сети)
    service.py    сценарии, где база встречается с TEZ APP и Telegram
    routes.py     Blueprint /api/client_cards — ручки телефона и раздела портала
    bot.py        приём ответов из Telegram-групп
    report.py     выгрузка отчёта в Excel
"""

