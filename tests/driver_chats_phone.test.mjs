import test from 'node:test';
import assert from 'node:assert/strict';

import {
  formatPhone,
  pluralChats,
  pluralDays,
  rangeDays,
  shiftDaysBack,
} from '../src/components/driver_chats/journalMeta.js';

/* Показ номера в разделе «Чаты водителей».
 *
 * Раздел ищет переписку ПО НОМЕРУ, и номер этот не обязательно казахстанский:
 * у водителей встречаются российские, узбекские, киргизские, таджикские,
 * турецкие и британские симки (владелец 08.09.2026: «могут быть и номера из
 * других стран»). Показывать их сплошной строкой цифр — значит делать вид, что
 * это не телефон: человек сверяет номер на экране с тем, что ему продиктовали.
 *
 * Проверяется здесь, а не в pytest: pytest читает .jsx текстом и подтвердит
 * разве что наличие строчки, а правило разбивки — это поведение функции. */

test('казахстанский номер читается «восьмёркой», как его и диктуют', () => {
  assert.equal(formatPhone('77000344057'), '8 700 034 40 57');
  assert.equal(formatPhone('+7 707 123 45 67'), '8 707 123 45 67');
});

test('та же форма у номера, попавшего сюда с восьмёркой', () => {
  // Внутри раздела номер лежит нормализованным («7…»), но функция публичная и
  // не имеет права разбивать «8 707…» как иностранный «+87 07…».
  assert.equal(formatPhone('87071234567'), '8 707 123 45 67');
});

test('российский номер — тоже «восьмёркой»: у него та же внутренняя форма', () => {
  assert.equal(formatPhone('79161234567'), '8 916 123 45 67');
});

test('иностранные номера показываются с кодом страны и группами', () => {
  assert.equal(formatPhone('998901234567'), '+998 90 123 45 67');   // Узбекистан
  assert.equal(formatPhone('996555510048'), '+996 55 551 00 48');   // Киргизия
  assert.equal(formatPhone('992920105581'), '+992 92 010 55 81');   // Таджикистан
  assert.equal(formatPhone('905317298361'), '+90 531 729 83 61');   // Турция
  assert.equal(formatPhone('447340816486'), '+44 734 081 64 86');   // Великобритания
});

test('номер узнаётся в любой записи — плюс, скобки и пробелы не мешают', () => {
  assert.equal(formatPhone('+998 (90) 123-45-67'), formatPhone('998901234567'));
});

test('идентификатор мессенджера НЕ выдаётся за телефон', () => {
  // В той же колонке вендора лежат 14-15-значные идентификаторы (852 строки).
  // Дорисовать им «+» значило бы сказать человеку, что это номер водителя.
  assert.equal(formatPhone('120400918929618'), '120400918929618');
  assert.equal(formatPhone('[wa_gupshup] KZ.926590227191272'),
               '[wa_gupshup] KZ.926590227191272');
});

test('пустое значение — прочерк, а не «+»', () => {
  assert.equal(formatPhone(''), '—');
  assert.equal(formatPhone(null), '—');
  assert.equal(formatPhone(undefined), '—');
});

test('слишком короткое остаётся как есть — это не номер', () => {
  assert.equal(formatPhone('12345'), '12345');
});

test('склонение чатов и суток', () => {
  assert.equal(pluralChats(1), '1 чат');
  assert.equal(pluralChats(3), '3 чата');
  assert.equal(pluralChats(9), '9 чатов');
  assert.equal(pluralChats(11), '11 чатов');
  assert.equal(pluralDays(1), '1 день');
  assert.equal(pluralDays(31), '31 день');
  assert.equal(pluralDays(32), '32 дня');
  assert.equal(pluralDays(11), '11 дней');
});

test('период считается включительно, как на сервере', () => {
  assert.equal(rangeDays('2026-09-01', '2026-09-01'), 1);
  assert.equal(rangeDays('2026-08-10', '2026-09-08'), 30);
  assert.equal(rangeDays('', ''), 0);
});

test('окно максимальной длины отсчитывается назад от конца', () => {
  assert.equal(shiftDaysBack('2026-09-08', 29), '2026-08-10');
  // Через границу месяца и года — считаем в UTC, а не «минус дни» от локальной
  // даты: перевод часов и пояс браузера иначе дают сдвиг на сутки.
  assert.equal(shiftDaysBack('2026-01-01', 1), '2025-12-31');
});
