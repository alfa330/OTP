# -*- coding: utf-8 -*-
"""Подсказки на пустом экране помощника собираются из статей ЭТОГО человека.

Зашитый в код список («Как оформить возврат депозита водителю?» и ещё два) был
одинаков для всех и ни на что не опирался. У человека, которому такие статьи не
выданы, первое же нажатие приводило к «в доступных вам статьях этого нет» —
подсказка, ведущая в отказ, хуже отсутствующей: она учит, что помощник не
работает.

Здесь проверяется не текст подсказок, а правила, по которым они отбираются.
Правила выведены из боевых данных (замер 04.09.2026: 505 кусков с
подзаголовком, из них 45 сформулированы вопросом), и каждое закрывает
конкретный дефект, который был виден на прогоне по проду:

  * «¶ Как заправляться в приложении?» — знак абзаца из исходного документа;
  * «7. Если текст уже есть в документе» — шаг инструкции, вырванный из порядка;
  * «Что видит читатель» — вопрос без подлежащего, который сам по себе не
    читается;
  * «Информация по Грузовой/Доставка/Шаттл: кто такой грузчик» — приставка
    длиннее вопроса, читается как путь в каталоге.

Отдельно закреплено главное свойство: пустой периметр даёт пустой список, а не
заглушку. Помощнику, которому нечего предложить, положено молчать.
"""

import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from wiki.ai import suggest  # noqa: E402


class FakeCursor:
    """Курсор на двух заготовленных ответах: подзаголовки и популярные статьи.

    Различаются по тексту запроса, а не по порядку вызова: порядок в build()
    может поменяться, и тест не должен от него зависеть.
    """

    def __init__(self, headings=(), popular=()):
        self.headings = list(headings)
        self.popular = list(popular)
        self._rows = []
        self.seen_ids = None

    def execute(self, sql, params=None):
        self.seen_ids = (params or {}).get('ids')
        self._rows = self.headings if 'heading_path' in sql else self.popular

    def fetchall(self):
        return self._rows


def build(headings=(), popular=(), *, ids=(1, 2, 3), limit=3, seed=0):
    return suggest.build(FakeCursor(headings, popular), list(ids),
                         limit=limit, seed=seed)


class SourceTests(unittest.TestCase):
    """Откуда берутся подсказки и в каком порядке."""

    def test_вопрос_автора_статьи_идёт_как_есть(self):
        """Лучший источник — подзаголовок, написанный вопросом: ответ на него в
        статье заведомо есть, и придумывать ничего не нужно."""
        got = build([('Как ИП-водителю перейти на самозанятость?', 'СМЗ', 40)])
        self.assertEqual(got, ['Как ИП-водителю перейти на самозанятость?'])

    def test_невопрос_не_берётся(self):
        """Обычный подзаголовок подсказкой не становится — иначе на пустом
        экране висел бы кусок оглавления."""
        self.assertEqual(build([('Порядок регистрации', 'СМЗ', 40)]), [])

    def test_вопрос_без_знака_тоже_считается(self):
        """Знак «?» авторы ставят не всегда: «Что входит в страховку» — вопрос."""
        got = build([('Что входит в страховку выезда', 'Страхование', 40)])
        self.assertEqual(got, ['Что входит в страховку выезда'])

    def test_добор_из_популярных_статей_когда_вопросов_нет(self):
        """45 вопросительных подзаголовков лежат в 18 статьях из 76 — у узкого
        периметра первый слой может не дать ничего, и экран остался бы пустым."""
        got = build(popular=[('Баллы приоритета', 90)])
        self.assertEqual(got, ['Что нужно знать про «Баллы приоритета»?'])

    def test_вопросы_автора_важнее_добора(self):
        """Слои перемешиваются по отдельности: добор не должен вытеснять
        формулировку автора статьи, которая всегда точнее."""
        got = build([('Как отвязать карту?', 'Транзакции', 50)],
                    [('Все акции', 200)], limit=2)
        self.assertEqual(got[0], 'Как отвязать карту?')


class HygieneTests(unittest.TestCase):
    """Мусор, который приезжал на экран на прогоне по проду."""

    def test_знак_абзаца_срезается(self):
        got = build([('¶ Как заправляться в приложении?', 'Заправка', 30)])
        self.assertEqual(got, ['Как заправляться в приложении?'])

    def test_нумерованный_шаг_инструкции_не_подсказка(self):
        self.assertEqual(build([('7. Как правильно оформить документ', 'Вики', 20)]), [])

    def test_ссылка_внутри_подзаголовка_отбрасывается(self):
        self.assertEqual(
            build([('Как подписать https://docs.google.com/document', 'Sapar', 20)]), [])

    def test_берётся_последний_уровень_пути(self):
        """heading_path — путь через «>», и показывать его целиком нельзя."""
        got = build([('Закрывающие документы > Какие документы подписывают водители?',
                      'ЭДО', 20)])
        self.assertEqual(got, ['Какие документы подписывают водители?'])


class SelfContainedTests(unittest.TestCase):
    """Подсказка обязана читаться сама по себе."""

    def test_обрывок_получает_заголовок_статьи(self):
        """«Сколько это стоит» — стоит что? Без статьи это не вопрос."""
        got = build([('Сколько это стоит', 'Страхование поездок', 20)])
        self.assertEqual(got, ['Страхование поездок: сколько это стоит'])

    def test_вопросительное_слово_не_считается_содержательным(self):
        """В «Что видит читатель» подлежащее только «читатель»; заголовок статьи
        длинный и в приставку не годится, поэтому кандидат выбывает целиком."""
        self.assertEqual(
            build([('Что видит читатель', 'Как наполнять вики: инструкция для СВ', 5)]),
            [])

    def test_длинный_заголовок_в_приставку_не_идёт(self):
        """«Информация по Грузовой/Доставка/Шаттл: кто такой грузчик» читается
        как путь в каталоге, а не как вопрос."""
        self.assertEqual(
            build([('Кто такой грузчик', 'Информация по Грузовой/Доставка/Шаттл', 30)]),
            [])

    def test_самодостаточный_вопрос_приставку_не_получает(self):
        got = build([('Как ИП-водителю перейти на самозанятость?', 'СМЗ', 40)])
        self.assertNotIn(':', got[0])


class ScopeTests(unittest.TestCase):
    """Периметр и устойчивость."""

    def test_пустой_периметр_даёт_пустой_список(self):
        """Помощнику, которому нечего предложить, положено молчать, а не
        показывать заглушку: подсказка, ведущая в отказ, подрывает доверие."""
        self.assertEqual(suggest.build(FakeCursor(), [], limit=3), [])

    def test_запрос_ограничен_периметром(self):
        """Ровно те статьи, что доступны человеку, — и никакие другие."""
        cursor = FakeCursor([('Как отвязать карту?', 'Транзакции', 10)])
        suggest.build(cursor, [11, 22, 33], limit=3)
        self.assertEqual(cursor.seen_ids, [11, 22, 33])

    def test_не_больше_запрошенного(self):
        headings = [(f'Как сделать шаг номер {i}?', 'Статья', 10) for i in range(20)]
        self.assertEqual(len(build(headings, limit=3)), 3)

    def test_повторы_склеиваются(self):
        """Один и тот же подзаголовок встречается в нескольких кусках статьи."""
        same = [('Как отвязать карту?', 'Транзакции', 10)] * 5
        self.assertEqual(build(same, limit=3), ['Как отвязать карту?'])

    def test_один_и_тот_же_человек_видит_одно_и_то_же(self):
        """Подсказки, меняющиеся в момент закрытия панели, читаются как
        случайные: набор закреплён за парой «человек + день»."""
        headings = [(f'Как выполнить действие {i}?', 'Статья', 10) for i in range(12)]
        self.assertEqual(build(headings, seed=777), build(headings, seed=777))

    def test_разным_людям_подсказки_различаются(self):
        headings = [(f'Как выполнить действие {i}?', 'Статья', 10) for i in range(12)]
        variants = {tuple(build(headings, seed=s)) for s in range(8)}
        self.assertGreater(len(variants), 1, 'все получили один и тот же набор')


class WiringTests(unittest.TestCase):
    """Проводка: кто просит подсказки, а кто нет."""

    def test_шарик_не_платит_за_подсказки(self):
        """Проба шарика дёргает /ai/status на каждой загрузке портала у всех,
        а пустой экран чата не рисует. Считать подсказки там незачем."""
        orb = (ROOT / 'src' / 'components' / 'assistant' / 'AssistantOrb.jsx').read_text(
            encoding='utf-8')
        self.assertIn('/ai/status', orb)
        self.assertNotIn('suggest', orb)

    def test_панель_просит_подсказки_и_не_держит_зашитого_списка(self):
        panel = (ROOT / 'src' / 'components' / 'assistant' / 'AssistantPanel.jsx').read_text(
            encoding='utf-8')
        self.assertIn('withSuggestions: true', panel)
        self.assertIn('chat.suggestions', panel)
        for gone in ('Как оформить возврат депозита водителю?',
                     'Какие документы нужны для подключения к парку?'):
            self.assertNotIn(gone, panel, 'зашитый список подсказок вернулся')

    def test_пустой_список_прячет_блок_целиком(self):
        panel = (ROOT / 'src' / 'components' / 'assistant' / 'AssistantPanel.jsx').read_text(
            encoding='utf-8')
        self.assertIn('!!chat.suggestions.length', panel)


if __name__ == '__main__':
    unittest.main()
