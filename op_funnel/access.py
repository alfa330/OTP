# -*- coding: utf-8 -*-
"""Права раздела «Воронка ОП». Чистая логика: ни базы, ни Flask.

Модуль не импортирует ни `database`, ни `flask` — так его берут в тест напрямую
(импорт `database` открывает пул к боевой базе; та же причина у `cdr/access.py`,
`parcels/access.py` и `crm/access.py`). Из своего пакета берётся только
`schema.DIRECTION_CODES`: `schema.py` — это строки DDL и ни одного `import`, а
список направлений обязан быть один на пакет. Иначе пятое направление появится
в схеме и не появится в правах, и новый таб будет молча пустым.

Что модуль ждёт в `ctx` (готовит `queries.load_access_context`)
--------------------------------------------------------------
    user_id, role, department_id, department_code
    headed_department_ids, headed_department_codes   возглавляемые отделы
    supervisor_group_ids                             группы СВ НА ДАТУ
    group_directions                                 {group_id: код модели группы}
    direction_code                                   своё направление, если задано

Кому открыт
-----------
    глобальный админ            весь раздел, все четыре направления
    глава отдела продаж         весь раздел, все четыре направления
    супервайзер ОП              только направления своих групп
    оператор, стажёр, тренер    нет

Почему оператору нет. В `op_funnel_leads` лежат `full_name` и `phone` водителей
за весь период (30 000 лидов Потока-1 за 01.08–11.09), а экран — это разбор
работы коллег: у кого дозвон ниже, у кого отказов больше, кто не дошёл до
половины базы. Это инструмент руководителя, а не личный кабинет; свои цифры
оператор смотрит в «Моих часах» и «Моих оценках». Тренеру закрыто по той же
причине, по которой ему закрыты «Обращения» и «Посылки», — живые персональные
данные не его дело.

Незнакомая роль сводится к `operator` и в раздел не попадает. Это не только
защита от опечатки: CHECK на `users.role` пускает ещё `hr_manager`,
`accounting_manager` и `marketing_manager` — рядовых сотрудников Бухгалтерии, HR
и Маркетинга. Воронка продаж им не нужна, и «закрыто по умолчанию» здесь
правильная сторона ошибки.

Отдельного QR-гейта раздел не заводит осознанно — ровно как «Касания». Ключ
портала (bot_schedule2: sensitive-access) закрывает раздел от РОЛИ «оператор», а
её здесь нет вовсе: супервайзер — это как раз тот, кто QR подтверждает, а главе
отдела и админу подтверждать не у кого. Второй гейт был бы декорацией, а лишний
QR на экране человек не различит.

Граница «глава отдела ≠ глобальный админ» — действующая семантика портала
(коммит b35d76b): назначение главой ЗАМЕНЯЕТ базовую роль и режет периметр своим
отделом. Поэтому все четыре направления даёт не «любой глава», а глава именно
ОП: СВ отдела продаж, которого назначили главой СЗоВ, остаётся на своих группах.

Четыре направления, и СВ видит только свои
------------------------------------------
Это главное отличие от «Касаний», где раздел принадлежал отделу целиком и
внутренних границ не имел. Здесь четыре супервайзера ведут четыре разных
отчётности (задачи #301, #302, #303, #305), и чужая им не нужна и не полезна:
формулы разные, а «% дозвона» Верификатора не существует вовсе.

Направление СВ выводится из его ГРУПП, а не из `users.direction_id`:
переименование направления в портале обнуляет `direction_id` у людей, а код
модели живёт на группе (то же решение, что в шапке `schema.py`). Сами группы —
производное от `group_supervisor_memberships` на дату, потому что связка «СВ ↔
группа» с 2026-07-14 единственная точка правды, а `users.supervisor_id` лишь её
зеркало.

Две ловушки этого вывода:

* Одно направление приходит несколькими группами: 14 «Поток» и 38 «Поток 2» —
  это `op_potok` со `stream_type` 1 и 2. Поэтому набор схлопывается через
  множество, а порядок берётся из `DIRECTION_CODES`, а не из словаря: иначе
  табы прыгали бы местами от порядка id групп.
* Группа СВ может быть не из ОП вовсе (модель `operator`, `tez_op`). Такие коды
  отфильтровываются по `DIRECTION_CODES`, и раздел не открывает СВ СЗоВ таб,
  которого у него нет.

Нормы правит руководитель
-------------------------
`can_edit_targets` не даёт супервайзеру править `op_funnel_targets`, и это не
недосмотр. Норма — это обязательство («20 дозвонов в час»), по выполнению
которого оценивают саму группу: поставить себе норму значит поставить себе
оценку. Пороги раскраски (`green_from`, `amber_from`) лежат в той же таблице и
живут по тому же правилу — «с какого процента работа считается сделанной» это
то же обязательство, а не настройка экрана, поэтому отдельного права «на цвета»
раздел не заводит.

Прошлое от правки нормы не едет: план записан числом в `op_funnel_daily`
(`plan_reached`, `plan_agreed`). Но следующий `force`-пересчёт этих суток
посчитает план уже по новой норме и положит разницу в `op_funnel_drift` — вот
почему право на норму и право на пересчёт стоит держать в одних руках, а не
раздавать по отдельности.
"""

from .schema import DIRECTION_CODES

# Роли, которые вообще существуют в портале. Остальное normalize_role сводит к
# 'operator' — см. шапку.
_KNOWN_ROLES = ('super_admin', 'admin', 'sv', 'supervisor', 'trainer', 'operator', 'trainee')

# Написания одной и той же роли. Повтор `database.ROLE_ALIASES` (там их четыре),
# потому что импортировать `database` ради словаря нельзя: CHECK на users.role
# пускает и 'sv', и 'supervisor', и оба написания в базе живые.
_ROLE_ALIASES = {
    'supervisor': 'sv',
    'superadmin': 'super_admin',
    'super-admin': 'super_admin',
    'super admin': 'super_admin',
}

# Отдел, которому принадлежит раздел. Один код, а не список: воронка — отчётность
# отдела продаж (367), и делить её больше не с кем.
SECTION_DEPARTMENT_CODE = 'op'

# Роли внутри отдела, которым раздел открыт. 'supervisor' оставлен рядом с 'sv'
# намеренно: список читают глазами, и без второго написания он выглядит как
# ошибка, хотя normalize_role уже свёл его к 'sv'.
_SECTION_ROLES = ('sv', 'supervisor', 'admin', 'super_admin')

_SUPERVISOR_ROLES = ('sv', 'supervisor')


def normalize_role(role):
    value = str(role or '').strip().lower()
    value = _ROLE_ALIASES.get(value, value)
    return value if value in _KNOWN_ROLES else 'operator'


def _codes(values):
    return {str(code).strip().lower() for code in (values or []) if code}


def _direction(value):
    """Код направления или '' — если это не направление воронки.

    Через эту воронку проходят и параметр из URL, и код модели группы. Проверка
    по `DIRECTION_CODES` нужна обеим: 'op_potok ' с пробелом и 'tez_op' должны
    отпасть здесь, а не превратиться в пустую выборку в SQL.
    """
    code = str(value or '').strip().lower()
    return code if code in DIRECTION_CODES else ''


def is_department_head(ctx):
    return bool(ctx.get('headed_department_ids'))


def is_global_admin(ctx):
    """Админ, не привязанный к одному отделу.

    super_admin — всегда; admin — пока он не назначен главой отдела, иначе глава
    СЗоВ читал бы воронку продаж со всеми телефонами водителей.
    """
    role = normalize_role(ctx.get('role'))
    if role == 'super_admin':
        return True
    return role == 'admin' and not is_department_head(ctx)


def is_supervisor(ctx):
    return normalize_role(ctx.get('role')) in _SUPERVISOR_ROLES


def belongs_to_sales(ctx):
    """Человек в отделе продаж — своим членством или как его глава."""
    if SECTION_DEPARTMENT_CODE in _codes(ctx.get('headed_department_codes')):
        return True
    return str(ctx.get('department_code') or '').strip().lower() == SECTION_DEPARTMENT_CODE


def heads_sales(ctx):
    """Глава именно отдела продаж, а не «какой-нибудь глава».

    Отдельно от `is_department_head`, потому что на этой разнице держится
    видимость всех четырёх направлений: глава СЗоВ, который сам числится в ОП,
    попадает в раздел (belongs_to_sales), но чужие направления ему не положены.
    """
    return is_department_head(ctx) and SECTION_DEPARTMENT_CODE in _codes(
        ctx.get('headed_department_codes'))


def can_open_section(ctx):
    """Пускать ли в раздел. Проверяется на КАЖДОМ роуте, а не только в меню:
    спрятанный пункт доступом не является, раздел открывается прямым адресом."""
    if is_global_admin(ctx):
        return True
    if not belongs_to_sales(ctx):
        return False
    if is_department_head(ctx):
        return True
    return normalize_role(ctx.get('role')) in _SECTION_ROLES


def visible_directions(ctx):
    """Направления, которые пользователь вправе открыть. Порядок стабильный.

    Админ и глава ОП — все четыре. Супервайзер — только те, что дают его
    группы: пересечение «мои группы на дату» с картой «группа → код модели».

    Пересечение делается ЗДЕСЬ, а не принимается на веру из `group_directions`:
    карта групп — справочник, а `supervisor_group_ids` — право. Если queries
    однажды начнёт отдавать карту целиком (так дешевле одним запросом), раздел
    от этого не откроет чужие направления.

    Ключи карты сравниваются строками: словарь мог приехать через JSON (кеш
    контекста, лог, тест с фикстурой), а там int-ключи становятся строками, и
    прямое `in` тихо не находило бы ни одной группы.

    Если групп нет вовсе — берём своё направление из карточки. Это не поблажка:
    у СВ нулевой список бывает штатно (группу архивировали, членство закрыли
    датой, человека только что перевели), а пустой экран он объяснить не сможет
    и пойдёт к админу. Периметр при этом не расширяется — одно своё направление,
    а не все четыре.
    """
    if not can_open_section(ctx):
        return ()
    if is_global_admin(ctx) or heads_sales(ctx):
        return DIRECTION_CODES
    mine = {str(group_id).strip() for group_id in (ctx.get('supervisor_group_ids') or [])
            if group_id is not None}
    found = set()
    for group_id, model_code in (ctx.get('group_directions') or {}).items():
        if str(group_id).strip() in mine:
            code = _direction(model_code)
            if code:
                found.add(code)
    if not found:
        own = _direction(ctx.get('direction_code'))
        if own:
            found.add(own)
    return tuple(code for code in DIRECTION_CODES if code in found)


def can_see_direction(ctx, direction_code):
    """Сужение по направлению делает РОУТ, а не фронт: `?direction=op_osnova`
    подставляется руками, и без этой проверки СВ Верификаторов прочитал бы
    «Основу» мимо своих табов. Неизвестный код — отказ, а не «покажем всё»."""
    code = _direction(direction_code)
    return bool(code) and code in visible_directions(ctx)


def can_sync(ctx):
    """Запускать выгрузку за период.

    Право то же, что на чтение: выкачка — не привилегия, а способ увидеть
    данные, которых ещё нет (та же формулировка, что в `cdr/access.py`).
    Отдельная функция всё же нужна: у действия своя цена — 30 000 лидов Потока-1
    за 01.08–11.09 это шестьдесят страниц по 500, amoCRM ходит с токеном на 40
    минут, — и сузить его завтра можно будет здесь, а не по всем роутам.

    Границу «чьи сутки перечитывать» держит `can_see_direction` в роуте:
    направление у ручки обязательное, и СВ не запустит пересчёт чужого таба.
    """
    return can_open_section(ctx)


def can_export(ctx):
    """Скачать книгу xlsx за период.

    Как чтение: в файле ровно то, что на экране, и отдельное право было бы
    фикцией — кто видит цифры, тот их и перепишет. Названо отдельной функцией
    потому, что выгрузка уносит телефоны водителей ЗА пределы портала, и если
    понадобится журналировать или сузить до главы отдела — правка будет одна,
    здесь, а не в роуте и в меню.
    """
    return can_open_section(ctx)


def can_map_operators(ctx):
    """Править `op_funnel_operator_map`: «кто это в портале», отказ сопоставлять.

    Супервайзер обязан это делать сам, и это не послабление: единственный, кто
    знает, что СРМ-«Кузембаева Аяулым» — это портальная «Кузембекова Аяулым», а
    «Сарсенбаева Эльдана» — «Елдана Сарсенбаева», — её руководитель. Ошибка
    здесь молчаливая (цифры окажутся в чужой строке и снаружи это не видно),
    поэтому подтверждает человек, а похожесть остаётся подсказкой.

    «Только своих» проверить в этой функции нечем — строки на входе нет. Границу
    держит роут: у строки карты есть `hint_direction`, и он проходит через
    `can_see_direction`.
    """
    return can_open_section(ctx)


def can_edit_targets(ctx):
    """Править нормы, таргеты и пороги раскраски — админ и глава ОП.

    Супервайзеру нельзя: норма это обязательство, по которому оценивают его же
    группу, а не настройка экрана (разбор — в шапке модуля). Чтение норм правом
    не ограничено вовсе: не зная плана, цифру выполнения прочитать нельзя.
    """
    return is_global_admin(ctx) or heads_sales(ctx)


def can_import_manual(ctx):
    """Грузить ручную выгрузку (`op_funnel_manual_rows`).

    Тикеты Верификаторов и время их обработки из API не берутся: партнёрской
    ручки обращений нет, а админский `/api/admin/list-requests/list` времени
    обработки не отдаёт (проверено по свагеру 11.09.2026). Значит файл грузит
    тот же человек, который и сегодня делает его руками, — супервайзер.

    К Верификатору право не привязано: строка ручной выгрузки несёт и `work_hours`
    (`hours_source = 'manual'`), а это нужно любому направлению, у которого
    статусов телефона нет.

    СВ без видимых направлений отсекается здесь, а не в роуте: грузить файл
    некуда, и ошибка «направление не ваше» на 30-м мегабайте multipart — плохой
    способ это сообщить.
    """
    if not can_open_section(ctx):
        return False
    if is_global_admin(ctx) or heads_sales(ctx):
        return True
    return bool(visible_directions(ctx))


def capabilities(ctx):
    """Сводка для фронта: кнопки и табы рисуются по ней, а не по роли.

    Одно место правды — правило меняется здесь, а не в трёх местах интерфейса.
    `directions` отдаём списком (не кортежем): это же значение уходит в JSON
    ответа `/meta`, и фронт строит по нему табы, а не по своему списку кодов.
    """
    return {
        'can_open': can_open_section(ctx),
        'can_sync': can_sync(ctx),
        'can_export': can_export(ctx),
        'can_map_operators': can_map_operators(ctx),
        'can_edit_targets': can_edit_targets(ctx),
        'can_import_manual': can_import_manual(ctx),
        'directions': list(visible_directions(ctx)),
        'is_global_admin': is_global_admin(ctx),
        'is_department_head': is_department_head(ctx),
        'is_supervisor': is_supervisor(ctx),
    }
